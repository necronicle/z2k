#!/bin/sh
# tests/test_fake_fooling.sh — хрупкий фулинг не бывает у фейка единственным.
#
# ЧТО ЗА ПРАВИЛО. Мануал nfqws2 (docs/manual.md, «standard fooling»):
#   «Прямым фейкам всегда необходимо искажение какой-либо информации в
#    заголовках пакета, чтобы пейлоад не попал в серверное приложение, иначе
#    это поломает соединение.»
#
# Но не всякий фулинг срабатывает всегда. Два из них условны:
#
#   tcp_ts — мануал: «работает только если уже есть timestamp option». А в
#            Windows опция TCP timestamps ВЫКЛЮЧЕНА ПО УМОЛЧАНИЮ (в macOS,
#            iOS, Linux, Android — включена). Для такого клиента это не
#            фулинг, а ноль: движок не находит опцию и идёт дальше.
#   badsum — роняет пакет только там, где контрольную сумму проверяет сетевая
#            карта получателя. Зависит от сервера.
#
# Замер 11.09.2026 (netns с tcp_timestamps=0, клиент шлёт настоящий
# ClientHello, сервер записывает, что до него доехало):
#
#   без фулинга вовсе     метки выкл -> до сервера дошёл ФЕЙК
#   только tcp_ts=-1000   метки выкл -> до сервера дошёл ФЕЙК
#   только tcp_ts=-1000   метки ВКЛ  -> дошло настоящее
#   tcp_ts + tcp_md5      метки выкл -> дошло настоящее
#   tcp_ts + tcp_md5      метки ВКЛ  -> дошло настоящее
#
# Пришло из поля: человек включил метки времени в Windows — и обход заработал.
#
# ИНВАРИАНТ: если у фейка есть tcp_ts или badsum, у него обязан быть и второй
# фулинг, не зависящий ни от клиента, ни от сетевой карты сервера.
#
# Сознательно НЕ проверяется: фейк без явного фулинга вообще — таким генератор
# дописывает fool=z2k_dynamic_ttl (TTL минус один). Он от клиента не зависит и
# молча не исчезает, но запас там ровно один хоп; отдельной меры пока нет.
# POSIX sh.

HERE=$(cd "$(dirname "$0")/.." && pwd)
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

AWK_SCAN="$HERE/tests/lib/fake_fooling.awk"
[ -f "$AWK_SCAN" ] || { printf '[FAIL] нет %s\n' "$AWK_SCAN"; exit 1; }

# Сам сканер обязан уметь находить нарушение — иначе зелёный цвет ничего не
# значит. Гоняем его по заведомо плохой строке перед настоящей проверкой.
_probe=$(printf '%s\n' '--lua-desync=fake:payload=tls_client_hello:dir=out:blob=x:tcp_ts=-1000' \
         | awk -v FRAGILE=tcp_ts -f "$AWK_SCAN")
if [ -n "$_probe" ]; then
    ok "сканер видит нарушение на заведомо плохой строке"
else
    no "сканер СЛЕП — все проверки ниже бессмысленны"
    printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
    exit 1
fi

for _fr in tcp_ts badsum; do
    for f in "$HERE/strats_new2.txt" "$HERE/lib/config_official.sh"; do
        [ -f "$f" ] || { no "нет файла $f"; continue; }
        _bad=$(awk -v FRAGILE="$_fr" -f "$AWK_SCAN" "$f")
        if [ -z "$_bad" ]; then
            ok "$(basename "$f"): $_fr нигде не единственный фулинг"
        else
            no "$(basename "$f"): фейк, где $_fr единственный фулинг:"
            printf '%s\n' "$_bad" | sed 's/^/        /'
        fi
    done
done

# Первые плечи всех трёх TCP-пулов — те, на которых сидят все по умолчанию.
for _pool in rkn_tcp yt_tcp gv_tcp; do
    _arm1=$(awk -v k="key=$_pool" '$0 ~ k {print; exit}' "$HERE/strats_new2.txt" \
            | tr ' ' '\n' | grep 'lua-desync=fake' | grep 'strategy=1$' | head -1)
    case "$_arm1" in
        *tcp_md5*) ok "$_pool плечо 1: фейк гасится независимо от клиента и от сервера" ;;
        '') no "$_pool плечо 1: фейк не найден — изменился формат пула?" ;;
        *)  no "$_pool плечо 1: фулинг зависит от клиента или от сервера: $_arm1" ;;
    esac
done

# Фейк подстановки имени (механизм 16 КБ) живёт не в пуле, а в генераторе.
_sni=$(grep -n 'blob=z2k_ch:optional' "$HERE/lib/config_official.sh" | head -1)
case "$_sni" in
    *tcp_md5*|*badseq*) ok "16 КБ: у фейка подстановки имени есть надёжный фулинг" ;;
    '') no "16 КБ: фейк подстановки имени не найден" ;;
    *)  no "16 КБ: у фейка подстановки имени только условный фулинг" ;;
esac

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
