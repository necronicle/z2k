#!/bin/sh
# tests/test_upstream_404_not_an_error.sh — отсутствие файла у апстрима не должно
# выглядеть как поломка нашей инфраструктуры.
#
# ЧТО СЛУЧИЛОСЬ. ru-gaming-blocklist перечисляет в индексе игры, для которых
# файла нет: Fallout76_AWS, GearsOfWar, MagicTheGathering — 404 на всех
# зеркалах, проверено. Для этого случая давно написано сообщение «у апстрима
# такого файла нет», но печаталось оно только при ЕДИНОГЛАСИИ: если хоть один
# слой ответил не-404 (таймаут, непрогретый кэш jsdelivr, моргнувший gh-proxy),
# признак сбрасывался и в журнал уходило «all mirrors failed».
#
# Дальше это всплывало в диагностике под «errors across all logs», человек видел
# поломку там, где её нет, и шёл с ней в поддержку. Поле 2026-08-24.
#
# Правило теперь такое: 404 от АВТОРИТЕТНОГО источника (сквозной проход через
# наш VPS или прямой raw.githubusercontent.com) — сам по себе доказательство
# отсутствия файла. Таймаут соседнего зеркала к доказательству ничего не
# добавляет и отменять его не должен.
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
assert_eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }
ROOT=$(cd "$(dirname "$0")/.." && pwd)
F="$ROOT/files/z2k-update-lists.sh"

# --- 1. Признак заведён и отделён от «все ответили 404» -----------------------
assert_eq "авторитетный 404 отслеживается отдельно" "1" \
    "$(grep -c 'Z2K_FETCH_AUTH_404=0' "$F")"

# --- 2. Оба авторитетных слоя его выставляют ---------------------------------
# Слой 0 — сквозной проход через VPS, и прямой raw. Оба разговаривают с
# raw.githubusercontent.com, поэтому их 404 окончателен.
assert_eq "выставляют ровно два слоя" "2" \
    "$(grep -c 'Z2K_FETCH_AUTH_404=1' "$F")"

# --- 3. Зеркала-пересказчики авторитетными НЕ считаются -----------------------
# jsdelivr и gh-proxy отдают 404 и когда файл есть: кэш не прогрет, прокси
# моргнул. Их ответ не должен объявлять файл отсутствующим.
_mirror_auth=$(awk '/jsdelivr" \]|gh_proxy" \]/,/fi/' "$F" | grep -c 'Z2K_FETCH_AUTH_404=1')
assert_eq "jsdelivr и gh-proxy авторитетными не считаются" "0" "${_mirror_auth:-0}"

# --- 4. Решение по сообщению учитывает оба признака ---------------------------
assert_eq "мягкое сообщение печатается и по авторитетному 404" "1" \
    "$(grep -c 'Z2K_FETCH_ALL_404:-0}" = "1" \] || \[ "${Z2K_FETCH_AUTH_404:-0}" = "1"' "$F")"

# --- 5. Текст остался человеческим -------------------------------------------
assert_eq "сообщение объясняет, а не пугает" "1" \
    "$(grep -c 'у апстрима такого файла нет (404), пропускаю' "$F")"

# --- 6. Поведение целиком: авторитетный 404 переживает моргнувшее зеркало -----
# Воспроизводим решение тем же выражением, что стоит в скрипте.
verdict() {
    Z2K_FETCH_ALL_404="$1"; Z2K_FETCH_AUTH_404="$2"
    if [ "${Z2K_FETCH_ALL_404:-0}" = "1" ] || [ "${Z2K_FETCH_AUTH_404:-0}" = "1" ]; then
        printf 'мягко'
    else
        printf 'ошибка'
    fi
}
assert_eq "все 404 → мягко"                          "мягко"  "$(verdict 1 1)"
assert_eq "raw дал 404, зеркало моргнуло → мягко"    "мягко"  "$(verdict 0 1)"
assert_eq "никто 404 не дал → честная ошибка"        "ошибка" "$(verdict 0 0)"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
