#!/bin/sh
# tests/test_geosite_rkn_asset.sh — по умолчанию берём короткий список РКН.
#
# ЗАМЕР, РАДИ КОТОРОГО ЭТО СДЕЛАНО. 2026-08-12, два роутера с ПОБАЙТОВО
# одинаковой строкой запуска nfqws2 (30794 байта). Отличался ровно один файл —
# extra_strats/TCP/RKN/List.txt:
#
#   ru-blocked.txt        74 720 доменов → nfqws2  16 720 КБ RSS
#   ru-blocked-all.txt 1 369 008 доменов → nfqws2 177 436 КБ RSS
#
# ~127 байт памяти на домен; полный список стоит +157 МБ. На гигабайтном
# роутере это 18% всей памяти в одном процессе, и nfqws2 становится там
# крупнейшим потребителем — больше xray.
#
# КАК БЫЛО. Список выбирался по объёму памяти: ≥900 МБ → полный. Правило
# родилось из полевого случая, где полный список ронял nfqws2 на 489-МБ
# роутере, то есть решало задачу «не упасть», а не «уместно ли». К моменту
# замера апстрим вырос почти вдвое против того, под что порог калибровали.
#
# ЧТО ОХРАНЯЕТСЯ ЗДЕСЬ:
#   1. по умолчанию — короткий список, независимо от железа;
#   2. явная просьба человека (Z2K_GEOSITE_RKN_ASSET) сильнее умолчания;
#   3. страж усадки пропускает смену класса списка — иначе у тех, кому большой
#      уже приехал, он никогда бы не сменился на короткий.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
GS="$ROOT/files/z2k-geosite.sh"

[ -f "$GS" ] || { printf '[FAIL] нет %s\n' "$GS"; exit 1; }

TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

# --- 1. Исполняем НАСТОЯЩИЙ выбор из скрипта ----------------------------------
#
# Не грепаем: греп зелёный и на мёртвой ветке. Берём функцию как есть.
{
    printf 'log() { :; }\n'
    awk '/^pick_rkn_asset\(\) \{/,/^}/' "$GS"
    printf 'echo "DEFAULT=$(pick_rkn_asset)"\n'
    printf 'Z2K_GEOSITE_RKN_ASSET=ru-blocked-all.txt; echo "EXPLICIT=$(pick_rkn_asset)"\n'
} > "$TMP/pick.sh"
OUT=$(sh "$TMP/pick.sh" 2>&1)

case "$OUT" in
    *"DEFAULT=ru-blocked.txt"*) ok "по умолчанию берётся короткий список" ;;
    *) no "умолчание" "ru-blocked.txt" "$(printf '%s' "$OUT" | grep DEFAULT=)" ;;
esac
case "$OUT" in
    *"EXPLICIT=ru-blocked-all.txt"*) ok "явная просьба человека сильнее умолчания" ;;
    *) no "явное указание" "ru-blocked-all.txt" "$(printf '%s' "$OUT" | grep EXPLICIT=)" ;;
esac

# --- 2. Выбора по железу больше нет -------------------------------------------
#
# Пока функция читает free/meminfo, умолчание снова становится функцией от
# объёма планок памяти — ровно то, от чего уходим.
_fn=$(awk '/^pick_rkn_asset\(\) \{/,/^}/' "$GS")
case "$_fn" in
    *free*|*meminfo*|*THRESHOLD*)
        no "выбор не зависит от объёма памяти" "нет чтения памяти в pick_rkn_asset" \
           "функция снова смотрит на железо" ;;
    *) ok "выбор не зависит от объёма памяти роутера" ;;
esac
# И мёртвая переменная порога не должна остаться висеть.
if grep -qE '^RAM_THRESHOLD_MB=' "$GS"; then
    no "порог удалён" "нет RAM_THRESHOLD_MB" "переменная осталась"
else
    ok "переменная порога удалена, а не оставлена мёртвой"
fi

# --- 3. Путь на понижение открыт ----------------------------------------------
#
# Без этого правка бесполезна для тех, у кого большой список УЖЕ стоит: страж
# усадки отвергает любой список меньше 80% от нынешнего, а короткий — это ~5%
# от полного. Смена класса обязана страж обходить.
_guard=$(awk '/asset_marker="/,/^    fi$/' "$GS")
case "$_guard" in
    *'"$prev_asset" = "$asset"'*)
        ok "страж усадки срабатывает только внутри одного класса списка" ;;
    *)
        no "страж пропускает смену класса" 'сравнение prev_asset = asset' \
           "условие изменилось — понижение может залипнуть" ;;
esac
# Маркер класса обязан записываться, иначе сравнение выше всегда пустое.
if grep -q 'printf .%s\\n. "\$asset" > "\$asset_marker"' "$GS"; then
    ok "класс применённого списка запоминается рядом с целью"
else
    no "запись маркера класса" 'asset > asset_marker' "не найдена"
fi

# --- 4. Документация не расходится с кодом ------------------------------------
#
# Прошлый раз разошлась дважды: в шапке стоял порог 400 при коде 900 и «~700k
# доменов» при фактических 1,37 млн. По такому комментарию делают неверный
# вывод о том, кому что достанется.
case "$(sed -n '1,60p' "$GS")" in
    *"400 MB total RAM"*)
        no "в шапке нет устаревшего порога" "упоминания 400 MB убраны" "осталось" ;;
    *) ok "устаревший порог из шапки убран" ;;
esac
case "$(sed -n '1,60p' "$GS")" in
    *"1 369 008"*) ok "в шапке указан фактически измеренный размер списка" ;;
    *) no "фактический размер в шапке" "1 369 008 доменов" "нет" ;;
esac
case "$(sed -n '1,60p' "$GS")" in
    *"Z2K_GEOSITE_RKN_ASSET"*) ok "в шапке назван способ получить полный список" ;;
    *) no "способ включить полный список" "Z2K_GEOSITE_RKN_ASSET" "не назван" ;;
esac

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
