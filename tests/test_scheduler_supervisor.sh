#!/bin/sh
# tests/test_scheduler_supervisor.sh — надзиратель не форкает планировщик впустую.
#
# ЧТО СЛУЧИЛОСЬ В ПОЛЕ (роутер пользователя, 2026-08-09 12:56–12:58):
#
#   [supervisor] scheduler exited (rc=0) — respawning in 10s
#   z2k-scheduler already running pid 2983
#   … и так каждые десять секунд, пока чужой процесс не умер сам
#
# Надзиратель крутит «запустить планировщик; sleep 10» вечно. Планировщик,
# увидев в pidfile живой pid, печатал «already running» и выходил С КОДОМ 0 —
# то есть «работу уже делает кто-то другой» было для надзирателя неотличимо от
# «мой планировщик отработал». Он респавнил снова и снова.
#
# Как в это состояние попадают: OOM убивает надзирателя, планировщик остаётся
# сиротой, NDM-хук поднимает стек заново, новый надзиратель натыкается на
# сироту. Периодические задачи при этом ИДУТ (сирота тикает), поэтому снаружи
# видны только форк-шторм и залитый лог — и никакого симптома, по которому это
# нашли бы раньше.
#
# Тест ИСПОЛНЯЕТ настоящий init-скрипт с подставным планировщиком и считает,
# сколько раз тот был запущен. Грепом это не проверить: вопрос не «есть ли
# нужная ветка в коде», а «сколько форков в единицу времени».
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
INIT="$ROOT/files/init.d/S99z2k-scheduler"
SCHED="$ROOT/files/z2k-scheduler.sh"
for f in "$INIT" "$SCHED"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

TMP=$(mktemp -d) || exit 1
cleanup() {
    [ -f "$TMP/sup.pid" ] && kill "$(cat "$TMP/sup.pid")" 2>/dev/null
    rm -rf "$TMP"
}
trap cleanup EXIT INT TERM

# Живой «чужой» процесс: спим долго, но не вечно, чтобы не оставить хвост.
sleep 600 &
FOREIGN=$!
echo "$FOREIGN" > "$TMP/sched.pid"

# --- 1. Планировщик отличает «уже запущен» кодом возврата ----------------------
#
# Ровно 3, а не 0 и не 1: 0 неотличим от штатного завершения, 1 — от ошибки
# запуска, на которую респавн как раз нужен.
Z2K_SCHED_PIDFILE="$TMP/sched.pid" sh "$SCHED" >/dev/null 2>&1
_rc=$?
if [ "$_rc" = "3" ]; then
    ok "планировщик при живом чужом pid выходит с кодом 3"
else
    no "планировщик выходит с кодом 3" "3" "$_rc"
fi

# --- 2. Надзиратель на код 3 НЕ респавнит --------------------------------------
#
# Подставной планировщик отмечает каждый свой запуск и возвращает 3. Ждём
# тринадцать секунд: со старым поведением (sleep 10 и снова) отметок было бы
# две, с правильным — одна.
cat > "$TMP/stub.sh" <<'STUB'
#!/bin/sh
echo x >> "$Z2K_SCHED_CALLS"
exit 3
STUB
chmod +x "$TMP/stub.sh"

Z2K_SCHED_CALLS="$TMP/calls"; : > "$Z2K_SCHED_CALLS"; export Z2K_SCHED_CALLS
env Z2K_SCHED_SCRIPT="$TMP/stub.sh" \
    Z2K_SCHED_PIDFILE="$TMP/sched.pid" \
    Z2K_SCHED_SUP_PIDFILE="$TMP/sup.pid" \
    Z2K_SCHED_LOG="$TMP/sched.log" \
    Z2K_SCHED_ADOPT_POLL=1 \
    sh "$INIT" start >/dev/null 2>&1

sleep 13
_calls=$(wc -l < "$TMP/calls" 2>/dev/null | tr -d ' ')
if [ "${_calls:-0}" -le 1 ]; then
    ok "за 13 секунд планировщик запущен один раз, а не респавнится (запусков: ${_calls:-0})"
else
    no "надзиратель не респавнит на код 3" "1" "${_calls:-0} — форк-шторм вернулся"
fi

# Сказано об этом один раз, а не в каждом цикле: залитый лог был половиной беды.
_said=$(grep -c 'жду его завершения' "$TMP/sched.log" 2>/dev/null | tr -d ' ')
if [ "${_said:-0}" = "1" ]; then
    ok "об ожидании сказано ровно один раз"
else
    no "об ожидании сказано один раз" "1" "${_said:-0}"
fi

# И ни одной строки про респавн: её появление и есть исходный дефект.
if grep -q 'respawning in 10s' "$TMP/sched.log" 2>/dev/null; then
    no "нет строк про респавн" "ни одной" "$(grep -c 'respawning' "$TMP/sched.log") шт."
else
    ok "в логе нет ни одной строки про напрасный респавн"
fi

# --- 3. Когда чужой процесс умирает, надзиратель подхватывает работу -----------
#
# Уйти совсем было бы не лучше шторма: после смерти сироты периодические задачи
# встали бы до следующего регена NDM. Надзиратель обязан дождаться и запустить
# свой планировщик.
kill "$FOREIGN" 2>/dev/null
rm -f "$TMP/sched.pid"
sleep 4
_calls2=$(wc -l < "$TMP/calls" 2>/dev/null | tr -d ' ')
if [ "${_calls2:-0}" -gt "${_calls:-0}" ]; then
    ok "после смерти чужого процесса работа подхвачена (запусков стало ${_calls2})"
else
    no "работа подхвачена после смерти чужого процесса" "больше ${_calls:-0}" "${_calls2:-0}"
fi

# И подхват не должен обернуться новым штормом. Исчезнувший pidfile когда-то
# делал ожидание циклом без паузы: 1431 запуск за четыре секунды при опросе в
# одну. Верхняя граница считается от периода опроса, а не выдумана.
if [ "${_calls2:-0}" -le 8 ]; then
    ok "подхват идёт с паузой, а не вхолостую (за 4 с при опросе 1 с: ${_calls2})"
else
    no "подхват идёт с паузой" "не больше 8 за 4 с" "${_calls2} — цикл без паузы"
fi

kill "$(cat "$TMP/sup.pid" 2>/dev/null)" 2>/dev/null

# --- 4. Дефолты не изменились --------------------------------------------------
#
# Переопределяемость путей — только ради этого теста. На роутере переменные
# никто не задаёт, и значения обязаны остаться прежними.
_bad=0
for _pair in \
    'Z2K_SCHED_SCRIPT:-/opt/zapret2/z2k-scheduler.sh' \
    'Z2K_SCHED_PIDFILE:-/var/run/z2k-scheduler.pid' \
    'Z2K_SCHED_SUP_PIDFILE:-/var/run/z2k-scheduler-sup.pid' \
    'Z2K_SCHED_LOG:-/opt/var/log/z2k-scheduler.log'; do
    grep -q "\${$_pair}" "$INIT" || { printf '[FAIL] дефолт разошёлся: %s\n' "$_pair"; _bad=$((_bad+1)); }
done
if [ "$_bad" = "0" ]; then
    ok "боевые пути остались прежними (переменные только для тестов)"
else
    FAIL=$((FAIL + _bad))
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
