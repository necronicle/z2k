#!/bin/sh
# tests/lib/panel_js.sh — печатает путь к файлу «весь JavaScript панели».
#
# ЗАЧЕМ. До 2026-08-14 весь фронтенд лежал в одном app.js, и два десятка тестов
# просто грепали его. После разбиения на 21 модуль тот же греп ищет в
# тридцатистрочной точке входа и не находит ничего — то есть тесты зеленели бы
# на пустом месте, охраняя файл, в котором больше нет кода. Это худший исход
# из возможных: проверка есть, а не проверяет ничего.
#
# Поэтому источник для таких проверок теперь один и собирается здесь: точка
# входа плюс всё дерево модулей. Тест, которому нужен «фронтенд целиком»,
# спрашивает путь у этого помощника и не знает, из скольких файлов тот собран —
# значит следующее разбиение (или слияние) не потребует править двадцать
# тестов заново.
#
# Проверки, которым важен КОНКРЕТНЫЙ файл (доставка модулей, точка входа),
# сюда не ходят и адресуют файл напрямую — это разные вопросы.
#
# Печатает путь на stdout. Диагностика — на stderr.

set -e

_here=$(cd "$(dirname "$0")" && pwd)
_root=$(cd "$_here/../.." && pwd)
_www="$_root/webpanel/www"
_out="${TMPDIR:-/tmp}/z2k-panel-all.js"
# Пишем через временный файл и rename, а НЕ в цель напрямую.
#
# Путь общий на всю машину, и наборы зовут этот помощник каждый сам. Пока
# прогон был однопоточным, это сходило с рук; при параллельном один набор
# усекал файл ровно тогда, когда другой его читал, и панель «не отрисовывалась»
# — три набора, 23 красных проверки, ни одна из которых не про панель
# (05.09.2026). Rename атомарен, и уже открытый читателем файл переживает
# подмену целиком.
_tmp_out="$_out.$$"

[ -f "$_www/app.js" ] || { echo "panel_js.sh: нет $_www/app.js" >&2; exit 1; }
[ -d "$_www/js" ]     || { echo "panel_js.sh: нет каталога модулей $_www/js" >&2; exit 1; }

# МОДУЛЬНЫЙ СИНТАКСИС СНИМАЕТСЯ. Часть тестов не грепает, а ИСПОЛНЯЕТ вынутые
# функции (new Function поверх куска, добытого awk) — и `export function x` для
# такого разбора недопустим, а `import` в склейке бессмыслен: все модули уже
# лежат рядом в одном файле. Снимаем оба, и склейка снова читается как обычный
# скрипт, каким фронтенд и был до разбиения.
#
# Режем ТОЛЬКО в начале строки: слово export внутри строкового литерала или
# комментария трогать нельзя.
#
# Порядок — точка входа, затем модули по алфавиту. Он не важен для грепа, но
# делает файл воспроизводимым: иначе разница между прогонами шумит в отладке.
# ПОРЯДОК — ПО СЛОЯМ, А НЕ ПО АЛФАВИТУ, И ТОЧКА ВХОДА ПОСЛЕДНЕЙ.
#
# В настоящих модулях порядок исполнения задают импорты: к моменту, когда тело
# точки входа зовёт navigate(), маршрутизатор уже вычислен. Плоская склейка
# этого не знает, и при алфавитном порядке app.js оказывался первым — вызов
# уходил в ещё не инициализированную const и падал с «Cannot access before
# initialization». Проверки при этом краснели все разом и по одной и той же
# причине, не имеющей отношения к тому, что они охраняют.
#
# Порядок повторяет слои разбиения: ядро, общие службы, оболочка, страницы,
# маршрутизатор, запуск. Он же документирует направление зависимостей.
_layers="js/core js/state-model.js js/job.js js/chrome.js js/pages js/router.js"
{
    for _l in $_layers; do
        if [ -d "$_www/$_l" ]; then
            find "$_www/$_l" -name '*.js' | LC_ALL=C sort
        elif [ -f "$_www/$_l" ]; then
            printf '%s\n' "$_www/$_l"
        fi
    done
    printf '%s\n' "$_www/app.js"
} | while IFS= read -r _f; do
        printf '\n// ===== %s =====\n' "${_f#"$_www/"}"
        cat "$_f"
    done | sed -e '/^import .* from "[^"]*";$/d' -e 's/^export //' \
  | sed -e 's/^\(.\)/  \1/' > "$_tmp_out"

# ОТСТУП В ДВА ПРОБЕЛА ВОССТАНАВЛИВАЕТСЯ НАМЕРЕННО. До разбиения весь код жил
# внутри одной IIFE, то есть с отступом, и два десятка тестов вырезают куски
# диапазонами вида awk '/^  function x/,/^  }/'. После разреза функции
# закрываются скобкой в нулевой колонке, и такой диапазон молча перестаёт
# заканчиваться — awk печатает до конца файла, проверка ищет не в том куске и
# зеленеет или краснеет наугад.
#
# Можно было переписать двадцать тестов. Но диапазон по отступу — это их способ
# сказать «тело этой функции», и он не виноват в том, что мы сменили обёртку.
# Дешевле и честнее отдать им склейку в той же форме, в какой был монолит:
# файл этот всё равно существует только для проверок и никогда не исполняется
# как настоящая панель.

# Пустой результат означал бы, что дерево уехало, а тесты этого не заметят —
# они просто перестанут что-либо находить. Лучше упасть здесь.
[ -s "$_tmp_out" ] || { rm -f "$_tmp_out"; echo "panel_js.sh: собранный файл пуст" >&2; exit 1; }
mv -f "$_tmp_out" "$_out"

printf '%s\n' "$_out"
