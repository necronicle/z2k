#!/bin/sh
# tests/test_geosite_apply_guard.sh — сторож для apply_new_list в z2k-geosite.sh
#
# Ночью у людей обнулялся список РКН: диагностика показывала
# «RKN blocked (TCP): MISSING or empty», ручное обновление тут же чинило.
#
# Причина была в apply_new_list. Список нормализуется парой `awk | sort -u`,
# и её результат НЕ проверялся ничем: ни статус, ни содержимое. У ru-blocked-all
# это 1.37 млн строк, 33 МБ на входе и 24 МБ на выходе, и всё через /tmp,
# который на Keenetic лежит в оперативке. Стоило конвейеру оборваться на
# полпути — в файле оставался ноль байт, а `cp` и `mv` ниже отрабатывали
# успешно, потому что пустой файл копируется прекрасно. Рабочий список
# заменялся пустым, и в журнал писалось «applied, 0 lines», то есть отчёт об
# успехе.
#
# Проверять статус конвейера мало: `awk | sort` отдаёт статус ПОСЛЕДНЕЙ
# команды, и убитый awk оставляет sort с усечённым входом, который тот
# успешно сортирует и выходит нулём. Поэтому проверка по содержимому.
#
# Второй дефект того же места: страж «не меньше 80% от прежнего» сравнивал
# СКАЧАННЫЙ файл (формат v2fly, `domain:example.com`) с лежащим на диске (уже
# голые домены). Замер: 33.4 МБ против 24.1 МБ — сырой на 39% толще просто
# из-за приставок, то есть запас у стража был дутый и апстрим мог обрезать
# список на 40% незамеченным.
#
# Тест гоняет НАСТОЯЩЕЕ тело функции, вытащенное из отгружаемого скрипта.
# POSIX sh.

SCRIPT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
GEOSITE="$SCRIPT_DIR/files/z2k-geosite.sh"
[ -f "$GEOSITE" ] || { echo "FAIL: $GEOSITE not found"; exit 1; }

PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL + 1)); printf '[FAIL] %s\n      %s\n' "$1" "$2"; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

TMP_DIR="$TMP/work"; mkdir -p "$TMP_DIR"
LOGBUF="$TMP/log.txt"; : > "$LOGBUF"
log() { printf '%s\n' "$*" >> "$LOGBUF"; }

# Настоящее тело функции из отгружаемого скрипта.
eval "$(sed -n '/^apply_new_list() {/,/^}/p' "$GEOSITE")"

TARGET="$TMP/List.txt"

# Готовит цель и вход заново перед каждым случаем.
reset_case() {
    rm -f "$TARGET" "$TARGET.asset" "$TARGET.shipped" "$TMP_DIR"/*.normalized 2>/dev/null
    : > "$LOGBUF"
}
mk_domains() { # число, приставка -> строки списка
    awk -v n="$1" -v p="$2" 'BEGIN { for (i = 1; i <= n; i++) printf "%s%s%d.com\n", p, "d", i }'
}

# --- 1. Здоровый список применяется -----------------------------------------
reset_case
mk_domains 100 "domain:" > "$TMP/new.txt"
mk_domains 100 ""        > "$TARGET"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked-all.txt" >/dev/null 2>&1; then
    n=$(wc -l < "$TARGET" | tr -d ' ')
    [ "$n" = "100" ] && ok "здоровый список применяется (100 строк)" \
        || bad "здоровый список применяется" "на диске $n строк вместо 100"
else
    bad "здоровый список применяется" "функция вернула отказ: $(cat "$LOGBUF")"
fi

# --- 2. Пустой результат нормализации — ровно ночной баг ----------------------
# Вход непустой, но после нормализации не остаётся ничего. Это же состояние
# возникало при оборванном конвейере.
reset_case
mk_domains 5000 "" > "$TARGET"
{ i=1; while [ "$i" -le 200 ]; do printf 'regexp:.*bad%d.*\n' "$i"; i=$((i + 1)); done; } > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked-all.txt" >/dev/null 2>&1; then
    bad "пустой результат нормализации отвергается" \
        "функция сказала «применил», а на диске $(wc -l < "$TARGET" | tr -d ' ') строк"
else
    n=$(wc -l < "$TARGET" | tr -d ' ')
    if [ "$n" = "5000" ]; then
        ok "пустой результат нормализации отвергается, список цел (5000 строк)"
    else
        bad "пустой результат нормализации отвергается" "список повреждён: $n строк"
    fi
fi
grep -q 'пустой результат' "$LOGBUF" \
    && ok "в журнал написано, ПОЧЕМУ отказано" \
    || bad "в журнал написано, почему отказано" "журнал: $(cat "$LOGBUF")"

# --- 3. Обрубок: выжило меньше половины входа --------------------------------
reset_case
mk_domains 5000 "" > "$TARGET"
{ mk_domains 100 "domain:"
  i=1; while [ "$i" -le 900 ]; do printf 'keyword:junk%d\n' "$i"; i=$((i + 1)); done; } > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked-all.txt" >/dev/null 2>&1; then
    bad "обрубок отвергается" "применён список, где выжило 10% входа"
else
    [ "$(wc -l < "$TARGET" | tr -d ' ')" = "5000" ] \
        && ok "обрубок отвергается (выжило 100 из 1000), список цел" \
        || bad "обрубок отвергается" "список повреждён"
fi

# --- 4. Страж усадки считает в строках и на нормализованном -------------------
# Цель 1000 строк, новый нормализуется в 700 = 70% < 80% → отказ.
# Старая проверка сравнивала БАЙТЫ сырого v2fly (700 строк с приставкой
# `domain:` толще, чем 1000 голых доменов) и такую усадку пропускала.
reset_case
mk_domains 1000 ""       > "$TARGET"
printf 'ru-blocked-all.txt\n' > "$TARGET.asset"
mk_domains 700  "domain:" > "$TMP/new.txt"
raw=$(wc -c < "$TMP/new.txt" | tr -d ' '); cur=$(wc -c < "$TARGET" | tr -d ' ')
if [ "$raw" -gt "$cur" ]; then
    ok "предпосылка теста верна: сырой файл ($raw Б) толще лежащего ($cur Б)"
else
    bad "предпосылка теста" "сырой $raw Б не толще лежащего $cur Б — случай не тот"
fi
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked-all.txt" >/dev/null 2>&1; then
    bad "усадка на 30% отвергается" "применён список 700 строк вместо 1000"
else
    [ "$(wc -l < "$TARGET" | tr -d ' ')" = "1000" ] \
        && ok "усадка на 30% отвергается, список цел" \
        || bad "усадка на 30% отвергается" "список повреждён"
fi

# --- 5. Смена класса списка проходит мимо стража усадки -----------------------
# ru-blocked-all → ru-blocked это падение примерно в 18 раз, и оно намеренное:
# роутер с малой памятью обязан уметь перейти на маленький список. Если страж
# это зарубит, путь на понижение мёртв.
reset_case
mk_domains 1000 "" > "$TARGET"
printf 'ru-blocked-all.txt\n' > "$TARGET.asset"
mk_domains 55 "domain:" > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked.txt" >/dev/null 2>&1; then
    n=$(wc -l < "$TARGET" | tr -d ' ')
    [ "$n" = "55" ] && ok "переход большой→маленький список разрешён" \
        || bad "переход большой→маленький разрешён" "на диске $n строк вместо 55"
else
    bad "переход большой→маленький разрешён" "страж зарубил путь на понижение: $(cat "$LOGBUF")"
fi

# --- 6. Класс запоминается ----------------------------------------------------
[ "$(cat "$TARGET.asset" 2>/dev/null)" = "ru-blocked.txt" ] \
    && ok "класс применённого списка записан в .asset" \
    || bad "класс записан в .asset" "получено: $(cat "$TARGET.asset" 2>/dev/null)"

# --- 7. Пустая цель не даёт обойти проверку содержимого -----------------------
# После первой же испорченной ночи цель пуста, и страж усадки замолкает
# (сравнивать не с чем). Проверка «нормализация дала пусто» обязана работать и
# в этом состоянии — иначе пустой список закрепляется навсегда.
reset_case
: > "$TARGET"
{ i=1; while [ "$i" -le 50 ]; do printf 'regexp:.*x%d.*\n' "$i"; i=$((i + 1)); done; } > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked-all.txt" >/dev/null 2>&1; then
    bad "пустая цель не отключает проверку" "применён пустой результат поверх пустой цели"
else
    ok "пустая цель не отключает проверку содержимого"
fi

# --- Замок «шипнутый бандл vs апстрим» ---------------------------------------
#
# Страж усадки хранит класс сравниваемого в маркере <цель>.asset и пишет его
# ТОЛЬКО после успешного применения, а отсутствие маркера трактовал как «тот же
# класс» — то есть включал стража. Установка клала бандл без маркера, и дальше:
# апстримный ru-blocked.txt (74739 строк) против бандла (125451) = 59% < 80%,
# «список НЕ трогаем», маркер не пишется, состояние не меняется. Замок навсегда.
#
# Свежий список не вставал НИ РАЗУ ни на одном роутере с памятью < 900 МБ, весь
# парк сидел на снимке из бандла, а снаружи это была одна строка
# «[geosite] fetch summary: 4 ok, 1 failed». Проверено на железе 2026-08-08:
# 125446 строк, маркера нет, в логе четыре подряд отказа.

# Замок: цель от другого источника (бандл) — страж обязан ПРОПУСТИТЬ усадку.
reset_case
mk_domains 125451 "" > "$TARGET"
printf 'shipped-fallback\n' > "$TARGET.asset"
mk_domains 74739 "domain:" > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked.txt" >/dev/null 2>&1; then
    n=$(wc -l < "$TARGET" | tr -d ' ')
    [ "$n" = "74739" ] && ok "смена источника: апстрим встаёт поверх бандла (74739 строк)" \
        || bad "смена источника: апстрим встаёт поверх бандла" "на диске $n строк"
else
    bad "смена источника: апстрим встаёт поверх бандла" \
        "отказ — замок цел: $(cat "$LOGBUF")"
fi

# После применения маркер обязан назвать источник — иначе на следующем прогоне
# страж снова не сможет отличить смену источника от усадки.
if [ "$(cat "$TARGET.asset" 2>/dev/null)" = "ru-blocked.txt" ]; then
    ok "после применения маркер называет источник"
else
    bad "после применения маркер называет источник" \
        "в маркере: [$(cat "$TARGET.asset" 2>/dev/null)]"
fi

# Обратная сторона: внутри ОДНОГО источника страж обязан остаться злым, иначе
# правка выше просто отключила бы защиту от настоящей усадки апстрима.
reset_case
mk_domains 100000 "" > "$TARGET"
printf 'ru-blocked.txt\n' > "$TARGET.asset"
mk_domains 50000 "domain:" > "$TMP/new.txt"
if apply_new_list "$TMP/new.txt" "$TARGET" "ru-blocked.txt" >/dev/null 2>&1; then
    bad "усадка внутри одного источника по-прежнему отвергается" \
        "применён список вдвое короче — защита снята"
else
    n=$(wc -l < "$TARGET" | tr -d ' ')
    [ "$n" = "100000" ] && ok "усадка внутри одного источника по-прежнему отвергается" \
        || bad "усадка внутри одного источника отвергается" "цель поехала: $n строк"
fi

# --- 304 не должен верить непустой цели --------------------------------------
#
# curl сохраняет ETag во время скачивания, даже если применить содержимое потом
# не удалось. Поэтому после отказа стража следующий прогон получал 304, видел
# непустую цель и рапортовал «unchanged, keep existing» с кодом 0: список так и
# оставался бандлом, а отказ ИСЧЕЗАЛ из счётчика failed. Проверяем, что ветка
# 304 сверяет происхождение цели, а не только её непустоту.
if sed -n '/if \[ "\$rc" = "3" \]/,/^    fi$/p' "$GEOSITE" | grep -q '\${target}\.asset'; then
    ok "ветка 304 сверяет происхождение цели, а не только непустоту"
else
    bad "ветка 304 сверяет происхождение цели" \
        "304 снова верит любой непустой цели — отказ стража будет молча забываться"
fi

# --- Установка обязана помечать бандл ----------------------------------------
#
# Это и есть корень: без маркера страж считает бандл «тем же классом» и режет
# апстрим навсегда. Гоняем НАСТОЯЩУЮ функцию из lib/config.sh, а не грепаем её
# наличие — иначе тест переживёт любую поломку её тела.
CONFIG_SH="$SCRIPT_DIR/lib/config.sh"
MARKFN=$(sed -n '/^z2k_mark_shipped_fallback() {/,/^}/p' "$CONFIG_SH")
if [ -n "$MARKFN" ]; then
    eval "$MARKFN"
    MT="$TMP/marked.txt"
    printf 'example.com\n' > "$MT"
    z2k_mark_shipped_fallback "$MT"
    got=$(cat "$MT.asset" 2>/dev/null)
    if [ -n "$got" ] && [ "$got" != "ru-blocked.txt" ] && [ "$got" != "ru-blocked-all.txt" ]; then
        ok "маркер бандла ставится и не выдаёт себя за апстримный источник"
    else
        bad "маркер бандла ставится и не выдаёт себя за апстримный источник" \
            "в маркере: [$got] — страж примет бандл за апстрим и снова замкнётся"
    fi
    # На пустой файл маркер не ставим: пустая цель означает «списка нет»,
    # и ветка «304 но цель пуста» обязана отработать перезакачкой.
    : > "$TMP/empty.txt"
    z2k_mark_shipped_fallback "$TMP/empty.txt"
    if [ ! -e "$TMP/empty.txt.asset" ]; then
        ok "пустой файл не помечается"
    else
        bad "пустой файл не помечается" "маркер на пустой цели соврёт про её содержимое"
    fi
else
    bad "маркер бандла ставится" "z2k_mark_shipped_fallback отсутствует в lib/config.sh"
fi

# И он обязан вызываться на каждой уложенной цели, иначе непомеченные останутся
# в замке. Целей, которыми управляет geosite и которые кладёт установка, — 4.
marked=$(grep -c '^ *z2k_mark_shipped_fallback "' "$CONFIG_SH")
if [ "${marked:-0}" -ge 4 ]; then
    ok "установка помечает все уложенные бандлы ($marked шт.)"
else
    bad "установка помечает все уложенные бандлы" \
        "размечено только $marked целей из 4 — остальные останутся в замке"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = "0" ]
