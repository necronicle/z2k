#!/bin/sh
# tests/test_blocked_monitor_awk.sh — находки ревью awk-программы 2026-08-15.
#
# ЗАЧЕМ. Внутри files/z2k-blocked-monitor.sh живёт awk-программа на ~290 строк,
# которая разбирает вывод tcpdump. Её никто никогда не проверял: линтера для
# awk в CI нет, тестов не было, а shell-ревью читало обёртку, а не программу
# внутри heredoc. При этом вход у неё — расшифровка чужих пакетов из сети, а
# работает она часами на устройстве со 128-256 МБ.
#
# Все проверки ниже ИСПОЛНЯЮТ настоящую программу, вынутую из heredoc, на
# строках в формате настоящего tcpdump. Ни одна не грепает исходник: дефекты
# здесь такие, что код выглядит правильным ровно до момента, когда его
# запустишь.
#
# POSIX sh + awk.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC="$ROOT/files/z2k-blocked-monitor.sh"
[ -f "$SRC" ] || { printf '[FAIL] нет %s\n' "$SRC"; exit 1; }
command -v awk >/dev/null 2>&1 || { printf '[SKIP] нет awk\n'; exit 0; }

TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

# Вынимаем программу по границам heredoc, а не по номерам строк: файл правится,
# номера уезжают, и тест начал бы проверять обрезок.
B=$(grep -n 'cat > "\$AWK_FILE" <<.AWK.' "$SRC" | head -1 | cut -d: -f1)
[ -n "$B" ] || { printf '[FAIL] в %s не найден heredoc awk\n' "$SRC"; exit 1; }
E=$(awk -v b="$B" 'NR>b && $0=="AWK"{print NR; exit}' "$SRC")
[ -n "$E" ] || { printf '[FAIL] не найден конец heredoc\n'; exit 1; }

# systime() нет в awk на macOS; на роутере (BusyBox) она есть. Подставляем
# заглушку, чтобы прогнать логику локально — сама программа время берёт из
# первого поля строки (tcpdump -tt), так что на проверяемое это не влияет.
{ echo 'function systime() { return _now }'; sed -n "$((B+1)),$((E-1))p" "$SRC"; } > "$TMP/m.awk"

if ! awk -f "$TMP/m.awk" </dev/null >/dev/null 2>&1; then
    no "программа разбирается" "синтаксис ок" "$(awk -f "$TMP/m.awk" </dev/null 2>&1 | head -2)"
    printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"; exit 1
fi
ok "awk-программа разбирается"

run() {  # run <now> ; строки на stdin ; результаты в $TMP/out/
    rm -rf "$TMP/out"; mkdir -p "$TMP/out"
    awk -v _now="$1" \
        -v all_out="$TMP/out/all.tsv" -v tcp_out="$TMP/out/tcp.tsv" \
        -v udp_out="$TMP/out/udp.tsv" -v ipmap_out="$TMP/out/ipmap.tsv" \
        -v tcp_ports="443,80" -v udp_ports="443" -f "$TMP/m.awk" >/dev/null 2>&1
}

# --- 1. SYN с флагами ECN — это тоже попытка соединения --------------------------
#
# Было `index($0, "Flags [S]")`, то есть засчитывался только SYN без единого
# другого флага. У современного клиента с ECN в скобках стоит [SEW] или [SE], и
# такой SYN не попадал в трекер ВООБЩЕ: заблокированное соединение молча не
# считалось заблокированным.
printf '%s\n' \
 '1.0 IP 10.0.0.5.5000 > 93.184.216.34.443: Flags [S], seq 1, length 0' \
 '2.0 IP 10.0.0.5.5000 > 93.184.216.34.443: Flags [SEW], seq 1, length 0' \
 '3.0 IP 10.0.0.5.5000 > 93.184.216.34.443: Flags [SE], seq 1, length 0' \
 '50.0 IP 10.0.0.9.1234 > 8.8.4.4.53: 1+ A? x.com. (20)' | run 50
if grep -q 'syn_retries=3' "$TMP/out/all.tsv" 2>/dev/null; then
    ok "SYN с флагами ECN считается попыткой (3 из 3)"
else
    no "учёт SYN с ECN" "syn_retries=3" \
       "$(cat "$TMP/out/all.tsv" 2>/dev/null || echo 'ничего не сообщено — блокировка пропущена')"
fi

# SYN+ACK при этом обязан остаться ответом сервера, а не считаться попыткой.
printf '%s\n' \
 '1.0 IP 93.184.216.34.443 > 10.0.0.5.5000: Flags [S.E], seq 1, length 0' \
 '50.0 IP 10.0.0.9.1234 > 8.8.4.4.53: 1+ A? x.com. (20)' | run 50
if [ ! -s "$TMP/out/all.tsv" ]; then
    ok "SYN+ACK не путается с исходящим SYN"
else
    no "различение SYN и SYN+ACK" "ничего" "$(cat "$TMP/out/all.tsv")"
fi

# --- 2. DNS: все адреса ответа, а не только последний ----------------------------
#
# Было `sub(/.* A /, "", ip)` — жадная одиночная замена, забирающая всё до
# ПОСЛЕДНЕГО " A ". У любого CDN в ответе несколько A-записей, клиент берёт
# любую, поэтому имя находилось примерно в одном случае из N.
printf '%s\n' \
 '1.0 IP 10.0.0.5.5353 > 8.8.8.8.53: 61374+ A? multi.example.com. (35)' \
 '2.0 IP 8.8.8.8.53 > 10.0.0.5.5353: 61374 2/0/0 A 1.1.1.1 A 2.2.2.2 (60)' | run 10
_n=$(wc -l < "$TMP/out/ipmap.tsv" 2>/dev/null | tr -d ' ')
if [ "${_n:-0}" = "2" ] && grep -q '1\.1\.1\.1' "$TMP/out/ipmap.tsv"; then
    ok "оба адреса из ответа с двумя A-записями попали в карту"
else
    no "все A-записи" "2 строки, включая 1.1.1.1" "${_n:-0} строк — адреса теряются"
fi

# --- 3. DNS: флаг у идентификатора не должен ронять ответ ------------------------
#
# tcpdump печатает флаги СЛИТНО с id: «61374*» (авторитетный), «61374-», «61374|».
# Обрезка по первому пробелу оставляла их в id, тот не проходил проверку на
# цифры, и ответ отбрасывался целиком. Среди отброшенных — NXDomain и SERVFAIL,
# то есть типовая подпись блокировки по DNS.
printf '%s\n' \
 '1.0 IP 10.0.0.5.5353 > 8.8.8.8.53: 4242+ A? aa.example.com. (32)' \
 '2.0 IP 8.8.8.8.53 > 10.0.0.5.5353: 4242* 1/0/0 A 7.7.7.7 (48)' | run 10
if grep -q 'aa.example.com' "$TMP/out/ipmap.tsv" 2>/dev/null; then
    ok "ответ с флагом AU у идентификатора разбирается"
else
    no "флаг у идентификатора" "aa.example.com в карте" "ответ отброшен целиком"
fi

# --- 4. DNS-запрос без флага RD --------------------------------------------------
#
# Обрезка «до плюса» ничего не делала, если плюса нет, и запрос терялся.
printf '%s\n' \
 '1.0 IP 10.0.0.5.5354 > 8.8.8.8.53: 12346 A? norec.example.com. (27)' \
 '2.0 IP 8.8.8.8.53 > 10.0.0.5.5354: 12346 1/0/0 A 5.5.5.5 (43)' | run 10
if grep -q 'norec.example.com' "$TMP/out/ipmap.tsv" 2>/dev/null; then
    ok "запрос без флага рекурсии сопоставляется с ответом"
else
    no "запрос без RD" "norec.example.com в карте" "запрос потерян"
fi

# --- 5. DNS поверх IPv6 ----------------------------------------------------------
#
# `index($0, ":")` находил двоеточие внутри адреса IPv6, и содержимое пакета
# начиналось с середины адреса: весь разбор DNS по IPv6 не работал.
printf '%s\n' \
 '1.0 IP6 2001:db8::5.5355 > 2001:4860:4860::8888.53: 777+ A? v6.example.com. (32)' \
 '2.0 IP6 2001:4860:4860::8888.53 > 2001:db8::5.5355: 777 1/0/0 A 9.9.9.9 (48)' | run 10
if grep -q 'v6.example.com' "$TMP/out/ipmap.tsv" 2>/dev/null; then
    ok "DNS поверх IPv6 разбирается"
else
    no "DNS по IPv6" "v6.example.com в карте" "не разобрано"
fi

# --- 6. ПАМЯТЬ: ничего не остаётся навсегда --------------------------------------
#
# Три независимых пути копили ключи, которые не удалялись ничем:
#   * поток, просрочившийся, но не добравший попыток до порога;
#   * ключ, заведённый только в tcp_ok (подметание ходит лишь по tcp_first_ts);
#   * DNS-запрос, оставшийся без ответа — то есть ровно признак блокировки.
# Монитор работает часами на устройстве со 128 МБ, так что это не стиль.
{
    cat "$TMP/m.awk"
    printf '%s\n' \
      'END {' \
      '  n=0' \
      '  for (k in tcp_first_ts) n++' \
      '  for (k in tcp_syn_count) n++' \
      '  for (k in tcp_ok) n++' \
      '  for (k in tcp_rst) n++' \
      '  for (k in udp_first_ts) n++' \
      '  for (k in dns_query_key_to_host) n++' \
      '  print "LEFTOVER=" n > "/dev/stderr"' \
      '}'
} > "$TMP/leak.awk"
_left=$(printf '%s\n' \
 '1.0 IP 10.0.0.5.5001 > 1.2.3.4.443: Flags [S], seq 1, length 0' \
 '2.0 IP 10.0.0.5.5001 > 1.2.3.4.443: Flags [S], seq 1, length 0' \
 '3.0 IP 10.0.0.5.5002 > 8.8.8.8.53: 999+ A? never.example. (30)' \
 '4.0 IP 5.6.7.8.443 > 10.0.0.5.6000: Flags [S.], seq 1, length 0' \
 '500.0 IP 10.0.0.9.1234 > 9.9.9.9.53: 2+ A? y.com. (20)' \
 | awk -v _now=500 -v all_out=/dev/null -v tcp_out=/dev/null -v udp_out=/dev/null \
       -v ipmap_out=/dev/null -v tcp_ports="443,80" -v udp_ports="443" \
       -f "$TMP/leak.awk" 2>&1 >/dev/null | sed -n 's/^LEFTOVER=//p')
if [ "${_left:-99}" = "0" ]; then
    ok "после подметания в памяти не осталось ни одного ключа"
else
    no "очистка состояния" "0 ключей" \
       "${_left:-?} — они не удалятся уже никогда, монитор течёт всё время работы"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
