#!/bin/sh
# tests/test_release_script.sh — сторож для scripts/release.sh.
#
# До 2026-08-05 скрипта релиза не существовало вовсе: версия, тип, список файлов
# и ссылка на коммит проставлялись руками каждый раз. Список файлов при этом
# писался глазами — по памяти о том, что менялось.
#
# Промахи в нём не гипотеза: webpanel/www/index.html пропускали ТРИЖДЫ подряд
# (r-71.1, r-72, r-72.1), и каждый раз ловили вручную. Цена промаха не
# косметическая — незаявленный файл патчем НЕ доставляется, а версия при этом
# продвигается вперёд, и у человека остаётся старый код под новым номером.
# Снаружи это состояние не опознаётся никак.
#
# Поэтому главное свойство скрипта: список файлов ВЫЧИСЛЯЕТСЯ из git, а не
# набирается руками. Этот тест следит, чтобы механизм не убрали и чтобы
# защитные проверки остались на месте.
#
# POSIX sh.

ROOT=$(cd "$(dirname "$0")/.." && pwd)
REL="$ROOT/scripts/release.sh"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n      %s\n' "$1" "$2"; }

if [ ! -f "$REL" ]; then
    no "scripts/release.sh существует" "файла нет — релиз опять собирается руками"
    
    printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
    exit 1
fi
ok "scripts/release.sh существует"

sh -n "$REL" 2>/dev/null && ok "синтаксис валиден" || no "синтаксис валиден" "sh -n падает"

# 1) Список файлов берётся из git. Это ЕДИНСТВЕННОЕ, что структурно защищает от
#    пропуска файла: то, чего человек не набирает, он не может забыть.
if grep -q 'git diff --name-only "\$PREV_REF"\.\.HEAD' "$REL"; then
    ok "changed_files вычисляется из git diff с предыдущего релиза"
else
    no "changed_files вычисляется из git diff" \
       "механизм убран — список снова пишется руками, и пропуск файла вернётся"
fi

# 2) Заявляем только то, у чего есть цель на роутере: файл без цели патч никуда
#    не положит, а в списке он создаёт ложное чувство покрытия.
if grep -q 'z2k_install_paths' "$REL"; then
    ok "доставляемость проверяется через z2k_install_paths"
else
    no "доставляемость проверяется через z2k_install_paths" "проверки нет"
fi

# 3) ЛЮБОЙ путь, который патч доставить не может (арх-бинарники, install-time
#    генераторы, install-time шаблоны), гейтится ОДНОЙ политикой —
#    z2k_legacy_reinstall_required() в lib/release_map.sh — а не разрозненными
#    regex-ами прямо в release.sh, которые заводились по одному на находку
#    (сперва только mtproxy-client, потом отдельно z2k-detect/z2k-verify,
#    потом отдельно config_official.sh/strategies.sh — а webpanel/lighttpd.conf
#    так и не попал ни в один из них, хотя комментарий рядом с ним прямо
#    гласил "ship as reinstall"). Проверяем ПОВЕДЕНИЕ функции, а не текст
#    скрипта — иначе тест сторожит формулировку, а не факт.
if grep -q 'z2k_legacy_reinstall_required' "$REL"; then
    ok "release.sh гейтит через единую z2k_legacy_reinstall_required(), а не свои regex-ы"
else
    no "release.sh использует единую z2k_legacy_reinstall_required()" "вызов функции" "не найден"
fi

# shellcheck disable=SC1091
. "$ROOT/lib/release_map.sh"

_covered=0; _total=0
for _p in "mtproxy-client/builds/tg-mtproxy-client-linux-arm64" \
          "z2k-detect/builds/z2k-detect-linux-mips" \
          "lib/config_official.sh" \
          "lib/strategies.sh" \
          "webpanel/lighttpd.conf"; do
    _total=$((_total + 1))
    if [ -n "$(z2k_legacy_reinstall_required "$_p")" ]; then
        _covered=$((_covered + 1))
    else
        printf '[FAIL] z2k_legacy_reinstall_required не накрывает %s\n' "$_p"
    fi
done
if [ "$_covered" = "$_total" ]; then
    ok "z2k_legacy_reinstall_required накрывает бинарники ЛЮБОГО модуля, генераторы конфига/стратегий и шаблон lighttpd.conf ($_covered/$_total)"
else
    FAIL=$((FAIL + (_total - _covered)))
fi

# И не перехватывает то, что патчу доставлять положено штатно — иначе гейт
# заставлял бы делать reinstall на каждую мелкую правку.
for _p in "lib/auto_update.sh" "files/lua/z2k-detectors.lua" "webpanel/cgi/api.sh"; do
    if [ -n "$(z2k_legacy_reinstall_required "$_p")" ]; then
        no "z2k_legacy_reinstall_required не перехватывает штатно патчуемые пути" "пусто для $_p" "непусто"
    else
        ok "z2k_legacy_reinstall_required не трогает штатно патчуемый путь ($_p)"
    fi
done

# 4) ref = уже существующий несущий коммит (HEAD), одним коммитом.
#
#    Прежняя схема писала ref="PENDING" и проставляла хеш ВТОРЫМ коммитом —
#    самоссылка на коммит, содержащий этот же манифест. Она тянула второй
#    коммит и ломала подпись (правила уже подписанный файл; поймано на r-75).
#    Убрали: ref берётся из HEAD (код закоммичен до release.sh), поэтому известен
#    сразу и коммит один. Тест сторожит, что самоссылка НЕ вернулась.
if grep -q 'REF="$VER"' "$REL"; then
    ok "ref — это имя тега (известно заранее, самоссылки нет)"
else
    no "ref — имя тега" 'REF="$VER" отсутствует — вернулась ссылка на коммит'
fi
# И тег обязан ставиться, иначе ref указывает в никуда.
if grep -q 'tag -s "\$VER"' "$REL"; then
    ok "релиз ставит подписанный тег"
else
    no "релиз ставит подписанный тег" "git tag -s отсутствует"
fi
if grep -q '"ref": "PENDING"' "$REL" || grep -q 'указать ref .* на несущий коммит"' "$REL"; then
    no "самоссылки нет" "остался PENDING или второй коммит простановки ref"
else
    ok "нет PENDING и второго коммита простановки ref (самоссылка убрана)"
fi
# Подпись — последним шагом, ПОСЛЕ карты сумм: иначе она не покроет финальные
# байты. Порядок в файле: gen_file_hashes -> pkeyutl -sign.
_gen=$(grep -n 'gen_file_hashes.sh' "$REL" | tail -1 | cut -d: -f1)
_sig=$(grep -n 'pkeyutl -sign' "$REL" | head -1 | cut -d: -f1)
if [ -n "$_gen" ] && [ -n "$_sig" ] && [ "$_gen" -lt "$_sig" ]; then
    ok "подпись накладывается после карты сумм (покрывает финальный манифест)"
else
    no "подпись после карты сумм" "gen=$_gen sign=$_sig — подпись раньше карты"
fi

# 4а) Ключ подписи обязателен. Раньше без ключа релиз всё равно собирался
#     (warn-and-continue), и человек узнавал о последствиях уже когда
#     publish.yml отвергал неподписанный тег — то есть после коммита и тега.
#     Оба места (манифест и тег) обязаны звать die, а не printf-предупреждение.
if grep -q 'ВНИМАНИЕ:.*БЕЗ подписи' "$REL" || grep -q 'ВНИМАНИЕ: ключ недоступен' "$REL"; then
    no "ключ подписи обязателен" "die при отсутствии ключа" "остался warn-and-continue"
else
    ok "нет warn-and-continue ветки без ключа (манифест и тег)"
fi
if grep -q 'die "ключ подписи не найден' "$REL" && grep -q 'die "не удалось подписать тег' "$REL"; then
    ok "отсутствие/сбой ключа останавливает релиз (die) и для манифеста, и для тега"
else
    no "отсутствие/сбой ключа останавливает релиз" "die в обеих ветках" "не найдено"
fi

# 4б) Покрытие каждого класса (генераторы, шаблон, бинарники) проверено выше
#     поведенчески через z2k_legacy_reinstall_required(). Здесь — что сам гейт в
#     release.sh условен на TYPE, а не абсолютный запрет менять эти пути.
if grep -q '_reinstall_changed' "$REL" && grep -q '"\$TYPE" != "reinstall"' "$REL"; then
    ok "гейт единой политики условен на TYPE=reinstall (снимается, не абсолютный запрет)"
else
    no "гейт единой политики условен на TYPE=reinstall" \
       "_reinstall_changed + проверка \$TYPE != reinstall" "не найдено"
fi

# 4в) Push — одной атомарной операцией. Два отдельных push оставляли окно, где
#     на origin уже есть ветка с новым коммитом, а тега ещё нет (или наоборот).
if grep -q 'git push --atomic origin' "$REL"; then
    ok "push ветки и тега — одна атомарная операция"
else
    no "push ветки и тега атомарен" "git push --atomic" "не найдено — остались два отдельных push"
fi

# 5) Грязное дерево: сумма считается по рабочей копии, а ссылка укажет на коммит
#    без этих правок — то есть карта сумм разойдётся с тем, что доедет людям.
if grep -q 'git status --porcelain' "$REL"; then
    ok "незакоммиченные правки останавливают релиз"
else
    no "незакоммиченные правки останавливают релиз" "проверки нет"
fi

# 6) Аргументы проверяются на самом деле, а не на словах.
out=$(sh "$REL" 2>&1); rc=$?
if [ "$rc" != "0" ] && printf '%s' "$out" | grep -q 'версия'; then
    ok "без аргументов скрипт отказывается работать"
else
    no "без аргументов скрипт отказывается" "rc=$rc, вывод: $out"
fi

out=$(sh "$REL" 72.3 patch "тест" 2>&1); rc=$?
if [ "$rc" != "0" ]; then
    ok "версия без префикса отвергается"
else
    no "версия без префикса отвергается" "скрипт принял '72.3'"
fi

out=$(sh "$REL" r-99.9 hotfix "тест" 2>&1); rc=$?
if [ "$rc" != "0" ]; then
    ok "неизвестный тип релиза отвергается"
else
    no "неизвестный тип отвергается" "скрипт принял 'hotfix'"
fi

# 7) Префикс версии обязан совпадать с типом: r = reinstall, p = patch. Правило
#    человеческое — код обновления смотрит только на поле type, — но номер
#    релиза для того и нужен, чтобы отвечать «быстрый патч или переустановка».
#    В истории разошлось семь раз из 139: вниманием это не ловится.
out=$(sh "$REL" r-99.9 patch "тест" 2>&1)
if [ "$?" != "0" ] && printf '%s' "$out" | grep -q 'p-99.9'; then
    ok "r- с типом patch отвергается и предлагает p-"
else
    no "r- с типом patch отвергается" "получено: $out"
fi

out=$(sh "$REL" p-99.9 reinstall "тест" 2>&1)
if [ "$?" != "0" ] && printf '%s' "$out" | grep -q 'r-99.9'; then
    ok "p- с типом reinstall отвергается и предлагает r-"
else
    no "p- с типом reinstall отвергается" "получено: $out"
fi

# 8) Этот скрипт СОБИРАЕТ релиз, но не выпускает его.
#
#    Свойство «код не доезжает до людей раньше своих тестов» никуда не делось —
#    оно просто переехало туда, где его нельзя переждать или обойти переменной.
#    Раньше гейт жил здесь: скрипт ждал `gh run` до 25 минут и умел пропускать
#    ожидание через Z2K_RELEASE_SKIP_CI_GATE. При одном разработчике такой гейт
#    рано или поздно обходится. Теперь релизную ветку двигает только
#    .github/workflows/publish.yml после зелёного CI (см. tests/test_publish_gate.sh).
#
#    Здесь охраняется обратное: release.sh НЕ имеет права ничего публиковать.
# Ищем `git push` именно как КОМАНДУ (начало строки), а не как текст подсказки
# внутри printf: скрипт обязан подсказывать человеку, что пушить, и это не то
# же самое, что пушить самому.
if grep -qE '^[[:space:]]*git push' "$REL"; then
    no "release.sh не публикует сам" "никаких git push" \
       "скрипт пушит — публикация обязана оставаться работой робота"
else
    ok "release.sh ничего не публикует — только собирает"
fi

#    И не собирается прямо в релизной ветке: коммит там уже был бы выпуском.
if grep -q 'RELEASE_BRANCH' "$REL" && grep -q 'STAGING_BRANCH' "$REL"; then
    ok "release.sh отличает рабочую ветку от релизной"
else
    no "release.sh отличает ветки" "RELEASE_BRANCH и STAGING_BRANCH" "не найдено"
fi

#    Обход гейта не должен вернуться сюда под новым именем.
if grep -qE '^[^#]*(SKIP_CI_GATE|gh run list)' "$REL"; then
    no "гейт не живёт в скрипте" "нет ожидания CI и нет обхода" \
       "гейт вернулся в скрипт — его снова можно переждать или обойти"
else
    ok "гейта, который можно обойти переменной, в скрипте нет"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = "0" ]
