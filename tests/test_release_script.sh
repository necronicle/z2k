#!/bin/sh
# tests/test_release_script.sh — сторож для scripts/release.sh.
#
# До 2026-08-05 скрипта релиза не существовало вовсе: версия, тип, список файлов
# и ссылка на коммит проставлялись руками каждый раз. Список файлов при этом
# писался глазами — по памяти о том, что менялось.
#
# Промахи в нём не гипотеза: webpanel/www/index.html пропускали ТРИЖДЫ подряд
# (r-71.1, r-72, r-72.1), и каждый раз ловили вручную. Цена промаха не
# косметическая — незаявленный файл патчем НЕ доставляется, а версия при этом
# продвигается вперёд, и у человека остаётся старый код под новым номером.
# Снаружи это состояние не опознаётся никак.
#
# Поэтому главное свойство скрипта: список файлов ВЫЧИСЛЯЕТСЯ из git, а не
# набирается руками. Этот тест следит, чтобы механизм не убрали и чтобы
# защитные проверки остались на месте.
#
# POSIX sh.

ROOT=$(cd "$(dirname "$0")/.." && pwd)
REL="$ROOT/scripts/release.sh"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n      %s\n' "$1" "$2"; }

if [ ! -f "$REL" ]; then
    no "scripts/release.sh существует" "файла нет — релиз опять собирается руками"
    printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
    exit 1
fi
ok "scripts/release.sh существует"

sh -n "$REL" 2>/dev/null && ok "синтаксис валиден" || no "синтаксис валиден" "sh -n падает"

# 1) Список файлов берётся из git. Это ЕДИНСТВЕННОЕ, что структурно защищает от
#    пропуска файла: то, чего человек не набирает, он не может забыть.
if grep -q 'git diff --name-only "\$PREV_REF"\.\.HEAD' "$REL"; then
    ok "changed_files вычисляется из git diff с предыдущего релиза"
else
    no "changed_files вычисляется из git diff" \
       "механизм убран — список снова пишется руками, и пропуск файла вернётся"
fi

# 2) Заявляем только то, у чего есть цель на роутере: файл без цели патч никуда
#    не положит, а в списке он создаёт ложное чувство покрытия.
if grep -q 'au_install_paths' "$REL"; then
    ok "доставляемость проверяется через au_install_paths"
else
    no "доставляемость проверяется через au_install_paths" "проверки нет"
fi

# 3) Бинарник туннеля доставляется только реинсталлом — цель зависит от
#    архитектуры роутера. Патч с изменившимся бинарником это молчаливо
#    несостоявшаяся доставка: люди остаются на старом клиенте под новой версией.
if grep -q 'mtproxy-client/builds/' "$REL" && grep -q 'reinstall' "$REL"; then
    ok "изменившийся бинарник туннеля требует reinstall"
else
    no "изменившийся бинарник требует reinstall" "проверки нет"
fi

# 4) Ссылка на коммит проставляется вторым коммитом. Иначе никак: хеш известен
#    только после создания коммита, а amend меняет хеш — и ссылка снова
#    указывает в никуда. На этом уже спотыкались.
if grep -q 'указать ref' "$REL"; then
    ok "ref проставляется отдельным коммитом"
else
    no "ref проставляется отдельным коммитом" "шага нет — ссылка будет висеть на PENDING"
fi

# 5) Грязное дерево: сумма считается по рабочей копии, а ссылка укажет на коммит
#    без этих правок — то есть карта сумм разойдётся с тем, что доедет людям.
if grep -q 'git status --porcelain' "$REL"; then
    ok "незакоммиченные правки останавливают релиз"
else
    no "незакоммиченные правки останавливают релиз" "проверки нет"
fi

# 6) Аргументы проверяются на самом деле, а не на словах.
out=$(sh "$REL" 2>&1); rc=$?
if [ "$rc" != "0" ] && printf '%s' "$out" | grep -q 'версия'; then
    ok "без аргументов скрипт отказывается работать"
else
    no "без аргументов скрипт отказывается" "rc=$rc, вывод: $out"
fi

out=$(sh "$REL" 72.3 patch "тест" 2>&1); rc=$?
if [ "$rc" != "0" ]; then
    ok "версия без префикса отвергается"
else
    no "версия без префикса отвергается" "скрипт принял '72.3'"
fi

out=$(sh "$REL" r-99.9 hotfix "тест" 2>&1); rc=$?
if [ "$rc" != "0" ]; then
    ok "неизвестный тип релиза отвергается"
else
    no "неизвестный тип отвергается" "скрипт принял 'hotfix'"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = "0" ]
