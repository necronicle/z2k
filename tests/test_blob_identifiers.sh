#!/bin/sh
# tests/test_blob_identifiers.sh — каждый регистрируемый блоб обязан быть
# принят движком и иметь смысл.
#
# ЧТО СЛУЧИЛОСЬ. Init-скрипт регистрировал `--blob=4pda:@files/fake/4pda.bin`.
# nfqws2 такой идентификатор отвергает — «bad identifier '4pda'», имя не может
# начинаться с цифры, — и демон не стартовал вовсе. Строка жила в дереве с
# марта и не срабатывала лишь потому, что сам файл на роутеры не приезжал:
# старая доставка возила только то, что релиз перечислил поимённо. Как только
# обновление стало приводить дерево к манифесту целиком, файл приехал, условие
# `[ -s ... ]` стало истинным — и обход лёг у всех, кто перезапустил сервис.
#
# Отсюда два правила, которые здесь и сторожатся:
#   1. идентификатор блоба обязан быть принят движком (буква или _ в начале);
#   2. регистрировать блоб, на который никто не ссылается, нельзя — он не даёт
#      ничего, кроме шанса уронить старт.
# POSIX sh.
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
assert_eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }
ROOT=$(cd "$(dirname "$0")/.." && pwd)
INIT="$ROOT/files/S99zapret2.new"
if command -v sha256sum >/dev/null 2>&1; then _sha() { sha256sum "$1" | awk '{print $1}'; }
elif command -v shasum >/dev/null 2>&1; then _sha() { shasum -a 256 "$1" | awk '{print $1}'; }
else _sha() { cksum "$1" | awk '{print $1"-"$2}'; }
fi

# Комментарии срезаем: почему `4pda` здесь нельзя — ценное объяснение, и оно
# должно пережить этот тест. Проверяем ВЫЗОВ, а не упоминание.
IDS=$(sed 's/#.*//' "$INIT" | grep -o '\-\-blob=[A-Za-z0-9_]*' | sed 's/--blob=//' | sort -u)
assert_eq "блобы вообще регистрируются" "1" "$([ -n "$IDS" ] && echo 1 || echo 0)"

# --- 1. Имя, которое примет движок -------------------------------------------
_bad=""
for id in $IDS; do
    case "$id" in
        [A-Za-z_]*) ;;
        *) _bad="$_bad $id" ;;
    esac
done
assert_eq "все идентификаторы начинаются с буквы или _" "" "$_bad"

# --- 2. Ни одной мёртвой регистрации -----------------------------------------
# Ссылка — это `blob=<id>` где-то ещё, кроме самой строки регистрации.
#
# ИСТОЧНИК СТРАТЕГИЙ — strats_new2.txt, а НЕ extra_strats/*/Strategy.txt:
# Strategy.txt это производная копия одной строки оттуда, которую пишет
# create_default_strategy_files, и в репозитории такого каталога нет вовсе.
# Тест, смотревший туда, объявлял мёртвыми одиннадцать живых блобов.
_dead=""
for id in $IDS; do
    _n=$(grep -rho "blob=${id}\([^A-Za-z0-9_]\|\$\)" \
            "$ROOT/strats_new2.txt" "$ROOT/lib/config_official.sh" \
            "$ROOT/lib/strategies.sh" "$ROOT/files/lua" 2>/dev/null | wc -l | tr -d ' ')
    [ "${_n:-0}" -eq 0 ] && _dead="$_dead $id"
done
if [ -z "$_dead" ]; then
    ok "мёртвых регистраций нет"
else
    printf '[INFO] не используются в поставляемых стратегиях:%s\n' "$_dead"
    printf '[INFO] это не отказ: их может звать пользовательская стратегия на роутере.\n'
    printf '[INFO] Сторожим главное — что такой блоб хотя бы СТАРТУЕТ (пункт 1).\n'
    ok "мёртвые регистрации перечислены и не ломают старт"
fi

# --- 3. Каждому регистрируемому блобу соответствует поставляемый файл ---------
# Регистрация условна (`[ -s FILE ] && ...`), поэтому отсутствие файла демон не
# роняет. Но файл, которого нет в дереве, означает мёртвую переменную — и ровно
# такая пара (файл-дубликат + невалидное имя) и стоила обхода.
_missing=""
for v in $(grep -o '^[A-Z0-9_]*_BLOB="[^"]*"' "$INIT" | sed 's/=.*//' | sort -u); do
    _p=$(grep -m1 "^${v}=" "$INIT" | sed 's/.*="//; s/"$//; s|\$ZAPRET_BASE/||')
    [ -n "$_p" ] || continue
    case "$_p" in files/fake/*) [ -f "$ROOT/$_p" ] || _missing="$_missing $_p" ;; esac
done
assert_eq "все объявленные blob-файлы есть в дереве" "" "$_missing"

# --- 4. Дубликатов среди поставляемых blob-файлов нет -------------------------
# 4pda.bin был байт-в-байт равен tls_clienthello_4pda_to.bin: два имени на один
# файл, и одно из них — с идентификатором, который движок не принимает.
# Сам по себе дубликат старт не ломает — ломало невалидное имя (пункт 1).
# Поэтому здесь не отказ, а видимый список: два имени на один файл означают, что
# одно из них, скорее всего, лишнее, и его стоит разобрать не в аварийном режиме.
# Пары считаем по контрольной сумме, а не попарным cmp: лексикографическое
# сравнение строк в POSIX sh не определено (SC3012), да и квадрат по 90 файлам
# ни к чему.
_dups=$(
    for f in "$ROOT"/files/fake/*.bin; do
        [ -f "$f" ] || continue
        printf '%s %s\n' "$(_sha "$f")" "$(basename "$f")"
    done | sort | awk '
        { if ($1 == prev) { printf "%s=%s ", pname, $2 } prev = $1; pname = $2 }'
)
_dups=$(printf '%s' "$_dups" | sed 's/[[:space:]]*$//')
if [ -z "$_dups" ]; then
    ok "среди blob-файлов нет байт-в-байт дубликатов"
else
    printf '[INFO] дубликаты blob-файлов:%s\n' "$_dups"
    ok "дубликаты перечислены (старт не ломают)"
fi

# --- 5. Файл, который больше не регистрируется, не должен остаться в поставке --
# 4pda.bin приезжал на каждый роутер и не использовался ничем: сходимость возит
# всё, что описано манифестом, поэтому лишний файл в дереве — это лишний файл у
# всех. Проверяем адресно тот, из-за которого лёг обход.
assert_eq "4pda.bin убран из поставки" "0" "$([ -f "$ROOT/files/fake/4pda.bin" ] && echo 1 || echo 0)"
assert_eq "регистрации blob=4pda больше нет" "0" \
    "$(grep -c '^\[ -s "\$TLS_4PDA_SHORT_BLOB" \]' "$INIT" | tr -d ' ')"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
