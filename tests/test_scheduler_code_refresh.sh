#!/bin/sh
# Обновление обязано переводить планировщик на новый код.
#
# Путь сходимости выполняет только объявленные шаги, и перезапуска планировщика
# среди них нет. Пока это не было закрыто, новый z2k-scheduler.sh лежал на диске,
# а работал старый процесс — до перезагрузки роутера. Ценой были все одноразовые
# действия после обновления: чистка записей ip host и первая проба линии на блок
# по объёму. У пользователя на r-81.6 механизм так и остался выключенным.
#
# Тест исполняемый: подсовывает функции поддельный init и проверяет, что она его
# дёрнула — ровно один раз на каждое изменение файла планировщика.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
INIT="$ROOT/files/S99zapret2.new"
SCHED="$ROOT/files/z2k-scheduler.sh"
fails=0
ok()   { echo "  [ок]     $1"; }
bad()  { echo "  [ПРОВАЛ] $1"; fails=$((fails+1)); }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- стенд -------------------------------------------------------------------
mkdir -p "$TMP/opt"
printf '#!/bin/sh\necho "$1" >> "%s/calls.log"\n' "$TMP" > "$TMP/opt/S99z2k-scheduler"
chmod +x "$TMP/opt/S99z2k-scheduler"
echo '# планировщик' > "$TMP/opt/z2k-scheduler.sh"
: > "$TMP/calls.log"

# Вырезаем только испытуемую функцию: подключать init целиком нельзя — он
# трогает firewall и демонов.
awk '/^_z2k_scheduler_sync\(\)/,/^}/' "$INIT" > "$TMP/fn.sh"
if [ ! -s "$TMP/fn.sh" ]; then
    bad "в $INIT нет функции _z2k_scheduler_sync"
    echo "провалов: $fails"; exit 1
fi

run_sync() {
    Z2K_SCHED_FILE="$TMP/opt/z2k-scheduler.sh" \
    Z2K_SCHED_INIT="$TMP/opt/S99z2k-scheduler" \
    Z2K_SCHED_STAMP="$TMP/stamp" \
    sh -c ". $TMP/fn.sh; _z2k_scheduler_sync" >/dev/null 2>&1
}
calls() { wc -l < "$TMP/calls.log" | tr -d ' '; }

# --- 1. отметки нет (старый планировщик в памяти) — обязан перезапустить ------
run_sync
[ "$(calls)" = "1" ] && ok "без отметки планировщик перезапускается" \
    || bad "без отметки перезапуска не было (вызовов: $(calls))"

# --- 2. повторный запуск службы ничего не делает ------------------------------
# NDM дёргает службу на каждое переподключение; шторм перезапусков планировщика
# был бы хуже исходной болезни.
run_sync; run_sync
[ "$(calls)" = "1" ] && ok "повторные запуски службы планировщик не трогают" \
    || bad "лишний перезапуск: вызовов $(calls), ожидалось 1"

# --- 3. приехал новый файл планировщика — обязан перезапустить снова ----------
sleep 1
echo '# новый код' >> "$TMP/opt/z2k-scheduler.sh"
run_sync
[ "$(calls)" = "2" ] && ok "новый файл планировщика вызывает перезапуск" \
    || bad "новый файл не подхвачен: вызовов $(calls), ожидалось 2"

# --- 4. отметка совпадает со временем файла ----------------------------------
want=$(stat -f %m "$TMP/opt/z2k-scheduler.sh" 2>/dev/null || stat -c %Y "$TMP/opt/z2k-scheduler.sh" 2>/dev/null)
have=$(cat "$TMP/stamp" 2>/dev/null)
[ -n "$have" ] && [ "$want" = "$have" ] && ok "отметка равна времени файла" \
    || bad "отметка ($have) не равна времени файла ($want)"

# --- 5. вызов стоит внутри start(), а не где-то в комментарии -----------------
body=$(awk '/^start\(\)$/{f=1} f{print} f&&/^}$/{exit}' "$INIT")
printf '%s' "$body" | grep -q '^[[:space:]]*_z2k_scheduler_sync' \
    && ok "start() вызывает _z2k_scheduler_sync" \
    || bad "start() не вызывает _z2k_scheduler_sync — функция мёртвая"

# --- 6. планировщик пишет ту же отметку при старте ----------------------------
# Иначе после перезагрузки отметки не будет и служба перезапустит только что
# поднявшийся планировщик впустую.
stamp_path=$(sed -n 's/.*Z2K_SCHED_STAMP:-\([^}]*\)}.*/\1/p' "$INIT" | head -1)
[ -n "$stamp_path" ] || stamp_path=/tmp/z2k-scheduler.mtime
grep -q "> *$stamp_path" "$SCHED" \
    && ok "планировщик пишет отметку $stamp_path при старте" \
    || bad "планировщик не пишет отметку $stamp_path — будет лишний перезапуск на каждой загрузке"

# --- 7. проба не должна зависеть от бита запуска ------------------------------
# Бит терялся на patch-пути (p-42), а гвард был строже вызова: файл на месте,
# механизм молчит. Оба места обязаны проверять читаемость и звать через sh.
if grep -q 'x "${ZAPRET2_DIR}/z2k-tcp16-probe.sh"' "$SCHED"; then
    bad "гвард пробы завязан на бит запуска — потеря бита выключает механизм молча"
else
    ok "проба не зависит от бита запуска"
fi
if grep -q 'run_task sni-refresh sh ' "$SCHED"; then
    ok "ночной перемер зовётся через sh"
else
    bad "ночной перемер зовёт файл напрямую — без бита запуска упадёт с rc 126"
fi

# --- 8. дроссель не должен держать невключённый механизм час -----------------
# Отметка дросселя лежит в /tmp и переживает переустановку. Если не разделить
# «уже мерили» и «не мерили ни разу», переустановка оставляла бы механизм
# выключенным до часа, ничем этого не показывая.
if grep -q '_sni_gap=600' "$SCHED" && grep -q '_sni_gap=3600' "$SCHED"; then
    ok "дроссель различает «мерили» и «не мерили ни разу»"
else
    bad "дроссель один на оба случая — невключённый механизм ждёт час"
fi
if grep -q 'ge "$_sni_gap"' "$SCHED"; then
    ok "сравнение идёт по выбранному дросселю"
else
    bad "дроссель вычисляется, но не используется в сравнении"
fi

echo
[ "$fails" = 0 ] && { echo "test_scheduler_code_refresh: OK"; exit 0; }
echo "test_scheduler_code_refresh: провалов $fails"; exit 1
