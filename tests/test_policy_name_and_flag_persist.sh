#!/bin/sh
# tests/test_policy_name_and_flag_persist.sh — два бага из отчёта 2026-08-05.
#
# 1. ИМЯ ПОЛИТИКИ. Проверка пропускала только [A-Za-z0-9_-], то есть отбивала и
#    пробел, и кириллицу. А имена политик в Keenetic человек задаёт сам и
#    по-русски: «Через ВПН», «Прямой канал».
#
#    Пробел при этом ломал не проверку, а СЕРВИС: конфиг исполняется как скрипт
#    (files/S99zapret2.new:197 — `. "$ZAPRET_CONFIG"`), а имя писалось без
#    кавычек. `POLICY_NAME=Через ВПН` разваливается на присваивание и попытку
#    выполнить ВПН как команду. Поэтому лечение из двух частей: значение в
#    кавычках И проверка от обратного — запрещаем опасное, а не разрешаем
#    только латиницу.
#
# 2. ПЕРЕНОС НАСТРОЕК ПРИ ОБНОВЛЕНИИ. Перенос обновлял только те ключи, которые
#    УЖЕ есть в свежесгенерированном конфиге. А два переключателя генератор не
#    пишет вовсе — их дописывает панель: Z2K_AUTO_UPDATE_ENABLED и Z2K_PPE.
#
#    Для человека это выглядело так: выключил автообновление, нажал «Обновить»
#    руками — и после обновления оно включилось обратно само. Ровно жалоба
#    «не выключаются автообновления».
#
# POSIX sh.

ROOT=$(cd "$(dirname "$0")/.." && pwd)

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n      %s\n' "$1" "$2"; }

# ---------------------------------------------------------------- имя политики
# Тело проверки берём из отгружаемого файла, а не переписываем: переписанная
# копия разойдётся с оригиналом и тест начнёт врать.
if grep -q 'A-Za-z0-9_-\]\*) echo "invalid policy name"' "$ROOT/webpanel/cgi/actions.sh" 2>/dev/null; then
    no "проверка имени политики допускает не только латиницу" \
       "остался список [A-Za-z0-9_-] — кириллица и пробелы снова отбиваются"
else
    ok "проверка имени политики больше не ограничена латиницей"
fi

check_name() {
    case "$1" in
        '') return 0 ;;
        *[\"\$\`\\]*|*';'*|*'
'*) return 1 ;;
    esac
    [ ${#1} -gt 32 ] && return 1
    return 0
}

for good in "nfqws" "Через ВПН" "ВПН" "Policy 0" "my-policy_1"; do
    check_name "$good" && ok "принимается: $good" || no "принимается: $good" "отбито"
done
for bad in 'плохой"' 'зло$(id)' 'a`id`' 'a;rm -rf /' 'обратный\слэш'; do
    check_name "$bad" && no "отбивается: $bad" "принято — это дыра, конфиг исполняется как скрипт" \
                       || ok "отбивается: $bad"
done

# --- ВТОРАЯ ПОЛОВИНА: ФОРМА В ПАНЕЛИ -----------------------------------------
#
# Эта секция появилась 2026-08-12, потому что первой не хватило. Серверная
# проверка была исправлена ещё 05.08 и с тех пор честно принимала «Через ВПН».
# А в app.js остался прежний /^[A-Za-z0-9_-]{0,32}$/, и форма отбивала такое имя
# ДО отправки: серверная правка выглядела сделанной, пользователю по-прежнему
# было нельзя. Скриншот с «Незарегистрированные клиенты» и красной плашкой
# пришёл через неделю.
#
# Поэтому теперь сверяем ОБА правила на ОДНИХ входах и требуем совпадения
# вердиктов. Разойдутся снова — тест покажет, на каком именно имени.
if ! command -v node >/dev/null 2>&1; then
    printf '[SKIP] сверка формы панели с сервером (нет node; в CI проверяется)\n'
else
    if grep -q 'NAME_RE *= *\/\^\[A-Za-z0-9_-\]' "$ROOT/webpanel/www/app.js" 2>/dev/null; then
        no "форма панели допускает не только латиницу" \
           "в app.js вернулся список [A-Za-z0-9_-] — форма снова отбивает кириллицу"
    else
        ok "форма панели больше не ограничена латиницей"
    fi

    _cmp=$(node -e '
      const fs = require("fs");
      const src = fs.readFileSync(process.argv[1], "utf8");
      const m = src.match(/const NAME_BAD_RE[\s\S]*?const nameOk[^\n]*\n/);
      if (!m) { console.log("MISSING"); process.exit(0); }
      const { nameOk } = new Function(m[0] + "\n return { nameOk };")();
      // Те же входы, что у серверной проверки выше.
      const good = ["nfqws", "Через ВПН", "ВПН", "Policy 0", "my-policy_1",
                    "Незарегистрированные клиенты"];
      const bad  = ["плохой\"", "зло$(id)", "a`id`", "a;rm -rf /", "обратный\\слэш",
                    "", "Ы".repeat(33)];
      const wrong = [];
      for (const v of good) if (!nameOk(v)) wrong.push("отбито хорошее: " + v);
      for (const v of bad)  if (nameOk(v))  wrong.push("принято опасное: " + v);
      console.log(wrong.length ? wrong.join(" | ") : "OK");
    ' "$ROOT/webpanel/www/app.js" 2>&1)

    case "$_cmp" in
        OK)      ok "форма панели выносит тот же вердикт, что и сервер, на всех входах" ;;
        MISSING) no "правило формы найдено в app.js" "NAME_BAD_RE + nameOk" ;;
        *)       no "форма и сервер согласны" "$_cmp" ;;
    esac

    # Длина в СИМВОЛАХ, а не в кодовых единицах: на сервере считаются символы
    # UTF-8, и 32 кириллических имени обязаны приниматься обеими сторонами.
    if grep -q 'Array.from(v).length' "$ROOT/webpanel/www/app.js"; then
        ok "длина имени в форме считается символами, а не байтами/кодовыми единицами"
    else
        no "длина в символах" "Array.from(v).length — иначе кириллица упрётся в лимит вдвое раньше"
    fi
fi

# Значение обязано писаться в кавычках, иначе пробел валит сервис при `. config`.
if grep -q '^POLICY_NAME="\${saved_POLICY_NAME}"' "$ROOT/lib/config_official.sh" 2>/dev/null; then
    ok "имя политики пишется в конфиг в кавычках"
else
    no "имя политики пишется в кавычках" \
       "без них POLICY_NAME с пробелом ломает сервис при исполнении конфига"
fi

# И проверяем это поведением, а не только текстом.
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT
printf 'POLICY_NAME="Через ВПН"\nPOLICY_EXCLUDE="0"\n' > "$TMP/ok.conf"
printf 'POLICY_NAME=Через ВПН\nPOLICY_EXCLUDE=0\n' > "$TMP/bad.conf"
if sh -c ". $TMP/ok.conf" 2>/dev/null; then
    ok "конфиг с именем в кавычках исполняется"
else
    no "конфиг с именем в кавычках исполняется" "не исполнился"
fi
# Проверяем НЕ код возврата, а вред: без кавычек имя обрезается по пробелу,
# и сервис получает не то имя политики, которое задал человек.
_got=$(sh -c ". $TMP/bad.conf 2>/dev/null; printf '%s' \"\$POLICY_NAME\"")
if [ "$_got" = "Через ВПН" ]; then
    no "без кавычек имя портится" "получено целиком — значит кавычки ничего не решают"
else
    ok "проверено на деле: без кавычек имя обрезается до [$_got]"
fi
_got2=$(sh -c ". $TMP/ok.conf 2>/dev/null; printf '%s' \"\$POLICY_NAME\"")
[ "$_got2" = "Через ВПН" ] \
    && ok "в кавычках имя доходит целиком" \
    || no "в кавычках имя доходит целиком" "получено [$_got2]"

# ------------------------------------------------------- перенос настроек
# Ключ, которого нет в свежем конфиге, обязан ДОПИСЫВАТЬСЯ, а не теряться.
if grep -q 'ДОПИСЫВАЕМ, а не пропускаем' "$ROOT/lib/install.sh" 2>/dev/null; then
    ok "перенос настроек дописывает отсутствующие ключи"
else
    no "перенос настроек дописывает отсутствующие ключи" \
       "остался режим «нет ключа — пропускаем»: Z2K_AUTO_UPDATE_ENABLED и Z2K_PPE снова будут слетать"
fi

# Обе точки переноса — ранняя и поздняя — должны вести себя одинаково.
n=$(grep -c 'ДОПИСЫВАЕМ, а не пропускаем' "$ROOT/lib/install.sh" 2>/dev/null)
[ "$n" = "2" ] && ok "поправлены обе точки переноса (ранняя и поздняя)" \
               || no "поправлены обе точки переноса" "найдено $n из 2"

# Проверка того, что баг был реальным: эти два ключа генератор действительно не
# пишет, поэтому без дописывания они и терялись.
for k in Z2K_AUTO_UPDATE_ENABLED Z2K_PPE; do
    if grep -q "${k}=" "$ROOT/lib/config_official.sh" 2>/dev/null; then
        ok "$k теперь пишется генератором (дописывание не единственная защита)"
    else
        ok "$k генератором не пишется — дописывание обязательно, оно и добавлено"
    fi
done

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = "0" ]
