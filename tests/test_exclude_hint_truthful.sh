#!/bin/sh
# tests/test_exclude_hint_truthful.sh — подсказка рядом со списком адресов не
# должна обещать того, чего нет.
#
# ЧТО БЫЛО. Файл-спутник zapret-hosts-user-exclude.README.txt утверждал:
# «Комментарии после # и пустые строки допустимы — они срезаются при чтении».
# Неправда. Список уходит в ipset/def.sh → filedigger → mdig, а zzcat в этой
# цепочке — обычный cat и не срезает ничего. Строка «203.0.113.10  # камера»
# уходит резолверу целиком, тот её не понимает и МОЛЧА выбрасывает вместе с
# адресом. Исключение выглядит записанным, а его нет.
#
# Проверено прогоном настоящего mdig 02.09.2026: из трёх строк (адрес с
# концевым комментарием, голый адрес, комментарий отдельной строкой) вернулся
# только голый адрес.
#
# При этом README проекта в том же месте говорил ВЕРНО и ровно обратное. Два
# наших документа противоречили друг другу, и пострадал тот, кто открыл
# ближайший к файлу.
#
# ПОЧЕМУ ЗДЕСЬ ГРЕП, А НЕ ИСПОЛНЕНИЕ. Проверяемый артефакт — сам текст: он и
# есть то, что читает человек. Поведение резолвера проверить offline нечем,
# mdig на машине сборки нет. Поэтому сторожим ровно одно: подсказка не обещает
# срезания концевых комментариев и предупреждает о них, а README не разошёлся
# с ней обратно.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
INIT="$ROOT/files/S99zapret2.new"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT

# Текст подсказки берём из init'а исполнением heredoc'а, а не глазами: так
# проверяется то, что реально ляжет на роутер.
awk '/local doc=.*zapret-hosts-user-exclude\.README\.txt/,/^Z2KEXCL$/' "$INIT" \
    | sed -n '/<</,$p' | sed '1d;$d' > "$SB/hint.txt"
if [ ! -s "$SB/hint.txt" ]; then
    # Запасной путь: вырезать между маркерами содержимого.
    awk '/^Исключения из обхода/,/^Удобнее всего править через веб-панель/' "$INIT" > "$SB/hint.txt"
fi
[ -s "$SB/hint.txt" ] || { bad "не нашёл текст подсказки в S99zapret2.new"
                           printf '\nPASSED: 0\nFAILED: 1\n'; exit 1; }

# --- 1. Ложного обещания больше нет -------------------------------------------
if grep -q 'допустимы — они срезаются при чтении' "$SB/hint.txt"; then
    bad "подсказка снова обещает срезание комментариев — это неправда"
else
    ok "ложного обещания про срезание комментариев нет"
fi

# --- 2. Про концевой комментарий сказано прямо --------------------------------
if grep -q 'В КОНЦЕ строки' "$SB/hint.txt"; then
    ok "подсказка предупреждает про комментарий в конце строки"
else
    bad "нет предупреждения про концевой комментарий — грабли остались без таблички"
fi

# --- 3. Сказано, что потеря МОЛЧАЛИВАЯ ----------------------------------------
# Без этого человек будет искать ошибку в журнале, которой там нет.
if grep -qi 'молча' "$SB/hint.txt"; then
    ok "сказано, что адрес пропадает молча" 
else
    bad "не сказано про молчаливую потерю — человек пойдёт искать ошибку в журнале"
fi

# --- 4. README проекта не противоречит подсказке ------------------------------
# Ровно это и было настоящим дефектом: два наших документа расходились.
if grep -q 'комментарии и пустые строки туда добавлять нельзя' "$ROOT/README.md"; then
    ok "README и подсказка говорят одно и то же"
else
    bad "README изменился и мог разойтись с подсказкой — сверьте оба текста"
fi

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
