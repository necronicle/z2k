#!/bin/sh
# tests/test_exclude_hint_truthful.sh — подсказка рядом со списком адресов
# обязана описывать то, что делает засев, и ничего сверх.
#
# ИСТОРИЯ. Файл читали двое в РАЗНЫХ грамматиках: засев z2k (срезает
# комментарий после «#», пропускает строки-не-адреса) и апстримная ночная
# пересборка ipset/get_config.sh -> mdig (строка целиком, домены разрешаются,
# затем `ipset flush nozapret`). Подсказка сначала описывала первую, утром
# 02.09.2026 её переписали под вторую («комментарий в конце уносит адрес»),
# и оба раза она была верна лишь наполовину — потому что читателей было два.
# Отчёт с точки babka (01–02.09.2026): из 14 адресов в сете 4, доменная
# строка разрешилась и утащила в исключения общий адрес CDN.
#
# Ночная пересборка из планировщика убрана (tests/test_no_upstream_ipset_job.sh),
# читатель остался один — засев. Его поведение проверяется исполнением в
# tests/test_local_exclusions.sh (п. 9–11). Здесь сторожится ТЕКСТ: он и есть
# то, что читает человек, и он обязан совпадать с засевом и с README проекта.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
INIT="$ROOT/files/S99zapret2.new"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT

# Текст подсказки берём из init'а исполнением heredoc'а, а не глазами: так
# проверяется то, что реально ляжет на роутер.
ENSURE=$(awk '/^z2k_ensure_user_exclude_file\(\)/{i=1} i{print} i&&/^\}/{exit}' "$INIT")
mkdir -p "$SB/ipset"
ZAPRET_BASE="$SB" sh -c "$ENSURE
z2k_ensure_user_exclude_file" >/dev/null 2>&1
HINT="$SB/ipset/zapret-hosts-user-exclude.README.txt"
[ -s "$HINT" ] || { bad "z2k_ensure_user_exclude_file не создала подсказку"
                    printf '\nPASSED: 0\nFAILED: 1\n'; exit 1; }

# --- 1. Комментарий после # разрешён и сказано об этом прямо -----------------
if grep -q 'Комментарии после #' "$HINT" && grep -q '# камера' "$HINT"; then
    ok "подсказка разрешает комментарий после # и показывает пример"
else
    bad "подсказка не говорит, что комментарий после # допустим"
fi
if grep -qi 'уносит' "$HINT"; then
    bad "подсказка снова пугает, что комментарий в конце строки уносит адрес — это было верно только для убранной ночной пересборки"
else
    ok "ложного запрета на комментарий в конце строки нет"
fi

# --- 2. Про домены сказано честно: не разрешаются, не действуют, об этом
#        сообщается ----------------------------------------------------------
if grep -qi 'не разреша' "$HINT"; then
    ok "сказано, что доменная строка НЕ разрешается в адреса"
else
    bad "не сказано, что домен не разрешается — человек может ждать, что его подхватят"
fi
if grep -qi 'сколько' "$HINT"; then
    ok "сказано, что о пропущенных строках сообщается при старте"
else
    bad "не сказано, что пропуск строки виден в выводе — потеря снова выглядит молчаливой"
fi

# --- 3. Когда правка руками начинает действовать ------------------------------
# Ночной пересборки больше нет; единственный момент чтения файла — старт
# файрвола. Панель кладёт адрес в живой сет сразу. Умолчать — значит получить
# «вписал, не работает».
if grep -qi 'перезапуск' "$HINT" && grep -qi 'сразу' "$HINT"; then
    ok "сказано, что панель применяет сразу, а правка файла — после перезапуска"
else
    bad "не сказано, когда правка файла вступает в силу"
fi

# --- 4. README проекта не противоречит подсказке ------------------------------
README="$ROOT/README.md"
if grep -q 'комментарии после `#`' "$README"; then
    ok "README разрешает комментарии после # (совпадает с подсказкой)"
else
    bad "README не говорит, что комментарии после # допустимы"
fi
if grep -q 'комментарии и пустые строки туда добавлять нельзя' "$README"; then
    bad "README всё ещё запрещает комментарии — противоречит подсказке и засеву"
else
    ok "README не запрещает комментарии"
fi

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
