#!/bin/sh
# tests/test_install_lists_match_map.sh — установка и обновление кладут ОДНИ И ТЕ
# ЖЕ файлы списков.
#
# ЧТО СЛУЧИЛОСЬ. Обновление кладёт файлы по карте install_map, а установщик — по
# ЗАШИТОМУ списку имён в lib/install.sh. Списки разъехались молча: три файла
# механизма обхода блока по объёму (мишени, кандидаты имён, карта сетей) были в
# карте, но не в установщике. При обновлении они приезжали, при чистой установке
# — нет.
#
# Наружу это выглядело как «механизм не работает»: у людей, поставивших z2k
# начисто, проба честно отвечала «нет списка мишеней» и уходила. Четыре выпуска
# чинили доставку, пока причина была в установке. Найдено на чистой установке
# 31.08.2026, а не тестом — поэтому тест и появился.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# Что карта обещает положить прямо в lists/ (не в files/lists — это промежуточный
# каталог, из которого установщик и копирует).
FROM_MAP=$(python3 - "$ROOT/UPDATES.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
out = set()
for src, dsts in d.get("install_map", {}).items():
    if not src.startswith("files/lists/"):
        continue
    for dst in (dsts if isinstance(dsts, list) else [dsts]):
        if dst.startswith("/opt/zapret2/lists/") and dst.count("/") == 4:
            out.add(dst.rsplit("/", 1)[1])
print("\n".join(sorted(out)))
PY
)
[ -n "$FROM_MAP" ] || { bad "карта install_map не отдала ни одного файла lists/"; printf '\nFAILED: 1\n'; exit 1; }

# Что установщик вообще знает. Проверяем УПОМИНАНИЕ имени в lib/install.sh, а не
# конкретный цикл: файлы попадают в lists/ несколькими путями — общий цикл,
# отдельная логика сохранения пользовательских правок, отдельный перенос через
# переустановку. Разбирать каждый путь значило бы дублировать установщик в
# тесте. Признак, который ловит НАСТОЯЩИЙ дефект: имени нет в установщике вовсе,
# то есть положить его он не может никак.
miss=""
for f in $FROM_MAP; do
    grep -q -- "$f" "$ROOT/lib/install.sh" || miss="$miss $f"
done

if [ -z "$miss" ]; then
    ok "установщик знает все файлы списков, обещанные картой"
else
    bad "обновление положит, а чистая установка — нет:$miss"
fi

# Отдельно и поимённо — файлы механизма: именно на них обожглись.
for f in tcp16_targets.txt sni_wl_candidates.txt tcp16_nets.txt; do
    grep -q -- "$f" "$ROOT/lib/install.sh" \
        && ok "$f кладётся при чистой установке" \
        || bad "$f при чистой установке не появится — механизм не заработает"
done

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
