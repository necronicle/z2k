#!/bin/sh
# tests/test_diag_web_port.sh — строки про вебморду в диагностике обязаны говорить
# про ОДИН И ТОТ ЖЕ порт.
#
# ЧТО БЫЛО. Порт читался из конфигурации роутера в переменную, а держателя искали
# по зашитому :80. У перенёсшего порт выходило «порт вебморды: 8080» и следом
# «кто держит :80: никто — вебморда не поднялась», хотя она жива. А если на
# освободившийся 80-й вставала наша же панель, отчёт клеветал на неё диагнозом
# «отнимает вебморду роутера». То есть врало ровно тем, ради кого добавлено.
#
# Проверяется ИСПОЛНЕНИЕМ настоящего блока из files/z2k-diag.sh с подставными
# ndmc и netstat.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT
mkdir -p "$SB/bin"

cat > "$SB/bin/ndmc" <<'STUB'
#!/bin/sh
cat "$NDM_CONF" 2>/dev/null
STUB
cat > "$SB/bin/netstat" <<'STUB'
#!/bin/sh
cat "$NETSTAT_OUT" 2>/dev/null
STUB
chmod +x "$SB/bin/ndmc" "$SB/bin/netstat"

# Блок берём настоящий: от комментария-маркера до закрывающего esac.
awk '/Держателя ищем на ТОМ порту/,/^    esac$/' "$ROOT/files/z2k-diag.sh" > "$SB/blk.sh"
[ -s "$SB/blk.sh" ] || { bad "не нашёл блок в z2k-diag.sh — проверка ослепла"
                         printf '\nPASSED: 0\nFAILED: 1\n'; exit 1; }
# local вне функции dash не принимает — снимаем, переменные и так свои.
sed -i.bak 's/^    local .*//' "$SB/blk.sh"

run() {  # run <running-config> <netstat>
    printf '%s\n' "$1" > "$SB/ndm.conf"
    printf '%s\n' "$2" > "$SB/ns.out"
    env PATH="$SB/bin:$PATH" NDM_CONF="$SB/ndm.conf" NETSTAT_OUT="$SB/ns.out" \
        "${Z2K_TEST_SH:-sh}" "$SB/blk.sh" 2>/dev/null
}

NS_NDM_80='tcp 0 0 192.168.1.1:80 0.0.0.0:* LISTEN 911/null'
NS_NDM_8080='tcp 0 0 192.168.1.1:8080 0.0.0.0:* LISTEN 911/null'
NS_LIGHTTPD_80='tcp 0 0 0.0.0.0:80 0.0.0.0:* LISTEN 1353/lighttpd'

# --- 1. Умолчание: порт 80, держатель оттуда же -------------------------------
out=$(run 'ip http security-level private' "$NS_NDM_80")
case "$out" in
    *'порт вебморды     : 80 (умолчание)'*) ok "без строки в конфигурации сообщается умолчание" ;;
    *) bad "умолчание не сообщено: [$out]" ;;
esac
case "$out" in
    *911/null*) ok "держатель найден на умолчательном порту" ;;
    *) bad "держатель на 80 не найден: [$out]" ;;
esac

# --- 2. Порт перенесён — держателя ищем ТАМ ЖЕ --------------------------------
# Это и есть исходный дефект: раньше здесь выходило «никто», хотя морда жива.
out=$(run 'ip http port 8080' "$NS_NDM_8080")
case "$out" in
    *'порт вебморды     : 8080'*) ok "перенесённый порт прочитан" ;;
    *) bad "перенесённый порт не прочитан: [$out]" ;;
esac
case "$out" in
    *'никто'*) bad "ложная тревога: морда жива на 8080, а отчёт говорит «не поднялась»" ;;
    *911/null*) ok "держатель найден на перенесённом порту" ;;
    *) bad "непонятный вывод: [$out]" ;;
esac

# --- 3. На освободившемся 80 наша панель — клеветать нельзя -------------------
out=$(run 'ip http port 8080' "$NS_NDM_8080
$NS_LIGHTTPD_80")
case "$out" in
    *ПЛОХО*) bad "отчёт обвиняет lighttpd на 80, хотя морда переехала на 8080: [$out]" ;;
    *) ok "чужой lighttpd на свободном 80 не объявляется виновным" ;;
esac

# --- 4. Настоящий диагноз сохранён --------------------------------------------
# Ради этого случая строки и добавлялись: пакетный lighttpd отнял порт морды.
out=$(run 'ip http security-level private' "$NS_LIGHTTPD_80")
case "$out" in
    *'1353/lighttpd — ПЛОХО'*) ok "lighttpd на порту морды по-прежнему диагноз" ;;
    *) bad "главный диагноз потерян: [$out]" ;;
esac

# --- 5. Порт свободен — так и говорим -----------------------------------------
out=$(run 'ip http port 8080' "$NS_LIGHTTPD_80")
case "$out" in
    *'никто — вебморда роутера не поднялась'*) ok "мёртвая морда на своём порту распознана" ;;
    *) bad "мёртвая морда не распознана: [$out]" ;;
esac

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
