#!/bin/sh
# tests/test_verify_then_commit.sh — сначала всё проверено, потом что-то меняется.
#
# СВОЙСТВО. Обновление не имеет права начать раскладывать файлы, пока не
# убедилось, что готовы ВСЕ. Иначе обрыв на середине оставляет дерево
# полусобранным: часть файлов новая, часть старая, и такое состояние патчем не
# лечится по построению — патч кладёт только изменённые файлы и достроит один
# гибрид до другого.
#
# ЭТО НЕ ГИПОТЕЗА. Именно так выглядел откат, возвращавший успех после
# восстановления половины файлов; и именно поэтому появился маркер смешанного
# дерева, принудительно уводящий следующее обновление в reinstall.
#
# Тест закрепляет то, что уже сделано правильно, а не требует переделки:
#   1) скачивание ВСЕХ файлов идёт до первой установки;
#   2) первый же несостоявшийся файл прерывает обновление;
#   3) у каждого скачивания есть ожидаемый дайджест, где манифест его знает.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
AU="$ROOT/lib/auto_update.sh"
INS="$ROOT/lib/install.sh"
for f in "$AU" "$INS"; do [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }; done

BODY=$(awk '/^au_apply_patch\(\)/,/^\}/' "$AU")
[ -n "$BODY" ] || { printf '[FAIL] не нашёл au_apply_patch\n'; exit 1; }

# --- 1. Порядок: скачали всё → только потом ставим ----------------------------
_dl=$(printf '%s\n' "$BODY" | grep -n 'download all files first' | head -1 | cut -d: -f1)
_inst=$(printf '%s\n' "$BODY" | grep -n 'install each file' | head -1 | cut -d: -f1)
if [ -n "$_dl" ] && [ -n "$_inst" ] && [ "$_dl" -lt "$_inst" ]; then
    ok "скачивание всех файлов идёт до установки (строка $_dl < $_inst)"
else
    no "скачивание идёт до установки" "download раньше install" "dl=$_dl inst=$_inst"
fi

# --- 2. Первый провал прерывает ДО установки ----------------------------------
_abort=$(printf '%s\n' "$BODY" | grep -n 'failed to download .* aborting' | head -1 | cut -d: -f1)
if [ -n "$_abort" ] && [ -n "$_inst" ] && [ "$_abort" -lt "$_inst" ]; then
    ok "провал скачивания прерывает обновление до первой установки"
else
    no "провал прерывает до установки" "abort раньше install" "abort=$_abort inst=$_inst"
fi

# И прерывает именно возвратом ошибки, а не продолжением цикла.
if printf '%s\n' "$BODY" | sed -n "$((_abort)),$((_abort + 2))p" | grep -q 'return 1'; then
    ok "прерывание — это return 1, а не continue"
else
    no "прерывание — return 1" "return 1 рядом с abort" "не найдено"
fi

# --- 3. У скачивания есть ожидаемый дайджест ----------------------------------
#
# Без него staging «укомплектован» ничего не значит: файл на месте, но не тот.
# Ожидание уехало из глобальной переменной в параметр загрузчика 26.08.2026:
# так его нельзя забыть в одном из вызовов, а забытым он и был — в сходимости.
if printf '%s\n' "$BODY" | grep -q 'au_download_repo_file "\$repo_path" "\$stage" "\$_want_sha"'; then
    ok "патч передаёт фетчеру ожидаемый sha256"
else
    no "патч передаёт ожидаемый sha256" "третьим параметром загрузчика" "не найдено"
fi

# Отсутствие дайджеста должно быть ЗАМЕТНЫМ, а не молчаливым.
if printf '%s\n' "$BODY" | grep -q 'в манифесте нет sha256'; then
    ok "файл без дайджеста в манифесте попадает в лог"
else
    no "файл без дайджеста попадает в лог" "запись в лог" "молчит"
fi

# --- 4. Reinstall: критичное стейджится до первого изменения дерева -----------
#
# У переустановки та же логика, но своя: хостлисты складываются в staging ДО
# того, как что-либо будет тронуто, и недоступность любого из них прерывает
# установку, не удалив рабочую копию.
if grep -q '^step_prefetch_hostlists()' "$INS"; then
    ok "у переустановки есть отдельная фаза предзагрузки"
else
    no "у переустановки есть фаза предзагрузки" "step_prefetch_hostlists" "не найдено"
fi

_pf=$(grep -n 'step_prefetch_hostlists || return 1' "$INS" | head -1 | cut -d: -f1)
_rm=$(grep -n 'mv "\$ZAPRET2_DIR" "\$_old_tree"' "$INS" | head -1 | cut -d: -f1)
if [ -n "$_pf" ] && [ -n "$_rm" ] && [ "$_pf" -lt "$_rm" ]; then
    ok "предзагрузка идёт до того, как дерево сдвинуто (строка $_pf < $_rm)"
else
    no "предзагрузка до сдвига дерева" "prefetch раньше mv" "prefetch=$_pf mv=$_rm"
fi

# Недоступный критичный список обязан ронять установку, а не пропускаться.
if awk '/^step_prefetch_hostlists\(\)/,/^\}/' "$INS" | grep -q 'die "Pre-flight'; then
    ok "недоступный критичный список прерывает установку"
else
    no "недоступный список прерывает установку" "die в фазе предзагрузки" "не найдено"
fi

# --- 5. Неполный откат не выдаётся за успех -----------------------------------
#
# Обратная сторона того же свойства: если дерево всё-таки осталось смешанным,
# это должно быть зафиксировано, а не забыто.
if grep -q 'au_mark_dirty_tree' "$AU" && grep -q 'au_tree_is_dirty' "$AU"; then
    ok "смешанное дерево помечается и учитывается при следующем решении"
else
    no "смешанное дерево помечается" "au_mark_dirty_tree + au_tree_is_dirty" "не найдено"
fi

if awk '/^au_decide\(\)/,/^\}/' "$AU" | grep -q 'au_tree_is_dirty'; then
    ok "маркер смешанного дерева принудительно уводит в reinstall"
else
    no "маркер уводит в reinstall" "проверка в au_decide" "не найдено"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
