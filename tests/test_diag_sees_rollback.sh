#!/bin/sh
# tests/test_diag_sees_rollback.sh — откат обновления виден в диагностике.
#
# ЗАЧЕМ. Детектор искал в журнале строку «rolling back», а её пишет ТОЛЬКО
# патч-путь (au_apply_patch). С r-79.7 все обновляются сходимостью, и она
# пишет по-русски: «доставка не удалась — откат», «шаги провалились — откат»,
# «rollback: restoring pre-apply files». То есть откат перестал быть виден
# диагностике ровно тогда, когда сменился путь обновления.
#
# Поле 2026-08-27: роутер откатился ДВА РАЗА подряд по ночам (p-79.12 →
# p-79.17 и p-79.18), простоял на старой версии двое суток, а сводка «что не
# так» отвечала «явных проблем не найдено». Человек узнал об этом только
# потому, что нажал обновление руками.
#
# POSIX sh.
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
assert_eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }
ROOT=$(cd "$(dirname "$0")/.." && pwd)
DIAG="$ROOT/files/z2k-diag.sh"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT INT TERM

# Блок детектора берём ИЗ ИСХОДНИКА, а не переписываем: копия разошлась бы с
# оригиналом на первой же правке и зеленела бы на сломанном коде.
# `local` вне функции — синтаксическая ошибка в dash; снимаем ключевое слово
# вместо того, чтобы объявлять функцию с таким именем.
sed -n '/local _aulog=/,/^    fi$/p' "$DIAG" \
    | sed -e 's#/opt/var/log/z2k-auto-update.log#'"$SB"'/au.log#' \
          -e 's/^\([[:space:]]*\)local /\1/' > "$SB/blk.sh"
[ -s "$SB/blk.sh" ] || { printf '[FAIL] блок детектора не извлёкся\n'; exit 1; }

verdict() {
    printf '%s\n' "$1" > "$SB/au.log"
    sh -c '
        _add() { printf "%s\n" "$1"; }
        . "'"$SB"'/blk.sh"
    ' 2>&1
}

# --- 1. Сходимость: файл не скачался (ровно случай из поля) -------------------
_v=$(verdict '[2026-08-27 03:25:34] новый путь: p-79.12 -> p-79.18
[2026-08-27 03:25:36] сходимость: расходится файлов — 35
[2026-08-27 03:27:29] сходимость: не скачался files/lists/warp-endpoints.txt
[2026-08-27 03:27:29] доставка не удалась — откат
[2026-08-27 03:27:29] rollback: restoring pre-apply files
[2026-08-27 03:27:34] rollback: восстановлены все файлы')
case "$_v" in
    *"последнее обновление откатилось"*) ok "откат сходимости замечен" ;;
    *) no "откат сходимости замечен" "строка про откат" "${_v:-тишина}" ;;
esac
case "$_v" in
    *"не скачался files/lists/warp-endpoints.txt"*) ok "причина названа поимённо" ;;
    *) no "причина названа поимённо" "имя файла" "$_v" ;;
esac

# --- 2. Вето валидатора (ровно случай r-80, лёгший на весь флот) --------------
_v=$(verdict '[2026-08-27 01:18:53] validate-config: конфиг не прошёл проверку (код 2) — вето на перезапуск
[2026-08-27 01:18:53] шаги провалились — откат
[2026-08-27 01:18:53] rollback: restoring pre-apply files
[2026-08-27 01:18:56] rollback: восстановлены все файлы')
case "$_v" in
    *"откатилось"*"validate-config"*) ok "вето валидатора названо причиной" ;;
    *) no "вето валидатора названо причиной" "validate-config" "${_v:-тишина}" ;;
esac

# --- 3. Старый апдейтер (патч-путь) по-прежнему опознаётся --------------------
_v=$(verdict '[2026-08-20 02:00:00] patch apply failed, rolling back')
case "$_v" in
    *"откатилось"*) ok "патч-путь со старым текстом тоже опознан" ;;
    *) no "патч-путь со старым текстом тоже опознан" "строка про откат" "${_v:-тишина}" ;;
esac

# --- 4. Удачное обновление тревоги не поднимает -------------------------------
_v=$(verdict '[2026-08-27 18:56:17] новый путь: p-79.12 -> r-80.2
[2026-08-27 19:00:45] health-check: 5s stability window, then checking
[2026-08-27 19:00:51] health-check OK
[2026-08-27 19:00:51] обновление завершено: r-80.2')
assert_eq "успешное обновление не тревожит" "" "$_v"

# --- 5. Старый откат, после которого всё наладилось, тоже молчит --------------
_v=$(verdict "$(echo '[2026-08-20] rollback: restoring pre-apply files'
                i=0; while [ $i -lt 45 ]; do echo "[2026-08-2$i] обновление завершено: r-80.2"; i=$((i+1)); done)")
assert_eq "откат за пределами хвоста не тревожит" "" "$_v"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
