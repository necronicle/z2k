#!/bin/sh
# tests/test_initd_detach.sh — фоновые надзиратели обязаны отвязываться от
# потоков init-скрипта.
#
# NDM запускает /opt/etc/init.d/* по очереди и ЧИТАЕТ вывод каждого до конца
# потока — именно так строки скриптов попадают в системный журнал. Фоновый
# надзиратель, запущенный голым `( ... ) &`, наследует этот поток и держит его
# открытым всё время жизни. Конца не наступает никогда: NDM ждёт и к следующему
# скрипту не переходит.
#
# Цена — вся загрузка. В отчёте 2026-08-05 цепочка встала на S96z2k-rt-proxy:
# веб-панель, http-туннель, планировщик и сам zapret2 не поднялись, человек ждал
# двадцать минут и запускал их руками. Болели все пять скриптов: у S51z2k-warp
# одна подоболочка была отвязана, а две — нет, и он идёт РАНЬШЕ S96, то есть у
# людей с включённым WARP загрузка вставала ещё раньше. Снаружи это не видно
# ничем, кроме отсутствия сервисов после перезагрузки.
#
# POSIX sh.

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DIR="$ROOT/files/init.d"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n      %s\n' "$1" "$2"; }
summary() { printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"; [ "$FAIL" = "0" ]; }

if [ ! -d "$DIR" ]; then
    no "каталог init.d найден" "нет $DIR"
    summary; exit 1
fi

checked=0
bad=""
for f in "$DIR"/S*; do
    [ -f "$f" ] || continue
    # Скрипт нас интересует, только если он что-то уводит в фон подоболочкой.
    grep -qE '^[[:space:]]*\).*&[[:space:]]*$' "$f" 2>/dev/null || continue
    checked=$((checked + 1))
    # Голое `) &` — без перенаправления — и есть поломка.
    if grep -qE '^[[:space:]]*\)[[:space:]]*&[[:space:]]*$' "$f" 2>/dev/null; then
        bad="$bad $(basename "$f")"
    fi
done

if [ "$checked" = "0" ]; then
    no "найдены скрипты с фоновой подоболочкой" "ни одного — проверка ничего не проверяет"
else
    ok "проверено скриптов с фоновой подоболочкой: $checked"
fi

if [ -z "$bad" ]; then
    ok "все фоновые надзиратели отвязаны от потоков init-скрипта"
else
    no "все фоновые надзиратели отвязаны" \
       "голое \`) &\` в:$bad — NDM встанет на первом из них и не запустит остальные сервисы"
fi

# Поведение целиком: убеждаемся, что разница реальна, а не вычитана из
# документации.
#
# Ребёнок живёт ОГРАНИЧЕННОЕ время и завершается сам. Первая версия этого теста
# держала бесконечный цикл и убивала его по метке через pkill — но метку я
# положил в текст скрипта, а в командной строке её нет, поэтому уборка не
# срабатывала, процессы оставались, и весь прогон вставал на этом тесте. Тест,
# оставляющий за собой мусор, — это тот же баг, что он проверяет.
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT

HOLD=6
cat > "$TMP/bad.sh" <<S
#!/bin/sh
echo start
( sleep $HOLD ) &
echo done
S
cat > "$TMP/good.sh" <<S
#!/bin/sh
echo start
( sleep $HOLD ) >/dev/null 2>&1 </dev/null &
echo done
S
chmod +x "$TMP/bad.sh" "$TMP/good.sh"

# Сколько секунд читатель ждёт конца потока — ровно то, что делает NDM.
elapsed() {
    _t0=$(date +%s)
    sh "$1" | cat > /dev/null
    _t1=$(date +%s)
    echo $((_t1 - _t0))
}

_bad=$(elapsed "$TMP/bad.sh")
_good=$(elapsed "$TMP/good.sh")

if [ "$_bad" -ge 3 ]; then
    ok "проверено на деле: с голым \`) &\` поток держится (${_bad} с)"
else
    no "с голым \`) &\` поток держится" "закрылся за ${_bad} с — значит проверка выше бессмысленна"
fi

if [ "$_good" -le 1 ]; then
    ok "проверено на деле: отвязанная подоболочка отпускает поток сразу (${_good} с)"
else
    no "отвязанная подоболочка отпускает поток" "ждали ${_good} с — лечение не лечит"
fi

summary
