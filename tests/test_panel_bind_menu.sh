#!/bin/sh
# tests/test_panel_bind_menu.sh — адрес и порт панели задаются из терминала
# и переживают обновление.
#
# ЖАЛОБА. Человек сменил адрес, на котором слушает веб-панель, и после каждой
# обновы получал автоопределённый обратно — правку приходилось повторять изо
# дня в день.
#
# ПОЧЕМУ ТАК БЫЛО. lighttpd.conf генерируется из шаблона при каждой установке
# (@BIND@ / @PORT@), поэтому правка файла руками стиралась. Установщик умеет
# принимать адрес флагом --bind и переигрывать его при переустановке, но
# только по маркеру bind.explicit, а маркер ставится ровно тогда, когда флаг
# передали. Способа передать его, не набирая команду руками, не было.
#
# ПОЧЕМУ ПУНКТ В ТЕРМИНАЛЕ, А НЕ В ПАНЕЛИ. Настройка меняет адрес, по которому
# панель отвечает. Ошибка в нём отрезает доступ к самой панели — чинить
# оттуда же было бы нечем. Терминал доступен всегда.
#
# ЧТО ОХРАНЯЕТСЯ ЗДЕСЬ. Три вещи, каждая из которых ломает доступ, если уедет:
# адрес выбирается из списка, а не вводится строкой; выбор доходит до
# установщика ФЛАГАМИ (иначе маркера не будет и всё вернётся к прежнему); и
# 0.0.0.0 не предлагается молча.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
WP="$ROOT/lib/webpanel.sh"
INST="$ROOT/webpanel/install.sh"
CONF="$ROOT/webpanel/lighttpd.conf"

for f in "$WP" "$INST" "$CONF"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

FN=$(awk '/^webpanel_change_address\(\) \{/,/^}/' "$WP")
[ -n "$FN" ] || { printf '[FAIL] webpanel_change_address не найдена\n'; exit 1; }

# --- 1. Пункт есть в меню и ведёт куда надо -----------------------------------
MENU=$(awk '/^menu_webpanel\(\) \{/,/^}/' "$WP")
case "$MENU" in
    *"[5] Изменить адрес и порт"*) ok "пункт [5] виден в меню панели" ;;
    *) no "пункт в меню" "[5] Изменить адрес и порт" "нет" ;;
esac
case "$MENU" in
    *"5) webpanel_change_address"*) ok "пункт [5] вызывает обработчик" ;;
    *) no "диспетчеризация [5]" "5) webpanel_change_address" "нет" ;;
esac
# Подсказка диапазона обязана совпадать с числом пунктов: разойдётся — человек
# не поймёт, что [5] вообще можно нажать.
case "$MENU" in
    *"[1-5,B]"*) ok "подсказка диапазона учитывает новый пункт" ;;
    *) no "подсказка диапазона" "[1-5,B]" "$(printf '%s' "$MENU" | grep -o '\[1-[0-9],B\]' | head -1)" ;;
esac

# --- 2. Выбор доходит до установщика ФЛАГАМИ ----------------------------------
#
# Это и есть весь смысл затеи: только путь с --bind оставляет маркер
# bind.explicit, ради которого адрес и переживает следующую переустановку.
# Правка конфига напрямую выглядела бы работающей ровно до первой обновы.
case "$FN" in
    *'install.sh" --bind "$new_bind" --port "$new_port"'*)
        ok "адрес и порт применяются установщиком, с флагами" ;;
    *)
        no "применение через установщик" 'install.sh --bind ... --port ...' \
           "$(printf '%s' "$FN" | grep -n 'install.sh' | head -1)" ;;
esac
case "$FN" in
    *"sed -i"*|*"lighttpd.conf >"*)
        no "конфиг не правится в обход установщика" "только установщик" \
           "в обработчике есть прямая правка конфига" ;;
    *) ok "конфиг напрямую не правится — иначе маркер не появится" ;;
esac

# --- 3. Установщик действительно ставит маркер --------------------------------
case "$(awk '/--bind\) BIND=/{print}' "$INST")" in
    *BIND_EXPLICIT=1*) ok "--bind помечает адрес как заданный человеком" ;;
    *) no "--bind ставит BIND_EXPLICIT" "BIND_EXPLICIT=1" "нет" ;;
esac
if grep -q 'if \[ "\$BIND_EXPLICIT" = 1 \]' "$INST" && grep -q 'bind.explicit' "$INST"; then
    ok "маркер bind.explicit пишется на диск"
else
    no "маркер пишется" "bind.explicit" "не найден"
fi
if grep -q 'server.bind[[:space:]]*=[[:space:]]*"@BIND@"' "$CONF" \
   && grep -q 'server.port[[:space:]]*=[[:space:]]*@PORT@' "$CONF"; then
    ok "адрес и порт подставляются в шаблон, а не хранятся в нём"
else
    no "шаблон конфига" "@BIND@ и @PORT@" "изменились — правка руками начнёт теряться иначе"
fi

# --- 4. Адрес вводится руками, но проверяется на формат -----------------------
#
# Выбор из списка здесь был бы запретом: адреса может ещё не быть на роутере —
# поднимаемый позже VPN, второй мост, интерфейс не в строю. Человек вправе
# вписать его сам. Но опечатка вроде «192.168.1.» уедет в конфиг, lighttpd не
# стартует, и панель не поднимется — поэтому формат проверяется.
case "$FN" in
    *"read_input wp_new_bind"*) ok "адрес вводится, а не выбирается из списка" ;;
    *) no "свободный ввод адреса" "read_input wp_new_bind" "нет" ;;
esac
case "$FN" in
    *"Адреса роутера:"*) ok "адреса роутера показаны подсказкой" ;;
    *) no "подсказка с адресами" "строка «Адреса роутера:»" "нет" ;;
esac

# Валидатор берём НАСТОЯЩИЙ и гоняем на значениях, которые реально набирают.
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM
{
    printf '%s\n' "$FN" | awk '/_valid_ipv4\(\) \{/{p=1} p{print} p&&/^    \}$/{exit}'
    cat <<'PROBE'
for v in 192.168.1.1 0.0.0.0 10.8.0.1 255.255.255.255          192.168.1. .1.2.3 192.168.1 1.2.3.4.5 192.168.1.256 abc 1..2.3; do
    if _valid_ipv4 "$v"; then echo "OK $v"; else echo "NO $v"; fi
done
PROBE
} > "$TMP/v.sh"
VOUT=$(sh "$TMP/v.sh" 2>&1)

_want_ok() {
    case "$VOUT" in
        *"OK $1"*) ok "принимается: $1" ;;
        *) no "принимается $1" "OK" "$(printf '%s' "$VOUT" | grep -w -- "$1")" ;;
    esac
}
_want_no() {
    case "$VOUT" in
        *"NO $1"*) ok "отвергается: $1" ;;
        *) no "отвергается $1" "NO" "$(printf '%s' "$VOUT" | grep -w -- "$1")" ;;
    esac
}
_want_ok 192.168.1.1
_want_ok 0.0.0.0
_want_ok 255.255.255.255
_want_no 192.168.1.
_want_no 192.168.1
_want_no 1.2.3.4.5
_want_no 192.168.1.256
_want_no abc

# Отсутствие адреса на интерфейсах — ПРЕДУПРЕЖДЕНИЕ, а не отказ. Иначе
# «вбить самому» превращается в «вбить из нашего списка».
_absent=$(printf '%s\n' "$FN" | awk '/elif ! _ip_present_local/,/^    fi$/')
case "$_absent" in
    *print_warning*) ok "про отсутствующий адрес предупреждают" ;;
    *) no "предупреждение об отсутствующем адресе" "print_warning" "нет" ;;
esac
case "$_absent" in
    *"return 1"*) no "отсутствующий адрес не запрещён" "только предупреждение" "стоит return 1" ;;
    *) ok "отсутствующий адрес не запрещён — решает человек" ;;
esac

# --- 5. Порт проверяется, а 0.0.0.0 не предлагается молча ---------------------
case "$FN" in
    *'*[!0-9]*) print_error "Порт — только цифры"'*) ok "нечисловой порт отвергается" ;;
    *) no "проверка порта на цифры" "ветка *[!0-9]*" "нет" ;;
esac
case "$FN" in
    *'-lt 1 ]'*'-gt 65535 ]'*) ok "порт вне диапазона отвергается" ;;
    *) no "диапазон порта" "1..65535" "нет" ;;
esac
# 0.0.0.0 — тот самый случай, когда панель с root-овым CGI уехала в
# провайдерский сегмент (Ростелеком, 10.4.x.x). Предупреждение обязательно.
case "$FN" in
    *"0.0.0.0 — все интерфейсы"*) ok "0.0.0.0 назван в подсказке" ;;
    *) no "0.0.0.0 в подсказке" "строка про все интерфейсы" "нет" ;;
esac
case "$FN" in
    *"У панели нет пароля"*) ok "перед применением 0.0.0.0 сказано, чем это грозит" ;;
    *) no "предупреждение перед применением" "упоминание отсутствия пароля" "нет" ;;
esac
# Необратимого тут нет, но подтверждение обязано быть: смена адреса рвёт
# текущую вкладку.
case "$FN" in
    *'confirm "Применить?"'*) ok "перед применением спрашивают подтверждение" ;;
    *) no "подтверждение" 'confirm "Применить?"' "нет" ;;
esac

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
