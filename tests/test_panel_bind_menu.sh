#!/bin/sh
# tests/test_panel_bind_menu.sh — адрес и порт панели задаются из терминала
# и переживают обновление.
#
# ЖАЛОБА. Человек сменил адрес, на котором слушает веб-панель, и после каждой
# обновы получал автоопределённый обратно — правку приходилось повторять изо
# дня в день.
#
# ПОЧЕМУ ТАК БЫЛО. lighttpd.conf генерируется из шаблона при каждой установке
# (@BIND@ / @PORT@), поэтому правка файла руками стиралась. Установщик умеет
# принимать адрес флагом --bind и переигрывать его при переустановке, но
# только по маркеру bind.explicit, а маркер ставится ровно тогда, когда флаг
# передали. Способа передать его, не набирая команду руками, не было.
#
# ПОЧЕМУ ПУНКТ В ТЕРМИНАЛЕ, А НЕ В ПАНЕЛИ. Настройка меняет адрес, по которому
# панель отвечает. Ошибка в нём отрезает доступ к самой панели — чинить
# оттуда же было бы нечем. Терминал доступен всегда.
#
# ЧТО ОХРАНЯЕТСЯ ЗДЕСЬ. Три вещи, каждая из которых ломает доступ, если уедет:
# адрес выбирается из списка, а не вводится строкой; выбор доходит до
# установщика ФЛАГАМИ (иначе маркера не будет и всё вернётся к прежнему); и
# 0.0.0.0 не предлагается молча.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
WP="$ROOT/lib/webpanel.sh"
INST="$ROOT/webpanel/install.sh"
CONF="$ROOT/webpanel/lighttpd.conf"

for f in "$WP" "$INST" "$CONF"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

FN=$(awk '/^webpanel_change_address\(\) \{/,/^}/' "$WP")
[ -n "$FN" ] || { printf '[FAIL] webpanel_change_address не найдена\n'; exit 1; }

# --- 1. Пункт есть в меню и ведёт куда надо -----------------------------------
MENU=$(awk '/^menu_webpanel\(\) \{/,/^}/' "$WP")
case "$MENU" in
    *"[5] Адрес и порт панели"*) ok "пункт [5] виден в меню панели" ;;
    *) no "пункт в меню" "[5] Адрес и порт панели" "нет" ;;
esac
case "$MENU" in
    *"5) webpanel_change_address"*) ok "пункт [5] вызывает обработчик" ;;
    *) no "диспетчеризация [5]" "5) webpanel_change_address" "нет" ;;
esac
# Подсказка диапазона обязана совпадать с числом пунктов: разойдётся — человек
# не поймёт, что последний пункт вообще можно нажать.
#
# Ожидаемое значение ВЫЧИСЛЯЕМ из самого меню, а не вписываем числом: с жёстким
# «[1-5,B]» этот тест краснел на каждом добавленном пункте, то есть требовал
# правки ровно тогда, когда всё сделано правильно. Сторожить надо совпадение,
# а не конкретную цифру.
_items=$(printf '%s\n' "$MENU" | grep -cE '^\[[0-9]\] ')
_want="[1-${_items},B]"
case "$MENU" in
    *"$_want"*) ok "подсказка диапазона совпадает с числом пунктов ($_items)" ;;
    *) no "подсказка диапазона" "$_want" "$(printf '%s' "$MENU" | grep -o '\[1-[0-9],B\]' | head -1)" ;;
esac

# --- 2. Выбор доходит до установщика ФЛАГАМИ ----------------------------------
#
# Это и есть весь смысл затеи: только путь с --bind оставляет маркер
# bind.explicit, ради которого адрес и переживает следующую переустановку.
# Правка конфига напрямую выглядела бы работающей ровно до первой обновы.
case "$FN" in
    *'install.sh" --bind "$new_bind" --port "$new_port"'*)
        ok "адрес и порт применяются установщиком, с флагами" ;;
    *)
        no "применение через установщик" 'install.sh --bind ... --port ...' \
           "$(printf '%s' "$FN" | grep -n 'install.sh' | head -1)" ;;
esac
case "$FN" in
    *"sed -i"*|*"lighttpd.conf >"*)
        no "конфиг не правится в обход установщика" "только установщик" \
           "в обработчике есть прямая правка конфига" ;;
    *) ok "конфиг напрямую не правится — иначе маркер не появится" ;;
esac

# --- 3. Установщик действительно ставит маркер --------------------------------
case "$(awk '/--bind\) BIND=/{print}' "$INST")" in
    *BIND_EXPLICIT=1*) ok "--bind помечает адрес как заданный человеком" ;;
    *) no "--bind ставит BIND_EXPLICIT" "BIND_EXPLICIT=1" "нет" ;;
esac
if grep -q 'if \[ "\$BIND_EXPLICIT" = 1 \]' "$INST" && grep -q 'bind.explicit' "$INST"; then
    ok "маркер bind.explicit пишется на диск"
else
    no "маркер пишется" "bind.explicit" "не найден"
fi
if grep -q 'server.bind[[:space:]]*=[[:space:]]*"@BIND@"' "$CONF" \
   && grep -q 'server.port[[:space:]]*=[[:space:]]*@PORT@' "$CONF"; then
    ok "адрес и порт подставляются в шаблон, а не хранятся в нём"
else
    no "шаблон конфига" "@BIND@ и @PORT@" "изменились — правка руками начнёт теряться иначе"
fi

# --- 4. Адрес вводится руками, но проверяется на формат -----------------------
#
# Выбор из списка здесь был бы запретом: адреса может ещё не быть на роутере —
# поднимаемый позже VPN, второй мост, интерфейс не в строю. Человек вправе
# вписать его сам. Но опечатка вроде «192.168.1.» уедет в конфиг, lighttpd не
# стартует, и панель не поднимется — поэтому формат проверяется.
case "$FN" in
    *"read_input wp_new_bind"*) ok "адрес вводится, а не выбирается из списка" ;;
    *) no "свободный ввод адреса" "read_input wp_new_bind" "нет" ;;
esac
case "$FN" in
    *"Адреса роутера:"*) ok "адреса роутера показаны подсказкой" ;;
    *) no "подсказка с адресами" "строка «Адреса роутера:»" "нет" ;;
esac

# Валидатор берём НАСТОЯЩИЙ и гоняем на значениях, которые реально набирают.
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM
{
    printf '%s\n' "$FN" | awk '/_valid_ipv4\(\) \{/{p=1} p{print} p&&/^    \}$/{exit}'
    cat <<'PROBE'
for v in 192.168.1.1 0.0.0.0 10.8.0.1 255.255.255.255          192.168.1. .1.2.3 192.168.1 1.2.3.4.5 192.168.1.256 abc 1..2.3; do
    if _valid_ipv4 "$v"; then echo "OK $v"; else echo "NO $v"; fi
done
PROBE
} > "$TMP/v.sh"
VOUT=$(sh "$TMP/v.sh" 2>&1)

_want_ok() {
    case "$VOUT" in
        *"OK $1"*) ok "принимается: $1" ;;
        *) no "принимается $1" "OK" "$(printf '%s' "$VOUT" | grep -w -- "$1")" ;;
    esac
}
_want_no() {
    case "$VOUT" in
        *"NO $1"*) ok "отвергается: $1" ;;
        *) no "отвергается $1" "NO" "$(printf '%s' "$VOUT" | grep -w -- "$1")" ;;
    esac
}
_want_ok 192.168.1.1
_want_ok 0.0.0.0
_want_ok 255.255.255.255
_want_no 192.168.1.
_want_no 192.168.1
_want_no 1.2.3.4.5
_want_no 192.168.1.256
_want_no abc

# Отсутствие адреса на интерфейсах — ПРЕДУПРЕЖДЕНИЕ, а не отказ. Иначе
# «вбить самому» превращается в «вбить из нашего списка».
_absent=$(printf '%s\n' "$FN" | awk '/elif ! _ip_present_local/,/^    fi$/')
case "$_absent" in
    *print_warning*) ok "про отсутствующий адрес предупреждают" ;;
    *) no "предупреждение об отсутствующем адресе" "print_warning" "нет" ;;
esac
case "$_absent" in
    *"return 1"*) no "отсутствующий адрес не запрещён" "только предупреждение" "стоит return 1" ;;
    *) ok "отсутствующий адрес не запрещён — решает человек" ;;
esac

# --- 5. Порт проверяется, а 0.0.0.0 не предлагается молча ---------------------
case "$FN" in
    *'*[!0-9]*) print_error "Порт — только цифры"'*) ok "нечисловой порт отвергается" ;;
    *) no "проверка порта на цифры" "ветка *[!0-9]*" "нет" ;;
esac
case "$FN" in
    *'-lt 1 ]'*'-gt 65535 ]'*) ok "порт вне диапазона отвергается" ;;
    *) no "диапазон порта" "1..65535" "нет" ;;
esac
# 0.0.0.0 — тот самый случай, когда панель с root-овым CGI уехала в
# провайдерский сегмент (Ростелеком, 10.4.x.x). Предупреждение обязательно.
case "$FN" in
    *"0.0.0.0 — все интерфейсы"*) ok "0.0.0.0 назван в подсказке" ;;
    *) no "0.0.0.0 в подсказке" "строка про все интерфейсы" "нет" ;;
esac
case "$FN" in
    *"У панели нет пароля"*) ok "перед применением 0.0.0.0 сказано, чем это грозит" ;;
    *) no "предупреждение перед применением" "упоминание отсутствия пароля" "нет" ;;
esac
# Необратимого тут нет, но подтверждение обязано быть: смена адреса рвёт
# текущую вкладку.
case "$FN" in
    *'confirm "Применить?"'*) ok "перед применением спрашивают подтверждение" ;;
    *) no "подтверждение" 'confirm "Применить?"' "нет" ;;
esac

# --- 6. Задать адрес и порт МОЖНО ДО УСТАНОВКИ ---------------------------------
#
# Раньше здесь стоял гейт «сначала пункт [1]»: панель сперва вставала на
# автоопределённый адрес, и только потом её можно было переселить. На роутере
# с несколькими сегментами это значит, что она сначала поднимется там, где её
# не ждут — с root-овым CGI и без пароля.
case "$FN" in
    *"Веб-панель не установлена — сначала пункт"*)
        no "адрес задаётся до установки" "без гейта" "гейт «сначала пункт [1]» вернулся" ;;
    *) ok "адрес и порт можно задать до установки панели" ;;
esac
# До установки переустанавливать нечего — значения кладутся на диск, и это
# работает только вместе с маркером: без него установщик сохранённый адрес
# игнорирует, и заранее заданное молча пропало бы.
_pre=$(printf '%s\n' "$FN" | awk '/ПАНЕЛЬ ЕЩЁ НЕ СТОИТ/,/^    fi$/')
case "$_pre" in
    *'> "$wp_dir/bind"'*) ok "до установки адрес сохраняется на диск" ;;
    *) no "сохранение адреса до установки" "запись в wp_dir/bind" "нет" ;;
esac
case "$_pre" in
    *'"$wp_dir/bind.explicit"'*) ok "вместе с адресом пишется маркер, иначе он будет проигнорирован" ;;
    *) no "маркер при предзадании" "bind.explicit" "нет" ;;
esac
case "$_pre" in
    *'> "$wp_dir/port"'*) ok "порт тоже сохраняется до установки" ;;
    *) no "сохранение порта до установки" "запись в wp_dir/port" "нет" ;;
esac
# Установщик обязан читать эти файлы ДО того, как что-либо снесёт — иначе
# предзаданное будет затёрто раньше, чем прочитано.
_read_line=$(grep -n 'WEBPANEL_DIR/port' "$INST" | head -1 | cut -d: -f1)
_wipe_line=$(grep -n 'STAGE_WP\|rm -rf "\$WEBPANEL_DIR"' "$INST" | grep -v '^[0-9]*:#' | awk -F: '$1>60{print $1; exit}')
if [ -n "$_read_line" ] && [ -n "$_wipe_line" ] && [ "$_read_line" -lt "$_wipe_line" ]; then
    ok "установщик читает заданные значения раньше, чем начинает что-либо менять"
else
    no "порядок чтения в установщике" "чтение раньше разрушения" \
       "чтение=$_read_line разрушение=$_wipe_line"
fi

# --- 7. Возврат к умолчаниям ---------------------------------------------------
#
# Отдельным действием, а не «введите пусто»: пустой ввод означает «оставить как
# есть», и перегружать его вторым смыслом — гарантированно однажды сбросить
# настройку по ошибке.
case "$FN" in
    *"Сбросить на умолчания"*) ok "сброс к умолчаниям предлагается явно" ;;
    *) no "сброс к умолчаниям" "отдельный вопрос" "нет" ;;
esac
_reset=$(printf '%s\n' "$FN" | awk '/Сбросить на умолчания/,/^    fi$/')
_gone=0
for f in bind bind.explicit port; do
    case "$_reset" in *"\$wp_dir/$f"*) ;; *) _gone=$((_gone+1)) ;; esac
done
if [ "$_gone" = "0" ]; then
    ok "сброс удаляет все три файла — адрес, маркер и порт"
else
    no "сброс удаляет всё" "bind + bind.explicit + port" "не удаляется: $_gone из 3"
fi

# --- 8. IPv6: второй сокет, и он переживает обновление --------------------------
#
# ЖАЛОБА. Человек дописывал в lighttpd.conf строку
#   $SERVER["socket"] == "[::]:8088" { }
# и терял её после каждого обновления. Причина не в потере файла: конфиг
# генерируется из шаблона при каждой установке, и дописанное руками стирается.
#
# Одной строки при этом мало: проверка Host в панели принимала только ::1,
# fe80:*, fd*, fc* — то есть по глобальному адресу IPv6 (а у IPv6 нет NAT, и
# домашний адрес часто именно глобальный) сокет бы открылся, а внутрь не
# пустило бы. Поэтому охраняются обе половины.
CONF="$ROOT/webpanel/lighttpd.conf"
AUTH="$ROOT/webpanel/cgi/auth.sh"

grep -q '@IPV6_SOCKET@' "$CONF" \
    && ok "в шаблоне есть место для сокета IPv6" \
    || no "метка сокета IPv6 в шаблоне" "@IPV6_SOCKET@" "нет"
# Имена меток НЕ должны перечисляться в комментариях: sed заменит их и там,
# и шапка установленного конфига превратится в бессмыслицу, а grep по имени
# сокета начнёт находить лишнюю строку.
if grep -nE '^#.*@(PORT|BIND|WWW_DIR|IPV6_SOCKET)@' "$CONF" | grep -q .; then
    no "метки не перечислены в комментариях" "без @…@ в тексте" \
       "$(grep -nE '^#.*@(PORT|BIND|WWW_DIR|IPV6_SOCKET)@' "$CONF" | head -1)"
else
    ok "имена меток не встречаются в комментариях — шапка не мангается"
fi

_inst=$(awk '/^_build_ipv6_socket\(\)/,/^}/' "$INST")
case "$_inst" in
    *'[ -n "$BIND6" ] || { printf'*) ok "при выключенном IPv6 подставляется пустая строка, а не пустой блок" ;;
    *) no "пустое значение даёт пустую строку" "ранний возврат" "нет — конфиг не стартует" ;;
esac
grep -q '\-\-bind6) BIND6=' "$INST" \
    && ok "установщик принимает --bind6" || no "флаг --bind6" "есть" "нет"
# Главное: значение читается ДО того, как что-либо снесено, иначе оно будет
# затёрто раньше, чем прочитано.
_read6=$(grep -n 'WEBPANEL_DIR/bind6' "$INST" | head -1 | cut -d: -f1)
_wipe=$(grep -n 'STAGE_WP=' "$INST" | head -1 | cut -d: -f1)
if [ -n "$_read6" ] && [ -n "$_wipe" ] && [ "$_read6" -gt "$_wipe" ]; then
    ok "сохранённый адрес IPv6 читается установщиком"
else
    no "чтение bind6" "есть" "чтение=$_read6"
fi
grep -q "printf '%s' \"\$BIND6\" > \"\$STAGE_WP/bind6\"" "$INST" \
    && ok "адрес IPv6 сохраняется на диск при установке" \
    || no "сохранение bind6" "запись в STAGE_WP/bind6" "нет"
# Выключение должно отличаться от «не задано», иначе снять IPv6 будет нечем.
grep -q '"\$BIND6" = "off"' "$INST" \
    && ok "IPv6 можно явно выключить (--bind6 off)" \
    || no "явное выключение" "обработка off" "нет"

# Вторая половина: проверка Host.
_v6=$(awk '/if _auth_is_ipv6 "\$h"; then/,/^    fi$/' "$AUTH")
case "$_v6" in
    *_auth_own_ipv6*) ok "глобальный IPv6 принимается, если это адрес самого роутера" ;;
    *) no "приём своего глобального IPv6" "_auth_own_ipv6" "нет — панель ответит «не отвечает на этот адрес»" ;;
esac
# Сравнение обязано быть точным: подстрокой «2a00::1» совпало бы с «2a00::10».
awk '/^_auth_own_ipv6\(\)/,/^}/' "$AUTH" | grep -q 'grep -qxF' \
    && ok "адрес сверяется целой строкой, а не подстрокой" \
    || no "точное сравнение адреса" "grep -qxF" "подстрочное сравнение — примет чужой адрес"
# И прежние диапазоны никуда не делись.
case "$_v6" in
    *'::1|fe80:*|fd*|fc*'*) ok "петля, link-local и приватные диапазоны по-прежнему приняты" ;;
    *) no "прежние диапазоны IPv6" "::1|fe80|fd|fc" "исчезли" ;;
esac

# Меню умеет задавать и сбрасывать.
case "$FN" in
    *'read_input wp_new_bind6'*) ok "адрес IPv6 спрашивается в меню" ;;
    *) no "вопрос про IPv6 в меню" "read_input wp_new_bind6" "нет" ;;
esac
case "$FN" in
    *'--bind6 "${new_bind6:-off}"'*) ok "выбор доходит до установщика флагом" ;;
    *) no "передача в установщик" "--bind6" "нет" ;;
esac
case "$_reset" in
    *'$wp_dir/bind6'*) ok "сброс к умолчаниям убирает и IPv6" ;;
    *) no "сброс убирает IPv6" "удаление bind6" "нет" ;;
esac
# :: — это все адреса, включая глобальный, и у IPv6 нет NAT. Молчать нельзя.
case "$FN" in
    *'IPv6 нет NAT'*) ok "перед включением :: сказано, чем это отличается от IPv4" ;;
    *) no "предупреждение про ::" "упоминание отсутствия NAT" "нет" ;;
esac

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
