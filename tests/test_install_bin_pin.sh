#!/bin/sh
# tests/test_install_bin_pin.sh — install_bin.sh не запускается от root вслепую.
#
# ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. После распаковки апстрим-релиза z2k запускает из него
# `install_bin.sh` — от root. Проверка целостности релиза, которая у нас есть
# (verify_release_binaries), этот файл НЕ покрывает, и не по недосмотру:
# апстримный sha256sum.txt содержит 46 записей, и все на бинарники
# (binaries/<арка>/{ip2net,mdig,nfqws2}). Проверено обращением к релизу
# v1.0.4-z2k-r0 2026-08-08 — записи install_bin.sh там нет.
#
# То есть единственный файл релиза, который мы ИСПОЛНЯЕМ как код, оказывался
# единственным непроверенным. Отсюда собственный пин рядом с URL релиза.
#
# Тест держит два свойства:
#   1) пин есть, выглядит как sha256 и стоит рядом с URL, чтобы их бампали вместе;
#   2) при несовпадении install_bin.sh НЕ запускается, а установка уходит на
#      ручную раскладку — то есть отказ не оставляет роутер без бинарников.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
INSTALL="$HERE/../lib/install.sh"
[ -f "$INSTALL" ] || { printf '[FAIL] нет %s\n' "$INSTALL"; exit 1; }

# --- 1. Пин на месте и выглядит как дайджест ---------------------------------
pin=$(sed -n 's/.*local install_bin_sha="\([0-9a-f]*\)".*/\1/p' "$INSTALL" | head -1)
case "$pin" in
    ????????????????????????????????????????????????????????????????)
        ok "пин install_bin.sh задан и имеет длину sha256" ;;
    "")
        no "пин install_bin.sh задан" "64 hex-символа" "пусто (проверка отключена)" ;;
    *)
        no "пин install_bin.sh имеет длину sha256" "64 hex-символа" "${#pin} символов" ;;
esac

# --- 2. Пин и URL релиза стоят рядом ------------------------------------------
#
# Они меняются одним бампом. Если пин уедет в другой конец файла, его забудут
# обновить — и он начнёт отвергать законный релиз, а установка молча свалится
# на ручную раскладку.
url_line=$(grep -n 'local fallback_url=' "$INSTALL" | head -1 | cut -d: -f1)
pin_line=$(grep -n 'local install_bin_sha=' "$INSTALL" | head -1 | cut -d: -f1)
if [ -n "$url_line" ] && [ -n "$pin_line" ] && [ "$((pin_line - url_line))" -lt 25 ] \
   && [ "$((pin_line - url_line))" -gt 0 ]; then
    ok "пин стоит рядом с URL релиза (строки $url_line и $pin_line)"
else
    no "пин стоит рядом с URL релиза" "в пределах 25 строк после URL" \
       "url=$url_line pin=$pin_line"
fi

# --- 3. Версия релиза в URL и в комментарии к пину совпадают -------------------
url_ver=$(sed -n 's|.*/releases/download/\(v[0-9][^/]*\)/.*|\1|p' "$INSTALL" | head -1)
if [ -n "$url_ver" ] && grep -q "$url_ver" "$INSTALL"; then
    # Комментарий к пину должен называть ту же версию — иначе при бампе
    # обновят URL и не заметят, что пин остался от прошлого релиза.
    if sed -n "${url_line},$((pin_line + 2))p" "$INSTALL" | grep -q "$url_ver"; then
        ok "комментарий к пину называет ту же версию, что и URL ($url_ver)"
    else
        no "комментарий к пину называет ту же версию" "$url_ver" "версия не упомянута рядом с пином"
    fi
else
    no "версия релиза извлекается из URL" "непустая версия" "$url_ver"
fi

# --- 4. Несовпадение НЕ запускает скрипт и уходит на ручную раскладку ---------
#
# Проверяем логику, а не файл: вырезать её из install.sh целиком нельзя
# (функция тянет полдерева), поэтому воспроизводим ровно то условие, которое
# стоит в коде, и убеждаемся, что оно ведёт себя как заявлено.
if grep -q 'if \[ "\$_ib_ok" = "1" \] && sh install_bin.sh; then' "$INSTALL"; then
    ok "запуск install_bin.sh стоит ПОД условием проверки"
else
    no "запуск install_bin.sh стоит под условием проверки" \
       'if [ "$_ib_ok" = "1" ] && sh install_bin.sh' "условие не найдено"
fi

_ib0=$(grep -n '_ib_ok=0' "$INSTALL" | head -1 | cut -d: -f1)
if [ -n "$_ib0" ] && sed -n "$((_ib0 - 6)),${_ib0}p" "$INSTALL" | grep -q "вручную"; then
    ok "при несовпадении сказано, что бинарники раскладываются вручную"
else
    no "при несовпадении объяснён следующий шаг" "упоминание ручной раскладки" "нет"
fi

# Ручная раскладка обязана существовать — иначе отказ оставит роутер без движка.
if grep -q "Попытка ручной установки" "$INSTALL"; then
    ok "ветка ручной раскладки бинарников существует"
else
    no "ветка ручной раскладки существует" "есть фоллбэк" "нет — отказ оставит роутер без движка"
fi

# --- 5. Проверка выполняется ДО запуска ---------------------------------------
chk=$(grep -n 'z2k_sha256_file install_bin.sh' "$INSTALL" | head -1 | cut -d: -f1)
run=$(grep -n 'sh install_bin.sh; then' "$INSTALL" | head -1 | cut -d: -f1)
if [ -n "$chk" ] && [ -n "$run" ] && [ "$chk" -lt "$run" ]; then
    ok "сверка идёт до запуска (строка $chk < $run)"
else
    no "сверка идёт до запуска" "проверка раньше запуска" "chk=$chk run=$run"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
