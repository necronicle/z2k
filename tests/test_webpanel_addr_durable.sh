#!/bin/sh
# tests/test_webpanel_addr_durable.sh — адрес и порт панели переживают потерю
# каталога панели.
#
# ЧТО СЛУЧИЛОСЬ. Настройки лежали ровно в том каталоге, который установщик
# панели на КАЖДОЙ установке отодвигает в сторону:
#     mv "$WEBPANEL_DIR" "$OLD_WP"; mv "$STAGE_WP" "$WEBPANEL_DIR"
# Откат на случай обрыва есть, но он висит на `trap ... EXIT` и не срабатывает
# при потере питания, OOM или KILL. Поле 2026-08-24: у человека первая попытка
# обновления оборвалась, каталог остался снесённым — меню честно показало
# «панель запущена, но не установлена», — вторая попытка панель переставила, а
# восстанавливать адрес было уже неоткуда. Заданный им 0.0.0.0 заменился
# автоопределением, и вернуть его было нечем.
#
# Правило: то, что задал человек, не должно жить там, где мы регулярно двигаем
# файлы. Копия — в /opt/etc/z2k/webpanel/, каталог вне дерева /opt/zapret2.
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
assert_eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }
ROOT=$(cd "$(dirname "$0")/.." && pwd)
SB=$(mktemp -d) || exit 1; trap 'rm -rf "$SB"' EXIT

W="$ROOT/lib/webpanel.sh"
I="$ROOT/webpanel/install.sh"

# --- 1. Меню пишет стойкую копию ---------------------------------------------
if grep -q '^WEBPANEL_KEEP_DIR=' "$W"; then ok "меню знает про стойкий каталог"
else no "меню знает про стойкий каталог" "объявлен" "нет"; fi
assert_eq "пишет туда все три значения" "3" \
    "$(grep -c '> *"\$WEBPANEL_KEEP_DIR/' "$W")"

# --- 2. Установщик читает её, когда своей копии нет ---------------------------
assert_eq "установщик знает про стойкий каталог" "1" \
    "$(grep -c 'WEBPANEL_KEEP_DIR' "$I" | awk '{print ($1>0)?1:0}')"

# --- 3. Поведение: подхват из стойкой копии -----------------------------------
# Воспроизводим ровно то, что делает установщик: своей копии нет, стойкая есть.
mkdir -p "$SB/wp" "$SB/keep"
printf '0.0.0.0' > "$SB/keep/bind"
printf '9090'    > "$SB/keep/port"
pick() {
    _d="$1"; _k="$2"; _n="$3"; _v=""
    [ -s "$_d/$_n" ] && _v=$(tr -d ' \t\r\n' < "$_d/$_n")
    [ -z "$_v" ] && [ -s "$_k/$_n" ] && _v=$(tr -d ' \t\r\n' < "$_k/$_n")
    printf '%s' "$_v"
}
assert_eq "каталог панели пуст — берём стойкую копию (адрес)" "0.0.0.0" "$(pick "$SB/wp" "$SB/keep" bind)"
assert_eq "каталог панели пуст — берём стойкую копию (порт)"  "9090"    "$(pick "$SB/wp" "$SB/keep" port)"
printf '192.168.1.1' > "$SB/wp/bind"
assert_eq "своя копия главнее стойкой" "192.168.1.1" "$(pick "$SB/wp" "$SB/keep" bind)"

# --- 4. Стойкая копия живёт ВНЕ дерева, которое пересобирает переустановка ----
_keep=$(grep -m1 'WEBPANEL_KEEP_DIR=' "$W" | sed 's/.*="//; s/"$//')
case "$_keep" in
    /opt/zapret2/*) no "стойкая копия вне /opt/zapret2" "не под /opt/zapret2" "$_keep" ;;
    /opt/etc/*)     ok "стойкая копия вне /opt/zapret2 ($_keep)" ;;
    *)              no "стойкая копия в разумном месте" "/opt/etc/..." "$_keep" ;;
esac

# --- 5. Сброс на умолчания чистит ОБЕ копии ----------------------------------
# Иначе «сбросить» не сбрасывает: стойкая копия вернёт старое при первой же
# переустановке, и человек получит обратно то, от чего отказался.
assert_eq "сброс чистит и стойкую копию" "1" \
    "$(awk '/Свои значения удалены/{found=1} /rm -f/ && /WEBPANEL_KEEP_DIR/{print 1; exit}' "$W" | head -1)"

# --- 6. Оборванная установка чинится при старте, а не только трапом ----------
#
# Установка панели атомарна: каталог уезжает в .old, на его место встаёт .new.
# Откат висел на `trap ... EXIT` и не срабатывал при потере питания, OOM или
# KILL — а обрыв случается ровно на переезде дерева. Роутер оставался с живым
# lighttpd и без каталога панели.
N="$ROOT/webpanel/init.d/S96z2k-webpanel"
assert_eq "починка объявлена" "1" "$(grep -c '^repair_interrupted_install()' "$N")"
assert_eq "и вызывается при старте" "1" "$(grep -c '^    repair_interrupted_install$' "$N")"

# Поведение: .old возвращается на место, только если рабочего каталога нет.
mkdir -p "$SB/r"
repair() {
    _wp="$SB/r/webpanel"; _www="$SB/r/www"; _fixed=0
    [ ! -d "$_wp" ] && [ -d "${_wp}.old" ] && { mv "${_wp}.old" "$_wp" 2>/dev/null && _fixed=1; }
    [ ! -d "$_www" ] && [ -d "${_www}.old" ] && { mv "${_www}.old" "$_www" 2>/dev/null && _fixed=1; }
    printf '%s' "$_fixed"
}
rm -rf "$SB/r"; mkdir -p "$SB/r/webpanel.old"; printf '0.0.0.0' > "$SB/r/webpanel.old/bind"
assert_eq "обрыв: .old вернулся на место" "1" "$(repair)"
assert_eq "и настройка внутри цела"       "0.0.0.0" "$(cat "$SB/r/webpanel/bind" 2>/dev/null)"

rm -rf "$SB/r"; mkdir -p "$SB/r/webpanel" "$SB/r/webpanel.old"
printf 'живой' > "$SB/r/webpanel/bind"; printf 'старый' > "$SB/r/webpanel.old/bind"
assert_eq "рабочий каталог есть — не трогаем" "0" "$(repair)"
assert_eq "живое содержимое не подменено"     "живой" "$(cat "$SB/r/webpanel/bind")"

rm -rf "$SB/r"; mkdir -p "$SB/r"
assert_eq "ничего нет — чинить нечего, не падаем" "0" "$(repair)"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
