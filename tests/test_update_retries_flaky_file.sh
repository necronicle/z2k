#!/bin/sh
# tests/test_update_retries_flaky_file.sh — рваный канал не должен навсегда
# лишать человека обновлений.
#
# ЧТО СЛУЧИЛОСЬ (диагностика 31.08.2026). Человек стоял на p-79.14 с 25 августа.
# Каждую ночь журнал повторял одно и то же: «[1/47] качаю <файл>», «сходимость:
# не скачался», «доставка не удалась — откат». Шесть ночей подряд, всегда на
# ПЕРВОМ файле прогона, причём файл каждую ночь был разный — то есть падал не
# файл, а первая же загрузка. Повторных попыток не было НИ ОДНОЙ: код звал
# загрузчик один раз и при отказе валил всю доставку.
#
# В тех же журналах у него сыплются списки, игровые файлы и туннель — канал не
# мёртвый, а рваный. Такому каналу нужен повтор, а не приговор.
#
# Тест исполняемый: подсовывает загрузчик, который отказывает заданное число раз,
# и проверяет поведение настоящей au_download_repo_file_retry.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT

LOG="$SB/au.log"
ZAPRET2_DIR="$SB"
# shellcheck source=/dev/null
. "$ROOT/lib/utils.sh" >/dev/null 2>&1
# shellcheck source=/dev/null
. "$ROOT/lib/auto_update.sh" >/dev/null 2>&1

# Заглушки ставим ПОСЛЕ подключения: au_log определён в самом auto_update.sh и
# затёр бы наш вариант, а журнал остался бы пустым — на этом тест и споткнулся
# при написании.
au_log() { printf '%s\n' "$1" >> "$LOG"; }
sleep() { :; }   # паузы не ждём — проверяем логику, а не часы

command -v au_download_repo_file_retry >/dev/null 2>&1 \
    || { bad "нет au_download_repo_file_retry — повторов не существует"; printf '\nFAILED: 1\n'; exit 1; }

# --- 1. Файл, который приходит со второй попытки, обязан доехать --------------
FAILS_LEFT=1
au_download_repo_file() {
    if [ "$FAILS_LEFT" -gt 0 ]; then FAILS_LEFT=$((FAILS_LEFT - 1)); return 1; fi
    : > "$2"; return 0
}
: > "$LOG"
if au_download_repo_file_retry "files/x.txt" "$SB/x" "" >/dev/null 2>&1; then
    ok "файл со второй попытки доезжает, а не роняет обновление"
else
    bad "файл со второй попытки НЕ доехал — повтор не работает"
fi

# --- 2. Безнадёжный файл всё-таки сдаётся, а не крутится вечно ---------------
FAILS_LEFT=99
: > "$LOG"
if au_download_repo_file_retry "files/y.txt" "$SB/y" "" >/dev/null 2>&1; then
    bad "вечно падающий файл почему-то признан скачанным"
else
    ok "безнадёжный файл сдаётся, а не крутится вечно"
fi

# --- 3. В журнал уходит ПРИЧИНА, а не только факт -----------------------------
# Прежняя строка «не скачался <файл>» не давала ничего: ни числа попыток, ни
# ответа источников. Разбор упирался в догадки.
if grep -q "попыт" "$LOG" && grep -q "последний ответ" "$LOG"; then
    ok "в журнале есть число попыток и ответ источников"
else
    bad "журнал не объясняет причину: $(tail -1 "$LOG")"
fi

# --- 4. Когда всё исправно, повторов нет ------------------------------------
# Цена страховки обязана быть нулевой на здоровом канале.
FAILS_LEFT=0
: > "$LOG"
au_download_repo_file_retry "files/z.txt" "$SB/z" "" >/dev/null 2>&1
if [ ! -s "$LOG" ]; then
    ok "на здоровом канале в журнал не пишется ничего лишнего"
else
    bad "лишние строки при успешной загрузке: $(cat "$LOG")"
fi

# --- 5. Число попыток настраивается и санитайзится ---------------------------
FAILS_LEFT=99
Z2K_AU_FILE_TRIES=2
: > "$LOG"
au_download_repo_file_retry "files/w.txt" "$SB/w" "" >/dev/null 2>&1
if grep -q "за 2 попыт" "$LOG"; then
    ok "число попыток берётся из настройки"
else
    bad "настройка числа попыток не действует: $(tail -1 "$LOG")"
fi

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
