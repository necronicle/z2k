#!/bin/sh
# tests/test_webpanel_port_conflict.sh — конфликт за порт определяется по
# слушающему сокету, а не по разбору чужого конфига.
#
# ЧТО СЛУЧИЛОСЬ В ПОЛЕ (2026-08-10). У человека штатный lighttpd Entware держал
# 0.0.0.0:8088. Наш установщик напечатал:
#
#   keeping stock lighttpd init /opt/etc/init.d/S80lighttpd
#   (its port 80 does not conflict with 8088)
#
# — оставил его жить, разложил файлы панели и упал на последнем шаге, при
# запуске. Снаружи это выглядело как «панель установлена, но не запускается»,
# и переустановка ничего не меняла.
#
# ПРИЧИНА была в инструменте: порт штатного сервера вычислялся разбором
# `server.port` из /opt/etc/lighttpd/*.conf. Задать порт можно и блоком
# $SERVER["socket"] == "0.0.0.0:8088", и через include — парсер этого не видит и
# молча подставляет умолчание 80.
#
# Слушающий сокет — единственный источник правды, не зависящий ни от версии
# lighttpd, ни от синтаксиса его конфига. Здесь проверяется и разбор netstat, и
# принятие решения.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
INS="$ROOT/webpanel/install.sh"
[ -f "$INS" ] || { printf '[FAIL] нет %s\n' "$INS"; exit 1; }

# --- 1. Решение опирается на факт, а не только на конфиг ----------------------
if grep -q '_port_holder_pid' "$INS"; then
    ok "держатель порта определяется по слушающему сокету"
else
    no "держатель порта определяется по сокету" "_port_holder_pid" \
       "решение снова принимается разбором конфига — та же дыра"
fi

if grep -q 'netstat -ltnp' "$INS"; then
    ok "источник — netstat, а не парсер lighttpd.conf"
else
    no "источник — netstat" "netstat -ltnp" "не найдено"
fi

# Конфликт обязан срабатывать и когда объявленный порт НЕ совпадает: ровно этот
# случай и был в поле. Само правило вынесено в _stock_init_verdict и
# проверяется ИСПОЛНЕНИЕМ ниже; здесь сторожим только то, что цикл ходит через
# него, а не решает сам по себе — иначе исполняемые проверки будут гонять
# функцию, которой в бою никто не пользуется.
if grep -q '_stock_init_verdict "\$_sport" "\$PORT" "\$_holder_cmd"' "$INS"; then
    ok "решение по штатному init принимает _stock_init_verdict, и цикл её зовёт"
else
    no "цикл зовёт _stock_init_verdict" \
       "вызов с портами и держателем" "цикл решает сам — исполняемые проверки станут холостыми"
fi

# --- 2. Своя же панель не считается конфликтом --------------------------------
#
# На момент проверки наша панель ещё работает (её останавливает шаг [3/7]).
# Приняв её за чужого, установщик отключал бы штатный init на ровном месте.
if grep -q '\*"\$CONF_DST"\*) _holder=""' "$INS"; then
    ok "собственная панель на порту не считается конфликтом"
else
    no "собственная панель не считается конфликтом" "проверка cmdline на CONF_DST" "не найдено"
fi

# --- 3. Посторонний процесс — внятный отказ, а не тихое падение ---------------
#
# Чужой сервис на нашем порту трогать нельзя, но и делать вид, что всё хорошо,
# тоже: панель не поднимется, а причина будет не названа.
_blk=$(awk '/порт \$PORT занят посторонним/,/exit 1 ;;/' "$INS")
if [ -n "$_blk" ] && printf '%s' "$_blk" | grep -q 'exit 1'; then
    ok "посторонний процесс на порту останавливает установку с указанием pid и команды"
else
    no "посторонний процесс останавливает установку" "явный отказ с pid" "молча продолжаем"
fi

# --- 4. Разбор netstat: поведение, а не наличие строки ------------------------
if ! command -v awk >/dev/null 2>&1; then
    printf '[SKIP] разбор netstat (нет awk)\n'
else
    _parse() {
        printf '%s\n' "$2" | awk -v p=":$1\$" \
            '$4 ~ p { n = split($NF, a, "/"); if (a[1] ~ /^[0-9]+$/) { print a[1]; exit } }'
    }
    # Ровно тот вывод, что пришёл с роутера.
    _real='tcp        0      0 0.0.0.0:8088            0.0.0.0:*               LISTEN      11959/lighttpd
tcp        0      0 0.0.0.0:80              0.0.0.0:*               LISTEN      723/lighttpd
tcp        0      0 127.0.0.1:53            0.0.0.0:*               LISTEN      900/dnsmasq'

    [ "$(_parse 8088 "$_real")" = "11959" ] \
        && ok "pid держателя 8088 извлечён верно" \
        || no "pid держателя 8088" "11959" "$(_parse 8088 "$_real")"

    [ -z "$(_parse 9999 "$_real")" ] \
        && ok "свободный порт — пустой ответ" \
        || no "свободный порт — пустой ответ" "пусто" "$(_parse 9999 "$_real")"

    # Якорь обязателен: без него ":088" совпал бы с ":8088" и мы отключили бы
    # штатный сервер из-за чужого порта.
    [ -z "$(_parse 088 "$_real")" ] \
        && ok "совпадение по суффиксу порта исключено (088 не матчит 8088)" \
        || no "совпадение по суффиксу исключено" "пусто" "$(_parse 088 "$_real")"

    # Строка без pid (netstat без -p или без прав) не должна давать мусор.
    _nopid='tcp        0      0 0.0.0.0:8088            0.0.0.0:*               LISTEN'
    [ -z "$(_parse 8088 "$_nopid")" ] \
        && ok "строка без pid не превращается в мусорный держатель" \
        || no "строка без pid" "пусто" "$(_parse 8088 "$_nopid")"
fi

# ============================================================================
# Порт 80 принадлежит вебморде роутера — стоковый init туда не пускаем
# ============================================================================
# Проверяется ИСПОЛНЕНИЕМ настоящей _stock_init_verdict из webpanel/install.sh.
#
# Поле 01.09.2026: у человека nginx роутера падал с bind() ... failed на ВСЕХ
# адресах разом, включая 127.0.0.1 — подпись держателя маски 0.0.0.0:80. Держал
# его стоковый init lighttpd, который мы же и приносим вместе с пакетом, а
# установщик оставлял: «порт 80 не конфликтует с 8088». С панелью — не
# конфликтует, с мордой роутера — отнимает её целиком.
eval "$(awk '/^_stock_init_verdict\(\)/,/^}/' "$ROOT/webpanel/install.sh")"
if ! command -v _stock_init_verdict >/dev/null 2>&1; then
    no "развилка стокового init вынесена в функцию" "_stock_init_verdict" "не найдена"
else
    _v=$(_stock_init_verdict 80 8088 "")
    [ "$_v" = "disable" ] \
        && ok "стоковый на 80 глушится, даже когда панель на 8088" \
        || no "стоковый на 80 глушится" "disable" "$_v"

    _v=$(_stock_init_verdict 81 8088 "")
    [ "$_v" = "keep" ] \
        && ok "чужой lighttpd на 81 не трогаем — он нам не мешает" \
        || no "чужой на 81 остаётся" "keep" "$_v"

    _v=$(_stock_init_verdict 8088 8088 "")
    [ "$_v" = "disable" ] \
        && ok "совпадение с нашим портом по-прежнему конфликт" \
        || no "совпадение портов" "disable" "$_v"

    _v=$(_stock_init_verdict 81 8088 "/opt/sbin/lighttpd -f /opt/etc/lighttpd/lighttpd.conf")
    [ "$_v" = "disable" ] \
        && ok "объявил 81, а держит наш порт — всё равно глушим" \
        || no "фактический держатель важнее объявленного" "disable" "$_v"

    # Порт 80 глушится и тогда, когда наш порт человек сменил на что угодно:
    # дело не в нашем порте, а в том, чей это порт на этом устройстве.
    _v=$(_stock_init_verdict 80 9090 "")
    [ "$_v" = "disable" ] \
        && ok "порт 80 глушится независимо от того, какой порт у панели" \
        || no "порт 80 глушится всегда" "disable" "$_v"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
