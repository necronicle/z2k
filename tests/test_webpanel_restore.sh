#!/bin/sh
# tests/test_webpanel_restore.sh — сломанная панель не должна оставаться
# сломанной после переустановки.
#
# ЧТО СЛУЧИЛОСЬ В ПОЛЕ (2026-08-10). Человек переустановил z2k, панель не
# появилась. Переустановил ещё раз — снова не появилась. При этом lighttpd
# исправно слушал :8088, и netstat показывал живую панель.
#
# МЕХАНИКА, из-за которой это самозапирается:
#
#   1. Панель — опциональный компонент, поэтому переустановка ставит её только
#      тем, у кого она была. Признаком «была» служил файл
#      $ZAPRET2_DIR/webpanel/port, снимаемый в бэкап перед сносом дерева.
#   2. Но если дерево панели УЖЕ сломано — а именно это и приводит человека к
#      переустановке — файла порта нет. Бэкап пуст, восстановление не
#      срабатывает, панель не ставится.
#   3. Init-скрипт S96z2k-webpanel живёт в /opt/etc/init.d/ и переустановку
#      переживает. Он поднимает lighttpd, у которого корень (/opt/zapret2/www)
#      снесён вместе с деревом. Сервер жив, отдаёт 404 на всё.
#
# То есть каждая следующая переустановка воспроизводила ровно то же состояние,
# и снаружи оно выглядело как «панель работает, но пустая».
#
# Правильный признак «панель была» — выживший init-скрипт, а не файл внутри
# снесённого дерева. Этот тест сторожит именно его.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
INS="$ROOT/lib/install.sh"
[ -f "$INS" ] || { printf '[FAIL] нет %s\n' "$INS"; exit 1; }

# --- 1. Условие восстановления не завязано ТОЛЬКО на файл порта ---------------
_cond=$(grep -n 'backup_tmp/webpanel-port" \]' "$INS" | head -1)
if printf '%s' "$_cond" | grep -q 'S96z2k-webpanel'; then
    ok "восстановление включается и по выжившему init-скрипту, а не только по файлу порта"
else
    no "восстановление включается по выжившему init-скрипту" \
       "|| [ -f /opt/etc/init.d/S96z2k-webpanel ]" \
       "условие только по webpanel-port — сломанная панель останется сломанной"
fi

# --- 2. Неизвестный порт не отменяет восстановление ---------------------------
#
# Если признак сработал по init-скрипту, порта в бэкапе может не быть вовсе.
# Установщик обязан быть вызван и в этом случае — с портом из init-скрипта либо
# со своим умолчанием.
_blk=$(awk '/backup_tmp\/webpanel-port" \]/,/^    fi$/' "$INS")
if printf '%s' "$_blk" | grep -q 'S96z2k-webpanel'; then
    ok "порт добирается из выжившего init-скрипта, когда бэкапа нет"
else
    no "порт добирается из init-скрипта" "чтение PORT= из S96z2k-webpanel" "не найдено"
fi

if printf '%s' "$_blk" | grep -q '\[ -n "\$_wp_port" \] && _wp_args="--port \$_wp_port"'; then
    ok "пустой порт не ломает вызов установщика (аргумент просто не передаётся)"
else
    no "пустой порт не ломает вызов" "аргумент --port добавляется только при непустом порте" "иначе"
fi

# --- 3. Установщик всё-таки вызывается ----------------------------------------
if printf '%s' "$_blk" | grep -q 'sh "\$_wp_src" \$_wp_args'; then
    ok "восстановление действительно запускает установщик панели"
else
    no "восстановление запускает установщик" "sh webpanel/install.sh" "не найдено"
fi

# --- 4. Отказ установщика виден человеку --------------------------------------
#
# Тихий отказ здесь — это ровно тот случай, с которого всё началось: панели нет,
# а причин не видно.
if printf '%s' "$_blk" | grep -q 'установите вручную через меню'; then
    ok "отказ установщика сообщается человеку с указанием, что делать"
else
    no "отказ установщика сообщается" "подсказка про меню" "молчит"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
