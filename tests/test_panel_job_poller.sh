#!/bin/sh
# tests/test_panel_job_poller.sh — переустановка молчит, а не жалуется.
#
# ПОЧЕМУ ЭТОТ ТЕСТ ИСПОЛНЯЕТ КОД, А НЕ ГРЕПАЕТ ЕГО.
#
# Одна и та же беда чинилась трижды, и каждый раз проверялась статически —
# «нужная строка в файле есть». Строка была, а люди продолжали получать
# «панель ответила ошибкой: 404 Not Found — чем кончилась задача, неизвестно»
# ровно посреди штатного обновления. Статическая проверка не умеет ответить на
# единственный важный вопрос: что увидит человек.
#
# Поэтому здесь настоящий app.js исполняется в node, ему подсовывается ровно
# тот ответ, который отдаёт lighttpd, когда /opt/zapret2 переезжает
# (живой сервер, отсутствующий CGI, HTTP 404), и проверяется РЕЗУЛЬТАТ.
#
# И отдельно проверяется, что тест вообще способен поймать дефект: тот же
# прогон делается на версии app.js ДО первой правки, и он ОБЯЗАН показать
# исходное сообщение. Тест, который зелен на сломанном коде, ничего не стоит —
# именно так эта беда и пережила три релиза.
#
# POSIX sh + node (без node — честный SKIP, в CI node есть).

PASS=0; FAIL=0; SKIP=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
APPJS="$ROOT/webpanel/www/app.js"
HARNESS="$HERE/panel_job_poller_harness.js"

[ -f "$APPJS" ]   || { printf '[FAIL] нет %s\n' "$APPJS"; exit 1; }
[ -f "$HARNESS" ] || { printf '[FAIL] нет %s\n' "$HARNESS"; exit 1; }

if ! command -v node >/dev/null 2>&1; then
    printf '[SKIP] поведение опроса задачи (нет node; в CI проверяется)\n'
    printf '\nPASSED: 0\nFAILED: 0\nSKIPPED: 1\n'
    exit 0
fi

OUT=$(node "$HARNESS" "$APPJS" 2>&1) || {
    printf '[FAIL] прогон не состоялся:\n%s\n' "$OUT"; exit 1;
}

field() { printf '%s' "$OUT" | node -e '
  let s=""; process.stdin.on("data",d=>s+=d).on("end",()=>{
    try { const d = JSON.parse(s); console.log(String(d[process.argv[1]])); }
    catch (e) { console.log("__PARSE_FAIL__"); }
  });' "$1"; }

SAID=$(field everySaid)
FINAL=$(field finalLog)
EARLY=$(field finishedDuringOutage)
TOASTS=$(field toasts)

# --- 1. Человеку не сказано ничего про недоступность ---------------------------
_bad=0
for _s in "404" "ошибк" "недоступна" "неизвестно" "потеряна" "перезапускается"; do
    case "$SAID" in
        *"$_s"*) printf '[FAIL] в выводе человеку появилось «%s»: %s\n' "$_s" "$SAID"
                 _bad=$((_bad+1)) ;;
    esac
done
if [ "$_bad" = "0" ]; then
    ok "за всю переустановку панель не пожаловалась ни разу"
else
    FAIL=$((FAIL + _bad))
fi

# --- 2. Настоящий итог задачи доехал ------------------------------------------
#
# Молчание не должно превратиться в потерю результата: файлы задачи лежат в
# /tmp и переезд дерева переживают, значит итог УЗНАВАЕМ — надо лишь дождаться.
case "$FINAL" in
    *"Установка завершена"*) ok "после возвращения панели показан настоящий итог задачи" ;;
    *) no "показан настоящий итог задачи" "лог задачи" "$FINAL" ;;
esac

# --- 3. Задача не объявлена законченной, пока панель лежала --------------------
if [ "$EARLY" = "false" ]; then
    ok "пока панель лежала, задача не объявлялась законченной"
else
    no "задача не объявляется законченной во время переезда" "false" "$EARLY"
fi

# --- 4. Ни одной красной плашки -----------------------------------------------
if [ "$TOASTS" = "" ]; then
    ok "тостов за переустановку не показано"
else
    no "тостов за переустановку не показано" "пусто" "$TOASTS"
fi

# --- 4b. Молчание — это не «ничего не показывать» ------------------------------
#
# Пережидать переезд молча оказалось перебором. Лог во время переезда замирает
# на последней строке, и «идёт долгий шаг» становится неотличимо от «повисло»:
# после r-75.6 пришла жалоба «ни логов, ни того, что панель скоро вернётся».
#
# До p-73.2 счётчик ожидания в логе был, и его снесли ЗАОДНО с ложными
# вердиктами («панель ответила ошибкой… чем кончилась задача, неизвестно»).
# Вердикты убраны правильно, счётчик — нет: он не утверждает ничего о судьбе
# задачи, он показывает, что панель жива и продолжает ждать. Возвращён.
if [ "$(field waitedInLog)" = "true" ]; then
    ok "пока панель не отвечала, в логе шёл счётчик ожидания"
else
    no "в логе есть признак жизни во время переезда" \
       "waitedInLog=true" "лог замер — неотличимо от зависшей установки"
fi
if [ "$(field backInLog)" = "true" ]; then
    ok "возврат связи отмечен в логе"
else
    no "в логе отмечен возврат связи" "backInLog=true" "не отмечен"
fi

# --- 5. Тест умеет ловить дефект ----------------------------------------------
#
# Без этой проверки всё вышеперечисленное могло бы быть зелёным просто потому,
# что харнесс ничего не измеряет. Берём app.js ДО первой правки (90823e8~1) и
# требуем, чтобы на нём тест КРАСНЕЛ.
if git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 \
   && git -C "$ROOT" cat-file -e '90823e8~1:webpanel/www/app.js' 2>/dev/null; then
    _old=$(mktemp) || exit 1
    git -C "$ROOT" show '90823e8~1:webpanel/www/app.js' > "$_old"
    _oldout=$(node "$HARNESS" "$_old" 2>&1)
    rm -f "$_old"
    case "$_oldout" in
        *"панель ответила ошибкой"*)
            ok "на коде до правки тест воспроизводит исходную жалобу (значит он рабочий)" ;;
        *)
            no "тест воспроизводит дефект на старом коде" \
               "«панель ответила ошибкой» в выводе" \
               "не воспроизвёл — харнесс ничего не проверяет" ;;
    esac
else
    SKIP=$((SKIP+1))
    printf '[SKIP] сверка со старым app.js (нет git-истории в этой копии)\n'
fi

printf '\nPASSED: %d\nFAILED: %d\nSKIPPED: %d\n' "$PASS" "$FAIL" "$SKIP"
[ "$FAIL" -eq 0 ]
