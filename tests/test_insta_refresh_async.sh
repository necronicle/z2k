#!/bin/sh
# tests/test_insta_refresh_async.sh — обновление адресов Instagram/WhatsApp
# не держит установку.
#
# ЖАЛОБА. Установка «висела минутами» и последним на экране оставалась строка
# «DNS записи для Instagram уже настроены». Люди решали, что всё сломалось.
# Доходило до конца, но выглядело как зависший экран — и приходили с этим
# не по одному.
#
# ЧТО ПРОИСХОДИЛО НА САМОМ ДЕЛЕ. Сразу за этой строкой шёл единственный шаг с
# полностью погашенным выводом: z2k-insta-ip-refresh.sh, запущенный синхронно.
# Внутри — проба живости каждого адреса: 12 хостов, до 29 адресов, curl -m 6
# на каждый. Замерено на живой сети 2026-08-12:
#
#   отвечают            20 адресов  ~0,3 с
#   TLS-сброс            3 адреса   ~0,2 с   (instagram.c10r.instagram.com)
#   чёрная дыра          6 адресов   6,0 с   (157.240.0.60, 57.144.249.32 —
#                                             TCP не соединяется, time_connect=0)
#   ---------------------------------------------------------------
#   итого на той сети   41,7 с, из них 37 — четыре хоста WhatsApp
#   худший случай       174 с, если молчат все 29
#
# Хосты WhatsApp и сама проба появились одним коммитом 502ac06 (2026-08-05,
# релиз r-72.2) — он же и создал зависание: добавил пять хостов, и именно у
# них адреса оказались чёрными дырами.
#
# ЧТО ОХРАНЯЕМ. Работа нужная — проба отбрасывает как раз мёртвые адреса, ради
# этого веб-клиент WhatsApp и чинился. Но установку она блокировать не должна:
# записи ip host уже есть и рабочие. Поэтому запуск фоновой и в самом конце.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
INST="$ROOT/lib/install.sh"
REFRESH="$ROOT/files/z2k-insta-ip-refresh.sh"

for f in "$INST" "$REFRESH"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

# --- 1. Синхронного запуска в установке больше нет ----------------------------
#
# Именно эта строка и держала экран. Ищем её в любом виде: запуск скрипта,
# после которого установка ждёт.
# Проверяем не отдельную строку, а МЕСТО: `&` стоит на строке закрывающей
# скобки подоболочки, поэтому «строка без амперсанда» ничего не доказывает.
# Требуем, чтобы ВСЕ запуски скрипта лежали внутри фонового блока.
_bg_from=$(grep -n 'ОБНОВЛЕНИЕ АДРЕСОВ INSTAGRAM/WHATSAPP' "$INST" | head -1 | cut -d: -f1)
_bg_to=$(awk -v s="${_bg_from:-0}" 'NR>s && /^    fi$/ {print NR; exit}' "$INST")
_outside=$(grep -nE 'sh +"\$\{ZAPRET2_DIR\}/z2k-insta-ip-refresh\.sh"' "$INST" \
           | awk -F: -v a="${_bg_from:-0}" -v b="${_bg_to:-0}" '$1<a || $1>b')
if [ -z "$_outside" ]; then
    ok "скрипт запускается только из фонового блока, установку не держит"
else
    no "запуск не блокирует установку" "только внутри фонового блока" "$_outside"
fi

# --- 2. Фоновый запуск есть, и он переживёт конец установки -------------------
_bg=$(awk '/ОБНОВЛЕНИЕ АДРЕСОВ INSTAGRAM\/WHATSAPP/,/^    fi$/' "$INST")
if [ -n "$_bg" ]; then
    ok "фоновый запуск объявлен"
else
    no "фоновый запуск" "блок есть" "не найден"
    printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
    exit 1
fi
# trap '' HUP — иначе busybox ash убьёт задачу, когда установщик выйдет, и она
# оборвётся на середине проб. Ровно эта же грабля была у задач веб-панели.
case "$_bg" in
    *'trap "" HUP'*) ok "фоновая задача не умрёт от SIGHUP при выходе установщика" ;;
    *) no "trap HUP в фоновой задаче" 'trap "" HUP' "нет — задача оборвётся" ;;
esac
# Стдин закрыт и вывод отвязан: иначе фоновый процесс держит конвейер
# установщика, и вызывающий не увидит завершения, пока не досчитаются пробы.
case "$_bg" in
    *'</dev/null >/dev/null 2>&1 &'*) ok "задача отвязана от конвейера установщика" ;;
    *) no "отвязка от конвейера" '</dev/null >/dev/null 2>&1 &' "нет" ;;
esac
# Молчания быть не должно: человеку сказано, что процесс идёт, и где смотреть.
case "$_bg" in
    *"в фоне"*) ok "человеку сказано, что обновление идёт в фоне" ;;
    *) no "сообщение о фоновой работе" "упоминание фона" "нет" ;;
esac
case "$_bg" in
    *"z2k-insta-refresh.log"*) ok "назван журнал, по которому это проверяется" ;;
    *) no "путь к журналу в сообщении" "z2k-insta-refresh.log" "нет" ;;
esac

# --- 3. Запуск стоит ПОСЛЕ объявления о завершении ----------------------------
#
# Иначе смысл теряется: фоновая задача, запущенная в середине, будет драться за
# ndmc с соседним блоком, который чистит записи Discord и делает
# «system configuration save».
_done_line=$(grep -n 'Установка zapret2 завершена!' "$INST" | head -1 | cut -d: -f1)
_bg_line=$(grep -n 'ОБНОВЛЕНИЕ АДРЕСОВ INSTAGRAM/WHATSAPP' "$INST" | head -1 | cut -d: -f1)
if [ -n "$_done_line" ] && [ -n "$_bg_line" ] && [ "$_bg_line" -gt "$_done_line" ]; then
    ok "фоновый запуск идёт после объявления о завершении установки"
else
    no "порядок запуска" "после «Установка завершена»" "завершение=$_done_line запуск=$_bg_line"
fi
# И до него не должно остаться ndmc-операций этого же скрипта в один момент с
# чисткой Discord: проверяем, что между ними нет синхронного вызова.
_between=$(awk -v a="$_done_line" -v b="$_bg_line" 'NR>a && NR<b' "$INST" \
           | grep -c 'z2k-insta-ip-refresh.sh' || true)
if [ "${_between:-0}" = "0" ]; then
    ok "между завершением и фоновым запуском обновление не вызывается повторно"
else
    no "нет повторного вызова" "0" "$_between"
fi

# --- 4. Таймаут пробы подрезан ------------------------------------------------
#
# Отвечающий узел укладывается в 0,3 с, молчащий выбирает таймаут целиком —
# лишние секунды покупают только ожидание на мёртвом адресе.
_t=$(grep -oE 'PROBE_TIMEOUT="\$\{Z2K_IP_PROBE_TIMEOUT:-[0-9]+\}"' "$REFRESH" \
     | grep -oE '[0-9]+\}' | tr -d '}')
if [ -n "$_t" ] && [ "$_t" -le 3 ] && [ "$_t" -ge 2 ]; then
    ok "таймаут пробы $_t с — с запасом над измеренными 0,3 с и без лишнего ожидания"
else
    no "таймаут пробы" "2..3 с" "${_t:-не найден}"
fi
# Переопределение переменной окружения обязано сохраниться: им пользуются
# при разборе жалоб.
case "$(grep -m1 'PROBE_TIMEOUT=' "$REFRESH")" in
    *'${Z2K_IP_PROBE_TIMEOUT:-'*) ok "таймаут по-прежнему переопределяется переменной окружения" ;;
    *) no "переопределение таймаута" "Z2K_IP_PROBE_TIMEOUT" "убрано" ;;
esac

# --- 5. Сама проба на месте ---------------------------------------------------
#
# Убрать её было бы «починкой» зависания ценой возврата исходной беды: именно
# она отбрасывает мёртвые адреса WhatsApp, ради чего всё и делалось.
if grep -q 'probe_ip_alive' "$REFRESH" && grep -q 'filter_alive' "$REFRESH"; then
    ok "проба живости адресов сохранена"
else
    no "проба сохранена" "probe_ip_alive + filter_alive" "исчезла"
fi
# И правило «ни один не ответил — не трогаем прежние записи» тоже.
case "$(awk '/^for h in \$HOSTS; do/,/^done$/' "$REFRESH")" in
    *"прежние записи оставлены"*) ok "при полном молчании прежние пины не стираются" ;;
    *) no "защита прежних записей" "ветка «прежние записи оставлены»" "нет" ;;
esac

# --- 6. Комментарий не врёт про число хостов ----------------------------------
_n=$(grep -m1 '^HOSTS=' "$REFRESH" | sed 's/HOSTS=//; s/"//g' | tr ' ' '\n' | grep -c .)
if grep -q "the $_n hostnames" "$REFRESH" || grep -q "$_n hostnames" "$REFRESH"; then
    ok "в шапке скрипта указано верное число хостов ($_n)"
else
    no "число хостов в комментарии" "$_n" "$(grep -oE '[0-9]+ insta hostnames|[0-9]+ hostnames' "$REFRESH" | head -1)"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
