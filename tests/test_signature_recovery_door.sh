#!/bin/sh
# tests/test_signature_recovery_door.sh — дверь восстановления открыта, но
# продукт в неё никого не гонит.
#
# УСТРОЙСТВО, КОТОРОЕ ЗДЕСЬ ОХРАНЯЕТСЯ.
#
# Подпись манифеста гейтит ТОЛЬКО авто-канал. Ручная переустановка командой из
# README не гейтится никогда и приносит новый публичный ключ. Благодаря этому
# мёртвый ключ означает «встали автообновления, обход работает», а не «флот
# заморожен навсегда» — ровно та причина, по которой подпись однажды уже
# откатывали (6fbe694).
#
# НО У ЭТОЙ ДВЕРИ ЕСТЬ УСЛОВИЕ, БЕЗ КОТОРОГО ОНА СТАНОВИТСЯ ВХОДОМ.
#
# Атакующий, контролирующий транспорт, репозиторий не трогает: он устойчиво
# роняет авто-канал и ждёт. Если продукт в ответ на отказ подписи начнёт
# советовать «переустановите вручную», он своими руками переведёт человека с
# гейтированного канала на негейтированный — и атака на транспорт станет
# подменой доверия без всякой компрометации GitHub.
#
# Поэтому: отказ подписи говорит «обновление отклонено, обход работает» и
# МОЛЧИТ дальше. Дверь — то, что человек находит в README сам, а не то, куда
# его подталкивает продукт.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
AU="$ROOT/lib/auto_update.sh"
INS="$ROOT/lib/install.sh"
for f in "$AU" "$INS"; do [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }; done

# --- 1. Отказ подписи не советует переустановку -------------------------------
#
# Берём каждую строку отказа по подписи и смотрим на неё и три следующие: там не
# должно быть ни слова про ручную переустановку.
_bad=0
for _ln in $(grep -n 'ОТКАЗ:.*подпис' "$AU" | cut -d: -f1); do
    if sed -n "${_ln},$((_ln + 3))p" "$AU" | grep -qiE 'переустанов|reinstall|z2k\.sh install'; then
        printf '[FAIL] строка %s: отказ подписи подталкивает к переустановке\n' "$_ln"
        _bad=$((_bad + 1))
    fi
done
if [ "$_bad" = "0" ]; then
    ok "отказ подписи не предлагает ручную переустановку"
else
    FAIL=$((FAIL + _bad))
fi

# Сообщения об отказе вообще должны существовать — иначе первый тест зелёный
# просто потому, что отказывать нечему.
if [ "$(grep -c 'ОТКАЗ:.*подпис' "$AU")" -ge 2 ]; then
    ok "отказы по подписи в коде есть (иначе проверка выше бессмысленна)"
else
    no "отказы по подписи в коде есть" "минимум 2" "$(grep -c 'ОТКАЗ:.*подпис' "$AU")"
fi

# --- 2. Ручной путь установки подписью НЕ гейтится ----------------------------
#
# Это и есть дверь. Если install.sh начнёт требовать валидную подпись манифеста,
# восстанавливаться станет нечем, и мы вернёмся ровно к той причине, по которой
# подпись откатывали.
if grep -qE 'au_manifest_verify|z2k-verify .*UPDATES' "$INS"; then
    no "ручная установка не гейтится подписью" "install.sh не проверяет подпись манифеста" \
       "проверка найдена — дверь закрыта"
else
    ok "ручная установка не гейтится подписью (дверь открыта)"
fi

# --- 3. Но ключ молча не подменяется ------------------------------------------
if grep -q 'z2k_guard_key_swap' "$INS"; then
    ok "перед раскладкой ключа стоит защита от подмены"
else
    no "перед раскладкой ключа стоит защита от подмены" "z2k_guard_key_swap" "не найдено"
fi

_g=$(grep -n 'z2k_guard_key_swap ||' "$INS" | head -1 | cut -d: -f1)
_d=$(grep -n 'deploy_critical_file "files/etc/z2k-update-pub.pem"' "$INS" | head -1 | cut -d: -f1)
if [ -n "$_g" ] && [ -n "$_d" ] && [ "$_g" -lt "$_d" ]; then
    ok "защита срабатывает ДО раскладки ключа (строка $_g < $_d)"
else
    no "защита срабатывает до раскладки" "guard раньше deploy" "guard=$_g deploy=$_d"
fi

# Подтверждение принимается только точным отпечатком нового ключа: «любое
# непустое значение» превратило бы защиту в формальность.
if grep -q 'Z2K_TRUST_NEW_KEY:-}" = "\$_h_new"' "$INS"; then
    ok "подтверждение сверяется с отпечатком нового ключа, а не просто «задано»"
else
    no "подтверждение сверяется с отпечатком" 'сравнение с $_h_new' "не найдено"
fi

# --- 4. Защита не мешает первой установке -------------------------------------
#
# Пока храповик не защёлкнут, подпись здесь ни разу не работала, и требовать
# подтверждения не с чем: так мы заперли бы обычную установку на ровном месте.
if awk '/^z2k_guard_key_swap\(\)/,/^}/' "$INS" | grep -q '\[ -f "\$_pin" \] || return 0'; then
    ok "без защёлкнутого храповика защита пропускает"
else
    no "без защёлкнутого храповика защита пропускает" "ранний return 0 по храповику" "не найдено"
fi

# --- 5. Подтверждённая замена сбрасывает храповик ------------------------------
#
# Доверие начинается заново с нового ключа. Не сбросить — значит оставить
# коробку с храповиком под старый ключ и новым ключом в дереве: следующий же
# манифест был бы отвергнут, и человек получил бы отказ после того, как всё
# сделал правильно.
if awk '/^z2k_guard_key_swap\(\)/,/^}/' "$INS" | grep -q 'rm -f "\$_pin"'; then
    ok "подтверждённая замена ключа сбрасывает храповик"
else
    no "подтверждённая замена сбрасывает храповик" "rm -f pin" "не найдено"
fi

# --- 6. Отпечаток ключа опубликован -------------------------------------------
#
# Без него подтверждение Z2K_TRUST_NEW_KEY бессмысленно: человеку нечем сверить
# показанный отпечаток, и «сверьте с README» превращается в «подтвердите что
# угодно».
_README="$ROOT/README.md"
_KEY="$ROOT/files/etc/z2k-update-pub.pem"
if [ -s "$_KEY" ] && [ -f "$_README" ]; then
    if command -v sha256sum >/dev/null 2>&1; then _h=$(sha256sum "$_KEY" | cut -d' ' -f1)
    else _h=$(shasum -a 256 "$_KEY" | cut -d' ' -f1); fi
    if grep -qF "$_h" "$_README"; then
        ok "отпечаток ключа опубликован в README и совпадает с файлом"
    else
        no "отпечаток ключа опубликован в README" "$_h" "в README его нет или он устарел"
    fi
else
    no "ключ и README на месте" "оба файла" "нет"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
