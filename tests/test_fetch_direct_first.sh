#!/bin/sh
# tests/test_fetch_direct_first.sh — прямой GitHub идёт первым, но не ценой тех,
# у кого он закрыт.
#
# ЗАЧЕМ. Раньше первым шёл наш VPS: у части провайдеров адреса GitHub закрыты, и
# таким людям прямой путь недоступен вовсе. Но цена этого порядка видна только на
# масштабе — ВЕСЬ флот ходит к GitHub с ОДНОГО адреса, нашего узла, а лимиты там
# считаются по адресу источника. Замер 31.08.2026: в тишине ответ за 25 мс, под
# нагрузкой зависания в три секунды и обрывы; хуже всего в момент публикации,
# когда обновляются все разом. Установки при этом остаются без движка.
#
# Порядок теперь обратный, но с условием: вердикт «прямой не работает» выносится
# ОДИН РАЗ ЗА ПРОГОН. Иначе человек с заблокированным GitHub платил бы таймаут на
# каждом из полусотни файлов.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
U="$ROOT/lib/utils.sh"

# --- 1. Прямой заход стоит ДО слоя VPS ---------------------------------------
d=$(grep -n 'ПРЯМОЙ GITHUB — ПЕРВЫМ' "$U" | head -1 | cut -d: -f1)
v=$(grep -n 'Layer 0: VPS SNI-passthrough' "$U" | head -1 | cut -d: -f1)
b=$(grep -n 'Z2K_FETCH_VPS_OUT:-0' "$U" | head -1 | cut -d: -f1)
if [ -n "$d" ] && [ -n "$b" ] && [ "$d" -lt "$b" ]; then
    ok "прямой путь пробуется раньше слоя VPS"
else
    bad "порядок слоёв не изменился (прямой на строке ${d:-нет}, VPS на ${b:-нет})"
fi

# --- 2. Вердикт запоминается на прогон ---------------------------------------
grep -q 'Z2K_FETCH_DIRECT_OUT=1' "$U" \
    && ok "прямой путь выключается до конца прогона" \
    || bad "нет размыкателя — таймаут будет платиться на каждом файле"

# --- 3. Выключает только отказ СОЕДИНЕНИЯ, не расхождение содержимого ---------
# Иначе одно несовпадение суммы с зеркала снимало бы быстрый путь целиком.
if awk '/ПРЯМОЙ GITHUB — ПЕРВЫМ/,/Слой 0 отключён размыкателем/' "$U" | grep -q 'Z2K_LAST_CONNFAIL'; then
    ok "считаются только отказы соединения"
else
    bad "размыкатель срабатывает не по отказу соединения"
fi

# --- 4. Успех обнуляет счётчик -----------------------------------------------
awk '/ПРЯМОЙ GITHUB — ПЕРВЫМ/,/Слой 0 отключён размыкателем/' "$U" \
    | grep -q 'Z2K_FETCH_DIRECT_CONNFAILS=0' \
    && ok "успешная загрузка обнуляет счётчик" \
    || bad "счётчик не обнуляется — прямой путь отвалится на разовой осечке"

# --- 5. Прежний порядок возвращается одной переменной -------------------------
grep -q 'Z2K_FETCH_DIRECT_FIRST:-1' "$U" \
    && ok "порядок возвращается через Z2K_FETCH_DIRECT_FIRST" \
    || bad "нет способа вернуть прежний порядок без правки кода"

# --- 6. Поведение целиком: три прогона на подставном загрузчике ---------------
# Проверяем ЛОГИКУ размыкателя тем же выражением, что стоит в коде.
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT
Z2K_FETCH_DIRECT_CONNFAILS=0
Z2K_FETCH_DIRECT_OUT=0
RES=""
# БЕЗ подстановки команд: она порождает подоболочку, и присваивания в ней не
# переживают вызов. В боевом коде переменные экспортируются и живут весь прогон,
# а первая версия этого теста ловила собственную ошибку, а не поведение кода.
step() {
    if [ "${Z2K_FETCH_DIRECT_OUT:-0}" = "1" ]; then RES="$RES пропущен"; return; fi
    if [ "$1" = "0" ]; then Z2K_FETCH_DIRECT_CONNFAILS=0; RES="$RES успех"; return; fi
    Z2K_FETCH_DIRECT_CONNFAILS=$((Z2K_FETCH_DIRECT_CONNFAILS + 1))
    [ "$Z2K_FETCH_DIRECT_CONNFAILS" -ge 2 ] && Z2K_FETCH_DIRECT_OUT=1
    RES="$RES отказ"
}
step 1; step 1; step 1
[ "$RES" = " отказ отказ пропущен" ] \
    && ok "после двух отказов прямой путь больше не пробуется" \
    || bad "размыкатель не сработал:$RES"

# И обратное: успех посреди отказов возвращает счётчик к нулю, то есть разовая
# осечка не снимает быстрый путь.
Z2K_FETCH_DIRECT_CONNFAILS=0; Z2K_FETCH_DIRECT_OUT=0; RES=""
step 1; step 0; step 1; step 1
[ "$RES" = " отказ успех отказ отказ" ] \
    && ok "успех посреди отказов сбрасывает счёт" \
    || bad "счётчик не сбрасывается:$RES"

# --- 7. Правка есть во ВСЕХ копиях цепочки ------------------------------------
# z2k_fetch продублирована в трёх файлах: установщик, библиотека и обновлялка
# списков. Правка в одной копии означает, что два пути из трёх ходят по-старому,
# и расхождение никак себя не проявит до жалобы. Первая версия этой правки как
# раз и легла в одну копию — поймал тест соседней сьюты, а не я.
for f in z2k.sh lib/utils.sh files/z2k-update-lists.sh; do
    if grep -q 'Z2K_FETCH_DIRECT_FIRST' "$ROOT/$f"; then
        ok "$f: прямой путь первым"
    else
        bad "$f: копия цепочки осталась со старым порядком"
    fi
done

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
