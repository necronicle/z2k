#!/bin/sh
# tests/test_4pda_static_resolve.sh
#
# 4pda.to обслуживается зарубежным резолвом, как Instagram и WhatsApp.
#
# ЗАЧЕМ. Замер 19.08.2026: провайдерский DNS отдаёт 8.6.112.0 и 8.47.69.0, к ним
# TLS не встаёт вовсе (tls_handshake_timeout за 5,3 с). Те же адреса с
# зарубежного выхода отвечают подлинным сертификатом CN=4pda.to — узлы живые,
# закрыт путь. Наша диагностика видит блок ПО АДРЕСУ: с нейтральным именем
# example.com те же адреса тоже молчат. Пакетными техниками это не обходится
# в принципе (manual, «Блокировка по IP»), помогает только другой адрес.
# С адресами зарубежного резолва TLS встаёт за 150 мс.
#
# Цепочка живёт в трёх местах, и порваться может любое звено — молча:
#   1. аллоулист /resolve на VPS      (vps-relay/main.go)
#   2. список HOSTS в скрипте         (files/z2k-insta-ip-refresh.sh)
#   3. засев записей при установке    (lib/install.sh)
# Сторожим все три плюс развязку с пунктом меню [I].

DIR="$(cd "$(dirname "$0")/.." && pwd)"
RELAY="$DIR/vps-relay/main.go"
REFRESH="$DIR/files/z2k-insta-ip-refresh.sh"
INSTALL="$DIR/lib/install.sh"
PASS=0
FAIL=0

ok()  { PASS=$((PASS + 1)); echo "[PASS] $1"; }
bad() { FAIL=$((FAIL + 1)); echo "[FAIL] $1"; }

for f in "$RELAY" "$REFRESH" "$INSTALL"; do
    [ -f "$f" ] || { echo "нет $f"; exit 1; }
done

# --- 1. VPS пускает домен в /resolve -----------------------------------------
# Без апекса запрос вернёт отказ, и роутер останется со старыми адресами.
if grep -q '"4pda\.to":' "$RELAY"; then
    ok "аллоулист /resolve содержит апекс 4pda.to"
else
    bad "в аллоулисте /resolve нет апекса 4pda.to — VPS откажет в резолве"
fi
if grep -q '"\.4pda\.to"' "$RELAY"; then
    ok "аллоулист /resolve принимает поддомены .4pda.to"
else
    bad "нет суффикса .4pda.to — www и s резолвиться не будут"
fi

# --- 2. Скрипт обновляет нужные имена ----------------------------------------
# Три имени, а не одно: www и s резолвятся в те же битые адреса и держат
# картинки со статикой. Проверяем поимённо, чтобы «сократить до апекса» не
# прошло незамеченным.
hosts=$(grep -m1 '^HOSTS=' "$REFRESH" | sed 's/HOSTS=//; s/"//g')
for h in 4pda.to www.4pda.to s.4pda.to; do
    case " $hosts " in
        *" $h "*) ok "HOSTS содержит $h" ;;
        *)        bad "в HOSTS нет $h — адрес останется провайдерским" ;;
    esac
done

# --- 3. Записи заводятся при установке ---------------------------------------
if grep -q '^z2k_4pda_dns_add_fallback()' "$INSTALL"; then
    ok "есть функция засева z2k_4pda_dns_add_fallback"
else
    bad "функции засева нет — на свежей установке 4pda останется без записей"
fi
if grep -q 'z2k_4pda_dns_add_fallback$' "$INSTALL"; then
    ok "функция засева вызывается при установке"
else
    bad "функция объявлена, но не вызывается"
fi

# --- 4. Развязка с пунктом меню [I] ------------------------------------------
# Ключевое требование: очистка записей Instagram пользователем не должна
# уносить 4pda, к которому Instagram отношения не имеет.
insta_fn=$(awk '/^z2k_instagram_dns_add_fallback\(\)/,/^}/' "$INSTALL")
case "$insta_fn" in
    *4pda*) bad "4pda внутри инстаграмной функции — очистка через [I] снесёт и его" ;;
    *)      ok  "4pda не внутри инстаграмной функции: [I] его не трогает" ;;
esac

# Сторож «пользователь всё вычистил» обязан смотреть и на 4pda, иначе человек,
# нажавший [I], перестанет получать обновление адресов 4pda, не выбирав этого.
guard=$(grep -A 2 '^existing=' "$REFRESH")
case "$guard" in
    *4pda*) ok "сторож очистки учитывает записи 4pda" ;;
    *)      bad "сторож смотрит только на instagram — очистка [I] отключит и 4pda" ;;
esac

# --- 5. Стартовые адреса не из блокируемого диапазона ------------------------
# Засевать тем, что и так режут, бессмысленно. 8.6.112.0/8.47.69.0 — ровно те
# адреса, которые отдаёт провайдерский DNS и к которым TLS не встаёт.
seed_fn=$(awk '/^z2k_4pda_dns_add_fallback\(\)/,/^}/' "$INSTALL")
case "$seed_fn" in
    *8.6.112.0*|*8.47.69.0*) bad "засев использует адреса, которые режут — смысла нет" ;;
    *)                       ok  "засев не использует блокируемые адреса" ;;
esac
if printf '%s' "$seed_fn" | grep -qE 'ip host (www\.|s\.)?4pda\.to [0-9]+\.[0-9]+\.[0-9]+\.[0-9]+'; then
    ok "засев прописывает конкретные адреса"
else
    bad "в засеве нет ни одной записи ip host с адресом"
fi

echo
echo "PASSED: $PASS"
echo "FAILED: $FAIL"
[ "$FAIL" = "0" ]
