#!/bin/sh
# tests/test_reasm_disable_tls_only.sh — движок не должен придерживать
# ClientHello, который не влез в один TCP-сегмент. И выключать пересборку
# QUIC при этом нельзя.
#
# ЗАЧЕМ. На Keenetic пересборка TLS ClientHello не завершается: первый сегмент
# движок держит («DELAY desync until reasm is complete»), а второй до NFQUEUE
# не доходит. Первый в итоге дропается, клиент ретрансмитит и упирается в
# таймаут — сайт для браузера не открывается вообще. Апстрим: bol-van/zapret2#229.
#
# Замер 2026-08-21 на роутере Марка, img.reg.ru (194.58.116.35), ClientHello
# ровно заданного размера:
#
#   до правки:    1440 байт → 5 из 5 OK,  1455 байт → 0 из 5
#   после правки: 1455/1800/2200 → OK,    1800 байт → 5 из 5
#
# Причинность снята включением-выключением через nozapret: адрес видит обход —
# тишина, адрес исключён — ServerHello, вернули — снова тишина. От SNI порог не
# зависит, то есть держится сегмент, а не решение по хостлисту.
#
# ЧТО ИМЕННО ПИНИТСЯ. Не «флаг присутствует», а его ОБЛАСТЬ:
#   - выключено для tls_client_hello;
#   - НЕ выключено целиком (голый --reasm-disable убил бы и разбор склеенных
#     QUIC Initial, а на нём стоит ютубный UDP-пул);
#   - флаг лежит в опциях ДЕМОНА, а не внутри профиля: пересборка — свойство
#     разборщика пакетов, в строке профиля она просто не сработает.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
SRC="${Z2K_INITD_UNDER_TEST:-$ROOT/files/S99zapret2.new}"

TMP=$(mktemp -d "${TMPDIR:-/tmp}/z2k-reasm.XXXXXX") || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

[ -f "$SRC" ] || { printf '[FAIL] нет %s\n' "$SRC"; exit 1; }

# --- собираем строку опций демона так, как её собирает init ------------------
#
# Берём ТОЛЬКО присваивания NFQWS2_OPT_BASE и исполняем их с подставными
# входами. Это не грепанье по файлу: если завтра флаг переедет в переменную,
# в подстановку или под условие, здесь он всё равно окажется в итоговой строке
# — либо не окажется, и тест покраснеет.
grep -n '^NFQWS2_OPT_BASE=' "$SRC" | sed 's/^[0-9]*://' > "$TMP/opts.sh"
if [ -s "$TMP/opts.sh" ]; then
    ok "присваивания NFQWS2_OPT_BASE извлечены ($(wc -l < "$TMP/opts.sh" | tr -d ' ') шт.)"
else
    no "присваивания NFQWS2_OPT_BASE извлечены" "хотя бы одно" "ноль"
    printf '\n%s: PASS=%s FAIL=%s\n' "$(basename "$0")" "$PASS" "$FAIL"; exit 1
fi

OPTS=$(env -i PATH=/usr/bin:/bin SB="$TMP" /bin/sh -c '
    USEROPT="--user=nobody"; DESYNC_MARK="0x40000000"; LUAOPT="--lua-init=@x.lua"
    . "$SB/opts.sh"
    printf "%s" "$NFQWS2_OPT_BASE"
' 2>/dev/null)

if [ -n "$OPTS" ]; then
    ok "строка опций демона собралась"
else
    no "строка опций демона собралась" "непустая" "пусто"
fi

# --- 1. ГЛАВНОЕ: пересборка TLS ClientHello выключена ------------------------
case "$OPTS" in
    *--reasm-disable=tls_client_hello*)
        ok "пересборка TLS ClientHello выключена (#229 больше не воспроизводится)" ;;
    *)
        no "пересборка TLS ClientHello выключена" "--reasm-disable=tls_client_hello" \
           "флага нет — вернётся зависание браузера на большом ClientHello" ;;
esac

# --- 2. Но НЕ выключена целиком ----------------------------------------------
#
# Голый `--reasm-disable` (без аргумента) в справке движка означает «disable all
# reasm». Это забрало бы и разбор склеенных QUIC Initial, на котором стоит
# ютубный UDP-пул, — то есть чинило бы один сайт ценой видео.
_bare=$(printf '%s' "$OPTS" | tr ' ' '\n' | grep -cx -- '--reasm-disable')
if [ "${_bare:-0}" = "0" ]; then
    ok "пересборка выключена не целиком — голого --reasm-disable нет"
else
    no "голого --reasm-disable нет" "0 штук" "$_bare — выключен и разбор QUIC Initial"
fi

# --- 3. QUIC явно не перечислен ----------------------------------------------
case "$OPTS" in
    *reasm-disable=*quic_initial*)
        no "QUIC-пересборка сохранена" "quic_initial не перечислен" "перечислен — ютубный UDP-пул ослеп" ;;
    *)
        ok "QUIC-пересборка сохранена (quic_initial не перечислен)" ;;
esac

# --- 4. Флаг — у ДЕМОНА, а не внутри профиля ---------------------------------
#
# Профильные строки собираются отдельно и разделяются --new. Пересборка живёт
# в разборщике пакетов: попав в строку профиля, флаг молча ничего не сделает,
# а выглядел бы как применённый.
case "$OPTS" in
    *--new*) no "опции демона не содержат разделителя профилей" "без --new" "внутри оказался --new" ;;
    *)       ok "флаг лежит в опциях демона, а не в строке профиля" ;;
esac

_in_profile=$(grep -c -- '--reasm-disable' "$SRC" 2>/dev/null)
if [ "${_in_profile:-0}" = "1" ]; then
    ok "флаг задан ровно в одном месте"
else
    no "флаг задан ровно в одном месте" "1 вхождение" "$_in_profile — есть вторая копия, они разъедутся"
fi

printf '\n%s: PASS=%s FAIL=%s\n' "$(basename "$0")" "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
