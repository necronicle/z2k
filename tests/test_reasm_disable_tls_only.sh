#!/bin/sh
# tests/test_reasm_disable_tls_only.sh — движок не должен придерживать
# ClientHello, который не влез в один TCP-сегмент. И выключать пересборку
# QUIC при этом нельзя.
#
# ЗАЧЕМ. На Keenetic пересборка TLS ClientHello не завершается: первый сегмент
# движок держит («DELAY desync until reasm is complete»), а второй до NFQUEUE
# не доходит. Первый в итоге дропается, клиент ретрансмитит и упирается в
# таймаут — сайт для браузера не открывается вообще. Апстрим: bol-van/zapret2#229.
#
# Замер 2026-08-21 на роутере Марка, img.reg.ru (194.58.116.35), ClientHello
# ровно заданного размера:
#
#   до правки:    1440 байт → 5 из 5 OK,  1455 байт → 0 из 5
#   после правки: 1455/1800/2200 → OK,    1800 байт → 5 из 5
#
# Причинность снята включением-выключением через nozapret: адрес видит обход —
# тишина, адрес исключён — ServerHello, вернули — снова тишина. От SNI порог не
# зависит, то есть держится сегмент, а не решение по хостлисту.
#
# ЧТО ИМЕННО ПИНИТСЯ. Не «флаг присутствует», а его ОБЛАСТЬ и ЦЕНА:
#   - выключено для tls_client_hello;
#   - НЕ выключено целиком (голый --reasm-disable убил бы и разбор склеенных
#     QUIC Initial, а на нём стоит ютубный UDP-пул);
#   - флаг лежит в опциях ДЕМОНА, а не внутри профиля: пересборка — свойство
#     разборщика пакетов, в строке профиля она просто не сработает;
#   - проба движка стоит РОВНО ОДИН exec на процесс и платится только при
#     запуске демона, а не на каждый subcommand.
#
# ПОЧЕМУ ХАРНЕСС ПЕРЕПИСАН. Гейт переехал с верхнего уровня в функцию
# z2k_apply_reasm_gate, которую зовёт run_nfqws. Прежний харнесс вырезал
# участок «от сборки NFQWS2_OPT_BASE до первого fi после reasm» — этого шва
# больше нет. Заодно тот awk печатал закрывающий `fi` дважды: под bash файл
# успевал выполниться до ошибки и тест зеленел, под dash (а это /bin/sh на
# ubuntu-latest) не разбирался вовсе. Отсюда же и tests/lib/common.sh.
#
# POSIX sh.

# Диалект вложенных оболочек задаётся набором, а не хардкодом: на macOS
# /bin/sh — это bash, в CI — dash, и один и тот же тест под ними ведёт себя
# по-разному. См. шапку tests/lib/common.sh.
. "$(cd "$(dirname "$0")" && pwd)/lib/common.sh"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
SRC="${Z2K_INITD_UNDER_TEST:-$ROOT/files/S99zapret2.new}"

TMP=$(mktemp -d "${TMPDIR:-/tmp}/z2k-reasm.XXXXXX") || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

[ -f "$SRC" ] || { printf '[FAIL] нет %s\n' "$SRC"; exit 1; }

# --- вынимаем ИСПОЛНЯЕМЫЕ куски ----------------------------------------------
#
# Грепать текст здесь нельзя: весь смысл правки в том, ПРИ КАКОМ УСЛОВИИ флаг
# попадает в строку. Берём определения функций и гоняем их с подставным
# движком — тогда проверяется то, что реально доедет до демона.
awk '/^z2k_apply_reasm_gate\(\)$/,/^\}$/' "$SRC" > "$TMP/gate.sh"
awk '/^run_nfqws\(\)$/,/^\}$/'           "$SRC" > "$TMP/run.sh"

if grep -q 'NFQWS2_OPT_BASE' "$TMP/gate.sh" && grep -q 'run_daemon' "$TMP/run.sh"; then
    ok "z2k_apply_reasm_gate и run_nfqws извлечены"
else
    no "функции извлечены" "обе непустые" \
       "gate=$(wc -l < "$TMP/gate.sh" | tr -d ' ') run=$(wc -l < "$TMP/run.sh" | tr -d ' ')"
    printf '\n%s: PASS=%s FAIL=%s\n' "$(basename "$0")" "$PASS" "$FAIL"; exit 1
fi

# --- подставные движки --------------------------------------------------------
#
# Три состояния, и различать их обязательно:
#   new  — знает и опцию, и ТИП (боевой);
#   half — печатает опцию, но НЕ печатает tls_client_hello. Такому движку флаг
#          отдавать нельзя: на незнакомом типе он делает exit_clean(1)
#          («Invalid l7 protocol list», nfqws.c, IDX_REASM_DISABLE) — то есть
#          демон не стартует, обход пропадает целиком;
#   old  — про reasm не знает вовсе.
# Каждый считает свои запуски: цена пробы — половина этой правки.
mkdir -p "$TMP/bin"
for _e in new half old; do
    {
        printf '#!/bin/sh\n'
        printf 'printf x >> "$ENG_CALLS"\n'
        case "$_e" in
            new)  printf 'echo "  --reasm-disable=[type[,type]] ; disable reasm : tls_client_hello quic_initial ."\n' ;;
            half) printf 'echo "  --reasm-disable=[type[,type]] ; disable reasm for these L7 payloads"\n' ;;
            old)  printf 'echo "  --dpi-desync=mode   ; старый движок, про reasm не знает"\n' ;;
        esac
    } > "$TMP/bin/nfqws2-$_e"
    chmod +x "$TMP/bin/nfqws2-$_e"
done

# gate_run <движок> <сколько раз звать run_nfqws>
# Печатает: строку(и), ушедшую(ие) в run_daemon, затем «---», затем вывод
# гейта (WARNING), затем «---», затем число exec'ов движка.
gate_run() {
    : > "$TMP/eng.calls"
    env -i PATH="$Z2K_TEST_PATH" SB="$TMP" ENG="$1" N="$2" \
        ENG_CALLS="$TMP/eng.calls" "$Z2K_TEST_SH" -c '
        USEROPT="--user=nobody"; DESYNC_MARK="0x40000000"; LUAOPT="--lua-init=@x.lua"
        NFQWS2="$ENG"
        NFQWS2_OPT_BASE="$USEROPT --fwmark=$DESYNC_MARK --bind-fix4 --bind-fix6 $LUAOPT"
        . "$SB/gate.sh"
        . "$SB/run.sh"
        # Подставной run_daemon печатает ровно то, что получил бы движок.
        run_daemon() { printf "%s\n" "$3"; }
        _i=1
        while [ "$_i" -le "$N" ]; do
            run_nfqws 1 "--new --filter-tcp=443 --lua-desync=fake:blob=x"
            _i=$((_i + 1))
        done
        printf -- "---\n"
        printf "%s" "$(cat "$ENG_CALLS" 2>/dev/null | wc -c | tr -d " ")"
    ' 2>&1
}

_new=$(gate_run "$TMP/bin/nfqws2-new"  1)
_half=$(gate_run "$TMP/bin/nfqws2-half" 1)
_old=$(gate_run "$TMP/bin/nfqws2-old"  1)

# Строка демона — всё до разделителя «---»; WARNING гейта тоже попадает сюда
# (он идёт в stdout init'а), поэтому берём именно строку с run_daemon.
_line_of() { printf '%s\n' "$1" | grep -- '--fwmark=' | head -1; }

# --- 1. ГЛАВНОЕ: движок знает опцию И тип — пересборка TLS CH выключена -------
case "$(_line_of "$_new")" in
    *--reasm-disable=tls_client_hello*)
        ok "движок знает опцию и тип → пересборка TLS ClientHello выключена (#229 не воспроизводится)" ;;
    *)
        no "пересборка TLS ClientHello выключена" "--reasm-disable=tls_client_hello" \
           "флага нет — вернётся зависание браузера на большом ClientHello" ;;
esac

# --- 2. F8: движок знает ОПЦИЮ, но не знает ТИП — флага быть не должно --------
#
# Раньше проба спрашивала только про имя опции, и здесь был ложный PASS: такой
# движок получал --reasm-disable=tls_client_hello и НЕ ЗАПУСКАЛСЯ. Обход
# пропадал целиком — то есть проба, написанная ради безопасности выкатки,
# ровно в этом случае её и ломала.
case "$(_line_of "$_half")" in
    *--reasm-disable*)
        no "движку без ТИПА флаг не передаётся" "без --reasm-disable" \
           "флаг передан — exit_clean(1) на разборе, демон не поднимется" ;;
    *)  ok "движок знает опцию, но не тип → флаг не передан (демон поднимется)" ;;
esac

# --- 3. Старый движок: флага нет, остальные опции целы, отказ ВИДЕН -----------
#
# Файл уезжает патч-каналом ОТДЕЛЬНО от бинарника (lib/auto_update.sh кладёт
# его в /opt/etc/init.d/S99zapret2, restart_set там безусловно содержит
# "S99zapret2"). Роутер может получить новый init и рестарт, оставшись на
# старом движке — и тогда в описании релиза написано «починено», а у человека
# висит. Молчаливый отказ гейта хуже отсутствующего гейта.
case "$(_line_of "$_old")" in
    *--reasm-disable*) no "старому движку флаг НЕ передаётся" "без --reasm-disable" "флаг передан" ;;
    *)                 ok "старому движку флаг не передаётся — демон поднимется" ;;
esac
case "$(_line_of "$_old")" in
    *--user=nobody*) ok "остальные опции старому движку передаются как прежде" ;;
    *) no "остальные опции сохранены" "--user=nobody" "$(_line_of "$_old")" ;;
esac
case "$_old" in
    *WARNING*) ok "отказ гейта виден в выводе init (WARNING)" ;;
    *) no "отказ гейта виден" "строка WARNING" "гейт промолчал — человек не узнает, почему висит" ;;
esac
case "$_new" in
    *WARNING*) no "на исправном движке гейт молчит" "без WARNING" "предупреждение на ровном месте" ;;
    *) ok "на исправном движке гейт молчит" ;;
esac

# --- 4. R9: цена пробы — один exec на процесс, и только при запуске демона ----
_calls_new=$(printf '%s\n' "$_new" | tail -1)
if [ "$_calls_new" = "1" ]; then
    ok "проба стоит ровно один exec движка"
else
    no "проба стоит один exec" "1" "${_calls_new:-нет счётчика}"
fi

_two=$(gate_run "$TMP/bin/nfqws2-new" 2)
_calls_two=$(printf '%s\n' "$_two" | tail -1)
if [ "$_calls_two" = "1" ]; then
    ok "второй запуск демона движок не переспрашивает (мемоизация)"
else
    no "мемоизация пробы" "1 exec на два вызова" "$_calls_two"
fi
# И флаг от этого не задваивается: NFQWS2_OPT_BASE правится один раз.
_dupe=$(printf '%s\n' "$_two" | grep -- '--fwmark=' \
        | tr ' ' '\n' | grep -c -- '--reasm-disable=tls_client_hello')
if [ "$_dupe" = "2" ]; then
    ok "на два запуска демона — по одному флагу в каждой строке, без задвоения"
else
    no "флаг не задваивается" "по 1 на строку (итого 2)" "$_dupe"
fi

# --- 5. Пересборка выключена НЕ целиком ---------------------------------------
#
# Голый `--reasm-disable` (без аргумента) в справке движка означает «disable all
# reasm». Это забрало бы и разбор склеенных QUIC Initial, на котором стоит
# ютубный UDP-пул, — то есть чинило бы один сайт ценой видео.
_bare=$(_line_of "$_new" | tr ' ' '\n' | grep -cx -- '--reasm-disable')
if [ "${_bare:-0}" = "0" ]; then
    ok "пересборка выключена не целиком — голого --reasm-disable нет"
else
    no "голого --reasm-disable нет" "0 штук" "$_bare — выключен и разбор QUIC Initial"
fi
case "$(_line_of "$_new")" in
    *reasm-disable=*quic_initial*)
        no "QUIC-пересборка сохранена" "quic_initial не перечислен" "перечислен — ютубный UDP-пул ослеп" ;;
    *)  ok "QUIC-пересборка сохранена (quic_initial не перечислен)" ;;
esac

# --- 6. Флаг — у ДЕМОНА, а не внутри профиля ---------------------------------
#
# Пересборка живёт в разборщике пакетов: попав в строку профиля, флаг молча
# ничего не сделает, а выглядел бы как применённый. Профили в командной строке
# отделены `--new`, значит флаг обязан стоять ЛЕВЕЕ первого --new.
#
# Прежняя проверка искала `--new` внутри извлечённого участка и не могла
# сработать никогда: строки профилей собираются ниже по файлу и в участок не
# попадали в принципе. Свойство было объявлено в шапке и не пинилось.
_daemon_part=$(_line_of "$_new" | sed 's/ --new .*//')
_profile_part=$(_line_of "$_new" | sed -n 's/.* \(--new .*\)/\1/p')
if [ -n "$_profile_part" ]; then
    ok "в строке есть и половина демона, и половина профиля (проверка не вакуумна)"
else
    no "в строке есть половина профиля" "часть после --new" "разделителя нет"
fi
case "$_daemon_part" in
    *--reasm-disable=tls_client_hello*) ok "флаг лежит в опциях демона (левее первого --new)" ;;
    *) no "флаг в опциях демона" "левее --new" "$_daemon_part" ;;
esac
case "$_profile_part" in
    *--reasm-disable*) no "флаг не попал в строку профиля" "без флага справа от --new" "$_profile_part" ;;
    *) ok "в строку профиля флаг не попал — там он молча ничего не делал бы" ;;
esac

# --- 7. Проба движка — ровно одна, и только на пути запуска демона ------------
#
# До R9 exec движка платился на КАЖДЫЙ subcommand: start_fw дёргают NDM-хук
# (~280 раз в сутки) и самолечение очереди (поминутно), и ни один из них демона
# не запускает. Здесь пинится, что вызов остался единственным и лежит в
# run_nfqws — единственном месте, где командная строка демона собирается.
_probe_lines=$(grep -c -- '"\$NFQWS2" --help' "$SRC")
if [ "$_probe_lines" = "1" ]; then
    ok "проба движка написана ровно один раз"
else
    no "проба движка одна" "1 вхождение" "$_probe_lines"
fi
if grep -q -- '"\$NFQWS2" --help' "$TMP/gate.sh"; then
    ok "проба лежит внутри z2k_apply_reasm_gate, а не на верхнем уровне"
else
    no "проба внутри функции" "в теле z2k_apply_reasm_gate" \
       "на верхнем уровне — вернётся exec на каждый subcommand"
fi
# Вызовов гейта ровно один (определение функции не считаем).
_gate_calls=$(grep -c '^[[:space:]]*z2k_apply_reasm_gate[[:space:]]*$' "$SRC")
if [ "$_gate_calls" = "1" ]; then
    ok "гейт зовётся ровно из одного места"
else
    no "гейт зовётся из одного места" "1 вызов" "$_gate_calls"
fi
if grep -q '^[[:space:]]*z2k_apply_reasm_gate[[:space:]]*$' "$TMP/run.sh"; then
    ok "вызов гейта стоит в run_nfqws (за stop/status/start_fw он не платится)"
else
    no "вызов гейта в run_nfqws" "внутри функции" "уехал наружу"
fi

# --- 8. Флаг задан в одном месте ---------------------------------------------
#
# Прежний счёт требовал РОВНО двух вхождений подстроки на весь файл. Он краснел
# от любого нового комментария, называющего флаг по имени, и от текста
# предупреждения — то есть наказывал за объяснение вместо расхождения. Считаем
# то, что действительно нельзя размножать: строку, ДОБАВЛЯЮЩУЮ флаг в опции.
# Комментариев, логов и сообщений может быть сколько угодно.
_assigns=$(awk '!/^[[:space:]]*#/ && /NFQWS2_OPT_BASE=/ && /--reasm-disable/' "$SRC" \
           | wc -l | tr -d ' ')
if [ "$_assigns" = "1" ]; then
    ok "флаг добавляется в опции ровно в одном месте"
else
    no "флаг добавляется в одном месте" "1 присваивание" \
       "$_assigns — вторая копия разъедется с первой"
fi

printf '\n%s: PASS=%s FAIL=%s\n' "$(basename "$0")" "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
