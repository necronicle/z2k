#!/bin/sh
# tests/test_shell_review_fixes.sh — находки ревью shell-кода 2026-08-15.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Все проверки ниже об одном классе: код вёл себя не так,
# как выглядел, и никто этого не видел, потому что видимого отказа не было.
# Человек нажимал «отмена» и получал согласие; вводил имя политики кириллицей и
# получал пустую строку; обновление не могло разложить файл и рапортовало успех.
# Такие дефекты возвращаются тихо, поэтому охраняются поведением, а не текстом.
#
# ГЛАВНОЕ ПРО ОБОЛОЧКУ. На роутере BusyBox ash, локально у разработчика zsh или
# bash. Половина находок существует ровно потому, что в bash код работает.
# Поэтому всё, что можно, исполняется через dash — ближайший доступный
# POSIX-прокси; на bash эти же проверки прошли бы и на сломанном коде.
#
# POSIX sh.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)

SH=$(command -v dash 2>/dev/null) || SH=""
[ -n "$SH" ] || SH="/bin/sh"

TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

# --- 1. confirm(): «отмена» это НЕ согласие -----------------------------------
#
# Классы вида *[Дд] на POSIX-оболочке сопоставляются побайтово: «Д» это D0 94,
# «д» это D0 B4, то есть набор {D0,94,B4}. У любого кириллического слова на «а»
# последние два байта D0 B0 — D0 попадает в набор от «Д», B0 в набор от «А», и
# срабатывает ветка `*[Дд][Аа]`. Проверено исполнением: «отмена» и «неа» давали
# согласие, а «нет» не распознавалось вовсе.
#
# Вырезаем настоящее тело case из lib/utils.sh, а не переписываем его: копия
# разойдётся с оригиналом и тест начнёт врать.
awk '/^        _ans_l=\$\(printf/,/^        esac$/' "$ROOT/lib/utils.sh" > "$TMP/case.frag"
if [ ! -s "$TMP/case.frag" ]; then
    no "тело confirm() найдено в lib/utils.sh" "фрагмент case" "не найден — тест не о чем"
else
    {
        echo 'print_warning() { echo REPROMPT; }'
        echo 'ans() {'
        echo '    answer="$1"'
        cat "$TMP/case.frag"
        echo '    echo REPROMPT'
        echo '}'
        echo 'for w in "$@"; do printf "%s=%s\n" "$w" "$(ans "$w")"; done'
    } > "$TMP/confirm.sh"

    # Внутри вырезанного case ветки делают return 0/1 — оборачиваем в функцию и
    # смотрим на код возврата: 0 = да, 1 = нет, REPROMPT = не распознано.
    verdict() {
        _v=$("$SH" -c '
            print_warning() { :; }
            ans() { answer="$1"; '"$(cat "$TMP/case.frag")"'
                    return 2; }
            ans "$1"; echo "rc=$?"' _ "$1" 2>/dev/null)
        case "$_v" in *rc=0*) echo YES ;; *rc=1*) echo NO ;; *) echo REPROMPT ;; esac
    }

    _bad=""
    # Слова отказа обязаны означать отказ, а не согласие.
    for w in "нет" "Нет" "НЕТ" "неа" "n" "no" "N"; do
        [ "$(verdict "$w")" = "NO" ] || _bad="$_bad $w->$(verdict "$w")"
    done
    if [ -z "$_bad" ]; then
        ok "слова отказа распознаются как отказ (включая «нет» и «неа»)"
    else
        no "слова отказа" "все NO" "$_bad"
    fi

    # И ни одно постороннее слово не должно означать согласие. «отмена» здесь
    # главное: именно оно давало YES на «Вы уверены? Это действие необратимо!».
    _bad=""
    for w in "отмена" "удалить" "код" "борщ" "продолжить" "ага" "хватит"; do
        [ "$(verdict "$w")" = "YES" ] && _bad="$_bad $w"
    done
    if [ -z "$_bad" ]; then
        ok "постороннее слово не превращается в согласие («отмена» в том числе)"
    else
        no "ложное согласие" "ни одного" "согласием прочтены:$_bad — они охраняют необратимые операции"
    fi

    # Согласие при этом обязано продолжать работать.
    _bad=""
    for w in "y" "Y" "yes" "YES" "да" "ДА" "Да"; do
        [ "$(verdict "$w")" = "YES" ] || _bad="$_bad $w->$(verdict "$w")"
    done
    [ -z "$_bad" ] && ok "слова согласия по-прежнему означают согласие" \
                   || no "слова согласия" "все YES" "$_bad"
fi

# --- 2. read_input(): кириллица доходит, управляющие байты нет ----------------
#
# Поддержка кириллического имени политики сделана в menu_policy_access
# специально и подробно (снят фильтр латиницы, сохранены пробелы, длина в
# символах). Она была мертва: read_input двумя строками выше стирал кириллицу
# целиком, и «Домашние устройства» превращалось в пустую строку.
# Диапазон закрывается по строке, оканчивающейся скобкой: конвейер бывал и
# однострочным, и разнесённым на три строки — тест обязан читать обе формы,
# иначе он краснеет из-за собственного разбора, а не из-за дефекта.
_pipe=$(awk '/_z2k_raw=\$\(printf/,/\)[[:space:]]*$/' "$ROOT/lib/menu.sh")
if [ -z "$_pipe" ]; then
    no "конвейер очистки найден в read_input" "строки с printf|tr|sed" "не найдены"
else
    clean() {
        "$SH" -c '_z2k_raw="$1"
            '"$_pipe"'
            printf "%s" "$_z2k_raw"' _ "$1" 2>/dev/null
    }
    if [ "$(clean 'Домашние устройства')" = "Домашние устройства" ]; then
        ok "кириллическое имя проходит read_input целиком"
    else
        no "кириллица в read_input" "Домашние устройства" \
           "[$(clean 'Домашние устройства')] — поддержка кириллицы в имени политики мертва"
    fi
    [ "$(clean 'Policy1')" = "Policy1" ] \
        && ok "латиница не пострадала" || no "латиница" "Policy1" "$(clean 'Policy1')"
    # Ради чего очистка вообще существует — управляющие байты.
    _ctl=$(printf 'аб\010\177вг')
    if [ "$(clean "$_ctl")" = "абвг" ]; then
        ok "управляющие байты по-прежнему вырезаются"
    else
        no "управляющие байты" "абвг" "$(clean "$_ctl")"
    fi
fi

# --- 3. Обновление: неустановленный файл — это отказ, а не успех --------------
#
# au_apply_patch логировал неудачу cp/mv и шёл дальше, после чего безусловно
# продвигал installed-tag и возвращал 0. Откат и маркер «смешанное дерево»
# висят на единственной ветке `if ! au_apply_patch`, то есть не срабатывали
# никогда. Роутер оставался на смеси версий и больше не пытался обновиться:
# следующий прогон видел совпадение тегов.
_fn=$(awk '/^au_apply_patch\(\)/,/^}$/' "$ROOT/lib/auto_update.sh")
if printf '%s' "$_fn" | grep -q '_au_install_failed'; then
    ok "au_apply_patch считает неустановленные файлы"
else
    no "счётчик отказов установки" "_au_install_failed" "нет — частичная установка снова пройдёт как успех"
fi
if printf '%s' "$_fn" | grep -q 'au_write_installed_tag'; then
    # Проверка порядка: возврат по ошибке обязан быть ДО продвижения тега,
    # иначе роутер запомнит версию, которой у него нет.
    _l_fail=$(printf '%s' "$_fn" | grep -n '_au_install_failed" -gt 0' | head -1 | cut -d: -f1)
    _l_tag=$(printf '%s' "$_fn" | grep -n 'au_write_installed_tag' | head -1 | cut -d: -f1)
    if [ -n "$_l_fail" ] && [ -n "$_l_tag" ] && [ "$_l_fail" -lt "$_l_tag" ]; then
        ok "выход по ошибке стоит раньше продвижения installed-tag"
    else
        no "порядок выхода и тега" "проверка отказов раньше тега" \
           "отказ=$_l_fail тег=$_l_tag — тег продвинется на версию, которой нет"
    fi
fi

# --- 4. set_flag: запись в конфиг под замком ----------------------------------
#
# В конфиг пишут больше десятка тумблеров панели и меню; set_flag делает
# grep-затем-sed -i, то есть чтение-изменение-запись без всякой защиты. Два
# одновременных переключателя — и один откатывается сам собой.
_sf=$(awk '/^set_flag\(\)/,/^}$/' "$ROOT/lib/utils.sh")
if printf '%s' "$_sf" | grep -q 'mkdir "\$_lk"'; then
    ok "set_flag берёт замок перед чтением-изменением-записью"
else
    no "замок в set_flag" "mkdir-замок" "нет — параллельные тумблеры затирают друг друга"
fi
# Замок обязан сниматься на ЛЮБОМ выходе, иначе первый же отказ подвесит
# конфиг на минуту (столько живёт «протухший» замок).
if printf '%s' "$_sf" | grep -q 'rmdir "\$_lk"'; then
    ok "замок снимается после записи"
else
    no "снятие замка" "rmdir" "нет — конфиг залипнет"
fi

# --- 5. WARP: снятие маркировки ищет ту же форму, что и установка -------------
#
# pbr_up ставит --set-xmark MARK/MARK, а pbr_down искал --set-mark MARK. Для
# iptables это разные правила, -C не находил ничего, и правило маркировки
# оставалось в mangle навсегда — каждое включение добавляло ещё одно.
_up=$(awk '/^warp_pbr_up\(\)/,/^}$/'   "$ROOT/files/z2k-warp.sh")
_dn=$(awk '/^warp_pbr_down\(\)/,/^}$/' "$ROOT/files/z2k-warp.sh")
if printf '%s' "$_up" | grep -q -- '--set-xmark'; then
    if printf '%s' "$_dn" | grep -q -- '--set-xmark'; then
        ok "warp_pbr_down снимает ту же форму маркировки, что ставит pbr_up"
    else
        no "форма маркировки при снятии" "--set-xmark, как у pbr_up" \
           "только --set-mark — правило не удаляется никогда"
    fi
else
    no "pbr_up ставит --set-xmark" "--set-xmark" "форма изменилась, проверку надо пересмотреть"
fi

# --- 6. Восстановление конфигурации проверяет боевую распаковку ---------------
#
# Проверялась только пробная распаковка во временный каталог, а настоящая, та
# что поверх /, шла без проверки — и следом безусловно печаталось
# «Конфигурация восстановлена».
_rc=$(awk '/tar -xzf "\$latest_backup" -C \/ /,/print_success/' "$ROOT/lib/config.sh")
if printf '%s' "$_rc" | grep -q 'if ! tar -xzf'; then
    ok "боевая распаковка при восстановлении проверяется"
else
    no "проверка боевой распаковки" "if ! tar ... -C /" \
       "нет — обрыв на середине сообщает об успехе"
fi

# --- 7. Валидатор знает настоящие действия движка -----------------------------
_acts=$(grep -A5 '^KNOWN_LUA_DESYNC_ACTIONS=' "$ROOT/files/z2k-config-validator.sh")
_missing=""
for a in rst rstack synack; do
    printf '%s' "$_acts" | grep -qw "$a" || _missing="$_missing $a"
done
[ -z "$_missing" ] && ok "валидатор знает rst/rstack/synack — рабочая страта не объявляется ошибкой" \
                   || no "известные действия" "rst rstack synack" "нет:$_missing"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
