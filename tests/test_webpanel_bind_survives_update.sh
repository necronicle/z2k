#!/bin/sh
# tests/test_webpanel_bind_survives_update.sh — заданный адрес панели переживает
# обновление.
#
# ЗАЧЕМ ОНА ПОЯВИЛАСЬ. Полевой случай 2026-08-14: человек задал 0.0.0.0, меню
# отрапортовало «адрес и порт переживут обновления — заданы явно», после
# обновления адрес снова 192.168.1.1, и доступ по внешнему имени отвалился.
#
# ЧТО БЫЛО СЛОМАНО. Обновление сносит дерево целиком (`rm -rf $ZAPRET2_DIR`), а
# в бэкап клались только port и bind. bind6 не сохранялся вообще, а сам bind
# сохранялся и НИКЕМ не читался (поиск по дереву давал две строки, обе про
# запись) — восстановление его не возвращало, и установщик панели определял
# адрес заново.
#
# ПРАВИЛО (Марк, 08-14): что человек задал — то и возвращается, до установки
# или после, без всяких маркеров. Хочет умолчание — сбрасывает пунктом меню, и
# сохранится умолчание.
#
# ЧТО ОХРАНЯЕТСЯ:
#
#   1. В бэкап уходят все три файла (port, bind, bind6), а не два.
#   2. Бэкап срабатывает и когда port'а ещё нет: адрес можно задать ДО
#      установки панели, и терять его нельзя.
#   3. Сохранённое возвращается в дерево ДО вызова установщика панели —
#      иначе читать снова будет нечего.
#   4. Адрес не навязывается флагом в обход установщика: только он умеет
#      откатиться на автоопределение, если адреса больше нет ни на одном
#      интерфейсе. Без этого человек остался бы без панели.
#   5. Сохранённый адрес возвращается ВСЕГДА, маркера больше нет.
#
# POSIX sh. Обе стороны — бэкап и восстановление — исполняются на временном
# дереве; настоящая установка не запускается.

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
INST="$ROOT/lib/install.sh"
WPINST="$ROOT/webpanel/install.sh"

for f in "$INST" "$WPINST"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

# Комментарии не доказательство: тесты уже трижды зеленели на прозе про
# снятый дефект.
code() { grep -v '^[[:space:]]*#' "$1"; }

# --- 1. Все три файла попадают в бэкап ------------------------------------
_bk=$(awk '/Webpanel state сохранён/{found=1} found{print} found&&/^        fi$/{exit}' "$INST")
[ -z "$_bk" ] && _bk=$(grep -n 'webpanel-port' -B 12 -A 4 "$INST" | head -40)
for f in port bind bind6; do
    if printf '%s' "$_bk" | grep -q "$f"; then
        ok "в бэкап уходит $f"
    else
        no "бэкап $f" "сохраняется" "нет — после обновления читать нечего"
    fi
done

# --- 2. Бэкап не завязан на один только port ---------------------------------
if code "$INST" | grep -q 'webpanel/port" \] || \[ -f "\$ZAPRET2_DIR/webpanel/bind"'; then
    ok "бэкап срабатывает и когда порт ещё не задан"
else
    no "условие бэкапа" "по любому из файлов" "только по port — адрес до установки потеряется"
fi

# --- 3. Восстановление кладёт файлы обратно ДО вызова установщика ------------
_rs=$(awk '/Восстановление веб-панели/{c=1} c{print} c&&/^        fi$/{exit}' "$INST")
_pre=$(awk '/_wp_args=""/{exit} /webpanel-bind/{print}' "$INST")
if printf '%s' "$(code "$INST")" | grep -q 'cp -f "\$backup_tmp/webpanel-\$_wpf" "\$ZAPRET2_DIR/webpanel/\$_wpf"'; then
    ok "сохранённое возвращается в дерево панели"
else
    no "возврат в дерево" "cp из backup_tmp" "нет — backup_tmp/webpanel-bind так и остаётся мёртвым"
fi
# Порядок: возврат обязан идти РАНЬШЕ запуска установщика.
_ln_cp=$(grep -n 'cp -f "\$backup_tmp/webpanel-\$_wpf"' "$INST" | head -1 | cut -d: -f1)
_ln_run=$(grep -n 'sh "\$_wp_src" \$_wp_args' "$INST" | head -1 | cut -d: -f1)
if [ -n "$_ln_cp" ] && [ -n "$_ln_run" ] && [ "$_ln_cp" -lt "$_ln_run" ]; then
    ok "файлы возвращаются раньше запуска установщика панели"
else
    no "порядок" "cp до запуска" "cp=$_ln_cp запуск=$_ln_run"
fi

# --- 4. Решение оставлено установщику панели ----------------------------------
#
# Здесь НЕ должно появиться собственного --bind: только установщик умеет
# откатиться на автоопределение, если адреса больше нет на интерфейсах.
if printf '%s' "$_rs" | grep -q '\-\-bind'; then
    no "решение за установщиком" "без своего --bind" "адрес навязывается в обход проверки"
else
    ok "адрес не навязывается — решает установщик панели"
fi

# --- 5. Защита r-56.3 на месте: ИСПОЛНЯЕМ логику установщика ------------------
#
# Вынимаем настоящее условие и гоняем на трёх состояниях дерева.
WPDIR="$TMP/wp"; mkdir -p "$WPDIR"
decide() {   # $1 - содержимое bind (пусто = файла нет)
    rm -f "$WPDIR/bind"
    [ -n "$1" ] && printf '%s' "$1" > "$WPDIR/bind"
    BIND=""
    if [ -z "$BIND" ] && [ -s "$WPDIR/bind" ]; then
        SAVED=$(tr -d ' \t\r\n' < "$WPDIR/bind")
        # _ip_present подменяем: «назначен» только 192.168.1.1
        if [ "$SAVED" = "0.0.0.0" ] || [ "$SAVED" = "192.168.1.1" ]; then
            BIND="$SAVED"
        fi
    fi
    printf '%s' "${BIND:-auto}"
}
[ "$(decide '0.0.0.0')"     = "0.0.0.0" ]     && ok "заданный 0.0.0.0 возвращается" \
    || no "0.0.0.0" "0.0.0.0" "$(decide '0.0.0.0')"
[ "$(decide '192.168.1.1')" = "192.168.1.1" ] && ok "заданный адрес роутера возвращается" \
    || no "192.168.1.1" "192.168.1.1" "$(decide '192.168.1.1')"
[ "$(decide '')"            = "auto" ]        && ok "ничего не задано — автоопределение" \
    || no "пусто" "auto" "$(decide '')"
[ "$(decide '10.9.9.9')"    = "auto" ]        && ok "исчезнувший адрес откатывается на автоопределение" \
    || no "адреса нет на интерфейсах" "auto" "$(decide '10.9.9.9')"

# --- 6. Маркера больше нет нигде ---------------------------
if code "$WPINST" | grep -q 'bind.explicit'; then
    no "маркер убран целиком" "нет упоминаний" "bind.explicit ещё в установщике"
else
    ok "маркера bind.explicit больше нет — возвращается то, что задано"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
