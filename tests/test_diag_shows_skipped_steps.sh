#!/bin/sh
# tests/test_diag_shows_skipped_steps.sh — шаг обновления, не сделавший работу,
# обязан попадать в сводку «что не так».
#
# ЧТО СЛУЧИЛОСЬ. Строка «cleanup-ip-hosts: функция недоступна, пропускаю» писалась
# в журнал обновления с апреля и всплыла случайно: человек прислал диагностику по
# другому поводу, и я заметил её глазами. Журнал в диагностике печатается, но
# целиком его никто не читает — читают верхний блок. Пока пропуск не виден там,
# он живёт месяцами.
#
# Тест исполняемый: подсовывает настоящий журнал и проверяет, что строка доехала
# до сводки, а не осталась в подоболочке конвейера.
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '[FAIL] %s\n' "$1"; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT

# Вырезаем блок из print_health и гоняем его на поддельном журнале: подключать
# z2k-diag.sh целиком нельзя — он лезет в iptables, ipset и процессы.
mkdir -p "$SB/log"
LOG="$SB/log/z2k-auto-update.log"
cat > "$LOG" <<'LOGEOF'
[2026-08-30 02:00:00] обновление p-80.4 -> r-81.1; после доставки: перезапускаю сервис
[2026-08-30 02:00:10] cleanup-ip-hosts: функция недоступна, пропускаю
[2026-08-30 02:00:11] обновление завершено: r-81.1
[2026-08-31 14:35:02] обновление r-81.2 -> r-81.6; после доставки: перезапускаю сервис
[2026-08-31 14:35:06] шаг: перезапускаю сервис
[2026-08-31 14:35:13] обновление завершено: r-81.6
[2026-08-31 14:35:13] cleanup-ip-hosts: функция недоступна, пропускаю
LOGEOF

# Тот же код, что в print_health, с той же логикой накопления.
issues=""
_add() { issues="${issues}  [!] $1
"; }
_aul="$LOG"
_from=$(awk '/обновление .* -> |no update needed/ {n=NR} END {print n+0}' "$_aul" 2>/dev/null)
_skips=$(tail -n "+$_from" "$_aul" 2>/dev/null \
    | grep -E "пропускаю|недоступн|не удалось|отложен" \
    | sed 's/^\[[^]]*\][[:space:]]*//' | sort -u)
if [ -n "$_skips" ]; then
    set -f
    IFS='
'
    for _s in $_skips; do [ -n "$_s" ] && _add "обновление: $_s"; done
    unset IFS
    set +f
fi

case "$issues" in
    *"cleanup-ip-hosts"*) ok "пропущенный шаг доехал до сводки" ;;
    *) bad "пропущенный шаг в сводку не попал (issues=[$issues])" ;;
esac

# Строка ПРОШЛОГО обновления не должна тянуться в сводку вечно.
case "$issues" in
    *"r-81.1"*) bad "в сводку попали строки старого обновления" ;;
    *) ok "берётся только последний прогон" ;;
esac

# И главное — сам скрипт обязан этот блок содержать и накапливать через _add,
# а не печатать из конвейера: в подоболочке изменение $issues пропадает.
D="$ROOT/files/z2k-diag.sh"
if grep -q 'z2k-auto-update.log' "$D" && grep -q '_add "обновление: \$_s"' "$D"; then
    ok "z2k-diag.sh накапливает пропуски через _add"
else
    bad "z2k-diag.sh не собирает пропуски шагов в сводку"
fi
if awk '/_skips=\$\(/,/^    fi$/' "$D" | grep -q 'while .*read'; then
    bad "сбор идёт конвейером — изменение issues потеряется в подоболочке"
else
    ok "сбор идёт без конвейера"
fi

printf '\nPASSED: %s\nFAILED: %s\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
