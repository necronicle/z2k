#!/bin/sh
# tests/test_binaries_in_manifest.sh — каждый бинарник, который установщик
# качает напрямую, обязан быть в манифесте.
#
# Повод: 31.08.2026. Сборки z2k-detect не значились в манифесте, поэтому шаг
# обновления refresh-binaries их не видел и не обновлял НИ РАЗУ. Люди сидели с
# бинарником от установки, новая команда tcp16 у них отсутствовала, и весь
# механизм обхода по объёму молчал: «unknown command: tcp16». Ни один тест
# этого не видел — проверялись строки в скриптах, а не состав манифеста.
#
# Здесь манифест берётся как есть и сверяется с тем, что качает установщик.
# POSIX sh (busybox ash).

DIR="$(cd "$(dirname "$0")/.." && pwd)"
MANIFEST="$DIR/UPDATES.json"
INSTALL="$DIR/lib/install.sh"
PASS=0; FAIL=0
ok()  { PASS=$((PASS + 1)); printf '[PASS] %s\n' "$1"; }
bad() { FAIL=$((FAIL + 1)); printf '[FAIL] %s\n' "$1"; }

[ -f "$MANIFEST" ] || { echo "нет $MANIFEST"; exit 1; }

# Что установщик тянет напрямую: пути вида <модуль>/builds/<имя>-linux-<арка>.
WANT=$(grep -ohE '\$\{GITHUB_RAW\}/[a-z0-9_-]+/builds/' "$INSTALL" "$DIR"/files/*.sh 2>/dev/null \
       | sed 's|\${GITHUB_RAW}/||; s|/builds/||' | sort -u)
[ -n "$WANT" ] || { bad "не нашёл ни одного модуля со сборками в установщике"; echo; echo "PASSED: $PASS"; echo "FAILED: $FAIL"; exit 1; }

# Ищем ИМЕННО в карте сумм, а не по всему файлу: пути к сборкам встречаются и
# в старых записях истории, и такая проверка давала ложный пропуск — ровно на
# ней я и попался, когда писал этот тест.
# Манифест между релизами НЕ трогаем: карту сумм пересобирает только скрипт
# выпуска. Поэтому здесь проверяется ПРАВИЛО в генераторе, а совпадение самого
# манифеста с этим правилом гейтит выпуск (scripts/release.sh) — там оно
# осмысленно, потому что карта пересобрана только что.

# Правило в генераторе: без него следующий релиз выкинет сборки из карты.
GEN="$DIR/scripts/gen_file_hashes.sh"
missing2=""
for m in $WANT; do
    grep -q "$m/builds/\*" "$GEN" || missing2="$missing2 $m"
done
if [ -z "$missing2" ]; then
    ok "генератор манифеста знает про все модули со сборками"
else
    bad "генератор не знает про:$missing2 — они выпадут из следующего манифеста"
fi

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ] && exit 0 || exit 1
