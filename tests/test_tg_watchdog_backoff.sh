#!/bin/sh
# tests/test_tg_watchdog_backoff.sh — сторож телеграм-туннеля не должен
# перезапускать его вечно раз в три минуты и не должен стирать причину из лога.
#
# ЧТО СЛУЧИЛОСЬ (диаг 2026-08-27). У человека умер резолвер роутера, туннель не
# смог зарегистрироваться, и дальше сторож встал в карусель: проба идёт через
# :1443, который лежит, значит валится всегда; три провала подряд → рестарт;
# рестарт обнулял счётчик — и так каждые три минуты, бесконечно. Рестарт при
# мёртвом резолвере не чинит НИЧЕГО, а стоит снятия и наложения правил, kill -9
# и окна в несколько секунд, когда телеграм идёт мимо туннеля.
#
# Второе: рестарт затирал лог до одной строки. Единственная строка с причиной
# печатается раз в ~40 с, поэтому в отчёте оставались одни дропы без причины.
#
# Третье: `pidof tg-mtproxy-client` отвечал «да», даже если жив только
# cdnbase-туннель на :1444 — бинарник у них общий.
# POSIX sh.
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
HERE=$(cd "$(dirname "$0")/.." && pwd)
WD="$HERE/files/z2k-tg-watchdog.sh"
TMP=$(mktemp -d) || exit 1
trap 'rm -rf "$TMP"' EXIT INT TERM

# --- 1. пауза между рестартами растёт ----------------------------------------
# Берём НАСТОЯЩИЕ функции из скрипта, а не их пересказ.
eval "$(sed -n '/^now_epoch() {/,/^}/p' "$WD")"
eval "$(sed -n '/^restart_allowed() {/,/^}/p' "$WD")"

_check() {   # подряд-рестартов, прошло-секунд, ожидание(да/нет)
    RESTARTS="$1"; RLAST=$(( $(now_epoch) - $2 ))
    if restart_allowed; then _got=да; else _got=нет; fi
    if [ "$_got" = "$3" ]; then
        ok "рестартов=$1, прошло ${2}с → разрешить=$3"
    else
        no "рестартов=$1, прошло ${2}с" "$3" "$_got"
    fi
}
_check 0 0    да      # первый раз — сразу
_check 1 30   нет     # после первого ждём минуту
_check 1 61   да
_check 2 61   нет     # потом две
_check 2 121  да
_check 3 200  нет     # потом четыре
_check 3 241  да
_check 6 1000 нет     # потолок 30 минут
_check 6 1801 да
_check 99 1801 да     # потолок не уезжает вверх бесконечно

# --- 2. лог не затирается, причина переживает рестарт -------------------------
LOG="$TMP/tg.log"
{
  echo "2026/08/27 05:31:48 [tunnel] регистрация не удалась: lookup ... i/o timeout"
  i=0; while [ $i -lt 50 ]; do echo "[tunnel] no WS connection, dropping stream $i"; i=$((i+1)); done
} > "$LOG"
# mark_log из скрипта (ему нужен только $LOG)
eval "$(sed -n '/^mark_log() {/,/^}/p' "$WD")"
mark_log "тест"
if grep -q "регистрация не удалась" "$LOG"; then
    ok "причина переживает рестарт сторожа"
else
    no "причина переживает рестарт сторожа" "строка на месте" "затёрта"
fi
if grep -q "watchdog restart: тест" "$LOG"; then
    ok "маркер рестарта записан"
else
    no "маркер рестарта записан" "маркер" "нет"
fi

# --- 3. якорь: старый шторм не вызывает второй рестарт ------------------------
# Ровно то выражение, что стоит в скрипте.
_count() { tail -40 "$1" | awk '/watchdog restart:/ {n=0; next} /CONNECT_FAIL/ {n++} END {print n+0}'; }
{ i=0; while [ $i -lt 20 ]; do echo "CONNECT_FAIL старый"; i=$((i+1)); done
  echo "$(date) watchdog restart: тест"
  echo "[tunnel] спокойно"; } > "$TMP/anchor.log"
got=$(_count "$TMP/anchor.log")
if [ "$got" = "0" ]; then ok "шторм ДО маркера не считается"
else no "шторм ДО маркера не считается" "0" "$got"; fi
{ echo "$(date) watchdog restart: тест"
  i=0; while [ $i -lt 12 ]; do echo "CONNECT_FAIL свежий"; i=$((i+1)); done; } > "$TMP/anchor2.log"
got=$(_count "$TMP/anchor2.log")
if [ "$got" = "12" ]; then ok "шторм ПОСЛЕ маркера считается"
else no "шторм ПОСЛЕ маркера считается" "12" "$got"; fi

# --- 4. проверки живости смотрят на СВОЙ экземпляр ----------------------------
if grep -q 'pidof tg-mtproxy-client >/dev/null 2>&1' "$WD"; then
    no "проверки живости фильтруют экземпляр :1443" "нет голого pidof" "остался голый pidof"
else
    ok "проверки живости фильтруют экземпляр :1443"
fi
grep -q 'tg_1443_running' "$WD" && ok "фильтр вынесен в общую функцию" \
    || no "фильтр вынесен в общую функцию" "tg_1443_running" "нет"

# --- 5. удачная проба обнуляет счётчик рестартов ------------------------------
grep -q 'rm -f "$RSTATE"' "$WD" && ok "удачная проба обнуляет счётчик рестартов" \
    || no "удачная проба обнуляет счётчик рестартов" "сброс есть" "нет"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
