#!/bin/sh
# z2k-tcp16-probe.sh — выяснить, есть ли на ЭТОЙ линии блокировка по объёму
# соединения («16-20 КБ»), и записать ответ флагом.
#
# Зачем флаг. Механизм подстановки белого имени осмыслен только там, где этот
# блок есть. У кого его нет, любая наша попытка «определить блок по поведению
# потока» — чистый источник ложных срабатываний: горизонт видимости движка
# меряется в пакетах, и здоровая крупная загрузка выглядит как обрыв. Поэтому
# сперва мерим линию на КУРИРУЕМЫХ мишенях, и только потом включаем механизм.
#
# Проба: десять HEAD-запросов по одному keep-alive соединению, со второго — с
# мусорным заголовком на 4000 байт; обрыв после 12 КБ накопленного объёма и
# есть вердикт.
#
# Здесь же подбирается ИМЯ НА КАЖДУЮ СЕТЬ. Одного имени на всех не бывает:
# замер 30.08.2026 на линии владельца — hcaptcha.com бьёт двадцать AS, но НЕ
# Hetzner; Hetzner, DigitalOcean и OVH берёт 300.ya.ru; Melbicom —
# ad.adriver.ru; семь AS не берёт ничто из списка.
#
# Подбор идёт ПРЯМОЙ пробой к мишени, а не через наш обход: перебор не трогает
# трафик человека и не подставляет ему случайные имена, пока ищет.
#
# Ответ живёт в state/tcp16.flag (1 — блок есть), список сетей с блоком — в
# state/tcp16_asn.txt, карта «сеть → имя» — в state/tcp16_sni.txt. Отсутствие
# флага означает «не мерили», и механизм в этом случае выключен.
PATH=/opt/bin:/opt/sbin:/usr/bin:/bin:/usr/sbin:/sbin
export PATH

ZAPRET2_DIR="${ZAPRET2_DIR:-/opt/zapret2}"
# ГДЕ ИСКАТЬ БИНАРНИК. Штатное место установки — /opt/sbin/z2k-detect: туда
# его кладёт установщик, оттуда его обновляет шаг refresh-binaries. Прежде
# здесь стоял только путь внутри каталога обхода, и у КАЖДОГО пользователя
# проба падала первой строкой «нет /opt/zapret2/z2k-detect» — механизм не
# работал вообще (жалоба с диагностикой 31.08.2026). У меня на стенде она
# проходила лишь потому, что копия бинарника лежала там руками.
#
# Каталог обхода оставлен вторым: там бинарник может оказаться на стендах и у
# тех, кто ставил его вручную.
DETECT_DIRS="${DETECT_DIRS:-/opt/sbin $ZAPRET2_DIR}"
if [ -z "${DETECT:-}" ]; then
    for _d in $DETECT_DIRS; do
        if [ -x "$_d/z2k-detect" ]; then DETECT="$_d/z2k-detect"; break; fi
    done
    DETECT="${DETECT:-${DETECT_DIRS%% *}/z2k-detect}"
fi
TARGETS="${TARGETS:-$ZAPRET2_DIR/lists/tcp16_targets.txt}"
FLAG="$ZAPRET2_DIR/state/tcp16.flag"
# Список AS, где блок найден: по нему рантайм решает, кому ставить имя, а кому
# не надо. Без него имя уходит всему пулу подряд.
ASNOUT="$ZAPRET2_DIR/state/tcp16_asn.txt"
SNIOUT="$ZAPRET2_DIR/state/tcp16_sni.txt"
CAND="${CAND:-$ZAPRET2_DIR/lists/sni_wl_candidates.txt}"
LOG="${LOG:-/tmp/z2k-tcp16-probe.log}"

# ПАРАМЕТРЫ ПРОГОНА — ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ.
#
# Этот скрипт — единственный штатный вход: и планировщик ночью, и первый старт
# после установки зовут именно его, без аргументов. Ручной запуск z2k-detect с
# другими флагами ничего не доказывает — он проверяет не тот прогон, который
# получают люди.
#
# Числа — из замеров на боевом роутере 31.08.2026:
#   PARALLEL 50 — общий потолок одновременных проб. При 4 проба линии по 110
#                 мишеням шла 2 м 44 с, при 50 — 15 секунд.
#   BATCH 5     — столько имён проверяется разом внутри одной сети. По одному
#                 сеть, где не подходит ничто, стоит 188 проб подряд.
# Остальное (10 запросов по 4000 байт, порог 12 КБ, таймауты, ожидание RTT×3)
# зашито в internal/tcp16 рядом с обоснованием и замером.
PARALLEL="${PARALLEL:-50}"
BATCH="${BATCH:-5}"

# Предпосылки. Обновление кладёт файлы по одному, и планировщик способен
# подняться раньше, чем приедут списки: тогда проба обязана честно сказать
# «данных нет» и НЕ трогать флаг — иначе запишет «блока нет» на пустом месте и
# выключит механизм до следующей ночи. Диагностика пользователя 31.08.2026
# показывала ровно это: «0 из 0 кандидатов», «карта сетей: 0 записей».
# БИНАРНИКА НЕТ ВОВСЕ ИЛИ ОН СТАРЫЙ — ДОСТАТЬ САМИМ, А НЕ ЖДАТЬ РЕЛИЗА.
#
# Раньше эти два случая обрабатывались по-разному, и это стоило людям
# работающего механизма. Самолечение стояло НИЖЕ проверки `-x`, то есть
# срабатывало только когда бинарник есть, но не умеет tcp16. У кого его не было
# совсем — а таких оказалось большинство: сборки z2k-detect годами не попадали в
# карту сумм, и установка их не клала — проба выходила первой же строкой и до
# самолечения не доходила никогда. В диагностике это выглядело как «нет
# /opt/zapret2/z2k-detect» и мгновенный выход (жалобы 31.08.2026).
#
# Случай ровно один: нужного бинарника нет. Достаём его тем же штатным шагом.
if ! [ -x "$DETECT" ] || ! "$DETECT" tcp16 -h >/dev/null 2>&1; then
    if [ -x "$DETECT" ]; then
        echo "бинарник не умеет tcp16 — обновляю его"
    else
        echo "бинарника пробы нет ($DETECT) — достаю его"
    fi
    if [ -r "$ZAPRET2_DIR/lib/auto_update.sh" ]; then
        # shellcheck source=/dev/null
        . "$ZAPRET2_DIR/lib/utils.sh" >/dev/null 2>&1
        # shellcheck source=/dev/null
        . "$ZAPRET2_DIR/lib/auto_update.sh" >/dev/null 2>&1
        # Тянем бинарник САМИ, а не шагом refresh-binaries.
        #
        # Тот шаг ОБНОВЛЯЕТ, но принципиально не СТАВИТ отсутствующее, и это
        # правильно: иначе он тащил бы семимегабайтный движок WARP на роутеры,
        # где WARP никто не включал. Значит для нашего случая — «бинарника нет
        # вовсе» — он не годится по замыслу, и звать его было бесполезно
        # (проверено на роутере: шаг отработал молча и ничего не положил).
        if command -v au_fetch_manifest >/dev/null 2>&1 \
           && command -v au_download_repo_file >/dev/null 2>&1 \
           && command -v au_bin_goarch >/dev/null 2>&1; then
            au_fetch_manifest >/dev/null 2>&1 || true
            _pd_arch=$(au_bin_goarch 2>/dev/null)
            _pd_man="${Z2K_AU_TMP_DIR:-/tmp/z2k_au}/UPDATES.json"
            if [ -n "$_pd_arch" ] && [ -s "$_pd_man" ]; then
                _pd_src="z2k-detect/builds/z2k-detect-linux-$_pd_arch"
                _pd_sha=$(au_manifest_file_sha "$_pd_man" "$_pd_src" 2>/dev/null)
                _pd_tmp="/tmp/z2k-detect.$$"
                # Ставим в ПЕРВЫЙ каталог списка поиска, а не в зашитый путь:
                # иначе добыча и поиск могут разойтись, и проверить это нечем.
                _pd_dir=${DETECT_DIRS%% *}
                if au_download_repo_file "$_pd_src" "$_pd_tmp" "$_pd_sha" 2>/dev/null; then
                    mkdir -p "$_pd_dir" 2>/dev/null
                    # Кладём во временный файл рядом и переименовываем: замена
                    # работающего бинарника на месте роняет его текущий запуск.
                    if mv -f "$_pd_tmp" "$_pd_dir/z2k-detect.new" 2>/dev/null \
                       && chmod 755 "$_pd_dir/z2k-detect.new" 2>/dev/null \
                       && mv -f "$_pd_dir/z2k-detect.new" "$_pd_dir/z2k-detect" 2>/dev/null; then
                        echo "бинарник получен: $_pd_src -> $_pd_dir/z2k-detect"
                    fi
                fi
                rm -f "$_pd_tmp" "$_pd_dir/z2k-detect.new" 2>/dev/null
            fi
        fi
    fi
    # Ищем заново: шаг обновления кладёт бинарник в штатное место, а до него
    # переменная могла указывать на другой каталог из списка поиска.
    DETECT=""
    for _d in $DETECT_DIRS; do
        if [ -x "$_d/z2k-detect" ]; then DETECT="$_d/z2k-detect"; break; fi
    done
    DETECT="${DETECT:-${DETECT_DIRS%% *}/z2k-detect}"
    if ! [ -x "$DETECT" ] || ! "$DETECT" tcp16 -h >/dev/null 2>&1; then
        echo "достать бинарник не удалось — проба отложена" >&2
        exit 2
    fi
    echo "бинарник готов: $DETECT"
fi

[ -s "$TARGETS" ] || { echo "нет списка мишеней: $TARGETS — отложено" >&2; exit 2; }
[ -s "$CAND" ] || { echo "нет списка имён: $CAND — отложено" >&2; exit 2; }
mkdir -p "$(dirname "$FLAG")" 2>/dev/null

# Без -confirmed: список AS нужен ПОЛНЫЙ, иначе имя не достанется тем, кого
# режут, но чья AS не помечена звёздочкой. Полный прогон стоит около минуты
# и делается раз в неделю.
# GODEBUG=asyncpreemptoff=1 — обязательно, а не на всякий случай.
#
# На MIPS вытеснение горутин по SIGURG роняет Go-бинарники: демон z2k-detect
# запускается с этим флагом с самого начала, а проба его не ставила — на
# роутерах mips она падала бы там, где демон живёт. Пользователь с mips как раз
# и прислал диагностику, где механизм молчит.
DETECT_ENV="GODEBUG=asyncpreemptoff=1"

env $DETECT_ENV "$DETECT" tcp16 -targets "$TARGETS" -parallel "$PARALLEL" -asn-out "$ASNOUT" > "$LOG" 2>&1
rc=$?

case "$rc" in
    1)  # блок есть
        printf '1\n' > "$FLAG"
        # Имя на каждую найденную сеть. Пишем во временный файл и подменяем
        # разом: половина карты хуже, чем прежняя целая.
        if [ -s "$CAND" ]; then
            if env $DETECT_ENV "$DETECT" tcp16 -targets "$TARGETS" -scan "$CAND" -per-asn \
                 -sni-out "$SNIOUT.new" -parallel "$PARALLEL" -batch "$BATCH" >> "$LOG" 2>&1; then
                mv -f "$SNIOUT.new" "$SNIOUT"
            else
                rm -f "$SNIOUT.new"
                echo "подбор имён не дал результата, карта оставлена прежней" >&2
            fi
        fi
        ;;
    0)  # блока нет
        printf '0\n' > "$FLAG" ;;
    *)  # мишени не ответили вовсе — не мерили; прежний ответ не трогаем,
        # чтобы обрыв связи не выключил людям рабочий обход.
        echo "проба не состоялась (код $rc), флаг оставлен как был" >&2
        exit 2 ;;
esac

# Метка времени рядом: по ней видно, когда мерили, и не пора ли перемерить.
date +%s > "$FLAG.ts" 2>/dev/null

# ПЕРЕСОБРАТЬ КОНФИГ, ЕСЛИ ОТВЕТ ИЗМЕНИЛ КАРТИНУ.
#
# Механизм попадает в конфиг только при флаге 1, а флаг появляется ЗДЕСЬ —
# то есть уже после того, как обновление пересобрало конфиг. Без этого шага
# человек получал новую версию с выключенным механизмом и ждал бы следующей
# пересборки неизвестно сколько: r-81.1 у тех, кому он установился, именно так
# и молчал.
#
# Сравниваем НАМЕРЕНИЕ с фактом: должен ли механизм быть в конфиге и есть ли он
# там сейчас. Совпало — не трогаем ничего, это ночной прогон, и лишний
# перезапуск сервиса людям не нужен.
CONFIG="${CONFIG:-$ZAPRET2_DIR/config}"
want=0
[ "$(cat "$FLAG" 2>/dev/null)" = "1" ] && want=1
have=0
grep -q -- "--lua-desync=z2k_sni_pick" "$CONFIG" 2>/dev/null && have=1

if [ "$want" != "$have" ]; then
    echo "механизм должен быть в конфиге: $want, сейчас: $have — пересобираю"
    if [ -r "$ZAPRET2_DIR/lib/config_official.sh" ]; then
        # Тот же путь, которым пересобирает обновление: utils.sh нужен
        # генератору для safe_config_read и печати.
        # shellcheck source=/dev/null
        . "$ZAPRET2_DIR/lib/utils.sh" >/dev/null 2>&1
        # shellcheck source=/dev/null
        . "$ZAPRET2_DIR/lib/config_official.sh" >/dev/null 2>&1
        if command -v create_official_config >/dev/null 2>&1; then
            create_official_config "$CONFIG" >/dev/null 2>&1
            # Проверяем ПЕРЕД перезапуском: пустить сервис в негодный конфиг
            # хуже, чем оставить как было.
            if [ -x "$ZAPRET2_DIR/z2k-config-validator.sh" ]; then
                sh "$ZAPRET2_DIR/z2k-config-validator.sh" >/dev/null 2>&1
                [ "$?" -ge 2 ] && { echo "конфиг не прошёл проверку — сервис не трогаю" >&2; exit 3; }
            fi
            [ -x /opt/etc/init.d/S99zapret2 ] && /opt/etc/init.d/S99zapret2 restart >/dev/null 2>&1
            echo "конфиг пересобран, сервис перезапущен"
        else
            echo "генератор конфига недоступен — пересборку пропустил" >&2
        fi
    fi
fi

tail -2 "$LOG"
exit 0
