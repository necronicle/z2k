#!/bin/sh
# z2k-tcp16-probe.sh — выяснить, есть ли на ЭТОЙ линии блокировка по объёму
# соединения («16-20 КБ»), и записать ответ флагом.
#
# Зачем флаг. Механизм подстановки белого имени осмыслен только там, где этот
# блок есть. У кого его нет, любая наша попытка «определить блок по поведению
# потока» — чистый источник ложных срабатываний: горизонт видимости движка
# меряется в пакетах, и здоровая крупная загрузка выглядит как обрыв. Поэтому
# сперва мерим линию на КУРИРУЕМЫХ мишенях, и только потом включаем механизм.
#
# Проба повторяет runnin4ik/dpi-detector: десять HEAD-запросов по одному
# keep-alive соединению, со второго — с мусорным заголовком на 4000 байт;
# обрыв после 12 КБ накопленного объёма и есть вердикт.
#
# Здесь же подбирается ИМЯ НА КАЖДУЮ СЕТЬ. Одного имени на всех не бывает:
# замер 30.08.2026 на линии владельца — hcaptcha.com бьёт двадцать AS, но НЕ
# Hetzner; Hetzner, DigitalOcean и OVH берёт 300.ya.ru; Melbicom —
# ad.adriver.ru; семь AS не берёт ничто из списка.
#
# Подбор идёт ПРЯМОЙ пробой к мишени, а не через наш обход. Так делает
# первоисточник, и так правильно: перебор не трогает трафик человека и не
# подставляет ему случайные имена, пока ищет.
#
# Ответ живёт в state/tcp16.flag (1 — блок есть), список сетей с блоком — в
# state/tcp16_asn.txt, карта «сеть → имя» — в state/tcp16_sni.txt. Отсутствие
# флага означает «не мерили», и механизм в этом случае выключен.
PATH=/opt/bin:/opt/sbin:/usr/bin:/bin:/usr/sbin:/sbin
export PATH

ZAPRET2_DIR="${ZAPRET2_DIR:-/opt/zapret2}"
DETECT="${DETECT:-$ZAPRET2_DIR/z2k-detect}"
TARGETS="${TARGETS:-$ZAPRET2_DIR/lists/tcp16_targets.txt}"
FLAG="$ZAPRET2_DIR/state/tcp16.flag"
# Список AS, где блок найден: по нему рантайм решает, кому ставить имя, а кому
# не надо. Без него имя уходит всему пулу подряд.
ASNOUT="$ZAPRET2_DIR/state/tcp16_asn.txt"
SNIOUT="$ZAPRET2_DIR/state/tcp16_sni.txt"
CAND="${CAND:-$ZAPRET2_DIR/lists/sni_wl_candidates.txt}"
LOG="${LOG:-/tmp/z2k-tcp16-probe.log}"

# Подтверждённых AS хватает за глаза: они и подобраны как самые надёжные
# индикаторы. Гонять все 110 мишеней на роутере незачем — это минуты работы
# и десятки соединений ради того же ответа.
LIMIT="${LIMIT:-12}"

[ -x "$DETECT" ] || { echo "нет $DETECT" >&2; exit 1; }
[ -s "$TARGETS" ] || { echo "нет $TARGETS" >&2; exit 1; }
mkdir -p "$(dirname "$FLAG")" 2>/dev/null

# Без -confirmed: список AS нужен ПОЛНЫЙ, иначе имя не достанется тем, кого
# режут, но чья AS не помечена звёздочкой. Полный прогон стоит около минуты
# и делается раз в неделю.
"$DETECT" tcp16 -targets "$TARGETS" -parallel 4 -asn-out "$ASNOUT" > "$LOG" 2>&1
rc=$?

case "$rc" in
    1)  # блок есть
        printf '1\n' > "$FLAG"
        # Имя на каждую найденную сеть. Пишем во временный файл и подменяем
        # разом: половина карты хуже, чем прежняя целая.
        if [ -s "$CAND" ]; then
            if "$DETECT" tcp16 -targets "$TARGETS" -scan "$CAND" -per-asn \
                 -sni-out "$SNIOUT.new" -parallel 6 >> "$LOG" 2>&1; then
                mv -f "$SNIOUT.new" "$SNIOUT"
            else
                rm -f "$SNIOUT.new"
                echo "подбор имён не дал результата, карта оставлена прежней" >&2
            fi
        fi
        ;;
    0)  # блока нет
        printf '0\n' > "$FLAG" ;;
    *)  # мишени не ответили вовсе — не мерили; прежний ответ не трогаем,
        # чтобы обрыв связи не выключил людям рабочий обход.
        echo "проба не состоялась (код $rc), флаг оставлен как был" >&2
        exit 2 ;;
esac

# Метка времени рядом: по ней видно, когда мерили, и не пора ли перемерить.
date +%s > "$FLAG.ts" 2>/dev/null
tail -2 "$LOG"
exit 0
