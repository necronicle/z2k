#!/bin/sh
# z2k-sni-select.sh — выбрать имя из белого списка провайдера, с которым
# перестаёт работать блокировка по объёму соединения.
#
# ПОЧЕМУ ПРОБОЙ ЧЕРЕЗ САМ ОБХОД, А НЕ КЛИЕНТОМ.
#
# Напрашивается простое: подключиться к мишени, поставив имя настоящим SNI, и
# посмотреть, доедет ли объём. Так делает первоисточник, и на линии владельца
# 30.08.2026 это НЕ работает: ни одно из 188 имён пробу не прошло, хотя в нашем
# механизме те же имена сайт чинят. Разница в том, куда попадает имя. У нас оно
# уходит в ФЕЙКОВОМ хелло, который коробка видит первым, а настоящее соединение
# несёт настоящее имя. Проверять надо ровно то, что применяется.
#
# Поэтому проба идёт через сам обход: имя кладётся в файл закрепления, и
# делается обычный запрос к мишени. Ответ полного объёма = имя подошло.
#
# Трафика человека это не касается: мишени свои, а перебор кончается на первом
# подошедшем имени.
PATH=/opt/bin:/opt/sbin:/usr/bin:/bin:/usr/sbin:/sbin
export PATH

ZAPRET2_DIR="${ZAPRET2_DIR:-/opt/zapret2}"
PIN="$ZAPRET2_DIR/lists/sni_wl_pin.txt"
# Замок: пока он есть, поштучный перебор в движке не работает. Без него подбор
# сам себе создаёт мусор — на первом шаге закрепление снято, и старый путь
# успевает повесить кандидата на посторонний хост.
PINLOCK="$PIN.lock"
CAND="${CAND:-$ZAPRET2_DIR/lists/sni_wl_candidates.txt}"
FLAG="$ZAPRET2_DIR/state/tcp16.flag"

# Мишени проверки: крупные страницы у хостингов, где блок и наблюдается.
# Первая же, которая без имени не доезжает, становится мерилом.
TARGETS="${TARGETS:-https://www.hetzner.com/de/cloud/ https://www.vultr.com/ https://www.ovhcloud.com/en/}"

# Полный ответ — больше этого; оборванный — меньше. Между 40 КБ и 100 КБ
# намеренно зазор: у блока разброс 12-34 КБ, и попадать в него нельзя.
FULL_MIN="${FULL_MIN:-100000}"
CUT_MAX="${CUT_MAX:-40000}"
# Подошедшее имя отвечает за полсекунды; всё, что дольше пяти, — это уже
# неподошедшее, и ждать его полный таймаут значит платить по десять секунд за
# каждого кандидата. Замер 30.08.2026: с двенадцатью подбор занял 66 секунд,
# из них 52 — ожидание заведомых отказов.
CURL_TIMEOUT="${CURL_TIMEOUT:-5}"

say() { printf '%s\n' "$*"; }
cleanup() { rm -f "$PINLOCK" 2>/dev/null; }
trap cleanup EXIT INT TERM
: > "$PINLOCK" 2>/dev/null
size_of() {
    # Без `|| echo 0`: при обрыве curl и печатает размер, и возвращает код —
    # обе ветки давали склейку вроде «00» в отчёте.
    _n=$(curl -4 -s -o /dev/null -w '%{size_download}' --max-time "$CURL_TIMEOUT" "$1" 2>/dev/null)
    case "$_n" in ''|*[!0-9]*) _n=0 ;; esac
    printf '%s' "$_n"
}

[ -s "$CAND" ] || { say "нет списка кандидатов $CAND"; exit 1; }
if [ -r "$FLAG" ] && [ "$(cat "$FLAG" 2>/dev/null)" = "0" ]; then
    say "проба линии показала, что блока по объёму нет — подбирать нечего"
    exit 0
fi

# 0. Если имя уже стоит — сперва проверить его, а не перебирать заново.
#
# Ночной прогон иначе платил бы полминуты каждый раз и, что хуже, мог потерять
# рабочее имя из-за одного случайного сетевого сбоя посреди перебора. Проверка
# стоит один запрос: доехало — уходим, ничего не трогая.
PREV=""
if [ -s "$PIN" ]; then
    PREV=$(head -n1 "$PIN" 2>/dev/null)
    for t in $TARGETS; do
        n=$(size_of "$t")
        if [ "${n:-0}" -ge "$FULL_MIN" ] 2>/dev/null; then
            say "закреплённое имя $PREV работает ($n Б по $t) — перебор не нужен"
            exit 0
        fi
        # Мишень может не доезжать и по своей причине; пробуем следующую,
        # и только если ни одна не доехала, считаем имя протухшим.
    done
    say "закреплённое имя $PREV больше не пробивает — ищем заново"
fi

# 1. Найти мишень, которая СЕЙЧАС не доезжает: без неё мерить нечем.
rm -f "$PIN" 2>/dev/null
TARGET=""
for t in $TARGETS; do
    n=$(size_of "$t")
    say "мишень $t без имени: $n Б"
    if [ "${n:-0}" -le "$CUT_MAX" ] 2>/dev/null; then TARGET="$t"; break; fi
done
[ -n "$TARGET" ] || { say "все мишени доезжают целиком — на этой линии подбирать нечего"; exit 0; }
say "мерим по $TARGET"

# 2. Перебор. Останавливаемся на первом имени, дающем полный ответ дважды
#    подряд: одиночное совпадение может оказаться случайной удачей сети.
i=0
while IFS= read -r line; do
    name=$(printf '%s' "$line" | sed 's/#.*//; s/^[[:space:]]*//; s/[[:space:]]*$//')
    [ -z "$name" ] && continue
    case "$name" in *[!A-Za-z0-9.-]*) continue ;; esac
    i=$((i + 1))
    printf '%s\n' "$name" > "$PIN"
    # Движок перечитывает закрепление раз в секунду — дать ему эту секунду,
    # иначе кандидат проверится с предыдущим именем.
    sleep 1
    a=$(size_of "$TARGET")
    if [ "${a:-0}" -ge "$FULL_MIN" ] 2>/dev/null; then
        b=$(size_of "$TARGET")
        if [ "${b:-0}" -ge "$FULL_MIN" ] 2>/dev/null; then
            say "ПОДОШЛО: $name (кандидат $i, $a и $b Б)"
            printf '%s\n' "$name" > "$PIN"
            # Имена, подобранные раньше поштучно, теперь ни на что не влияют:
            # закрепление старше их. Чистим шестую колонку, чтобы в панели не
            # висело то, чего движок уже не применяет.
            ST="$ZAPRET2_DIR/extra_strats/cache/autocircular/state.tsv"
            if [ -w "$ST" ]; then
                awk -F"\t" -v OFS="\t" '"'"'{ if ($0 ~ /^#/) print; else if (NF>=6) { NF=5; print } else print }'"'"' \
                    "$ST" > "$ST.pin-new" 2>/dev/null && mv -f "$ST.pin-new" "$ST" 2>/dev/null
            fi
            exit 0
        fi
    fi
done < "$CAND"

# Ничего не нашли. Прежнее имя возвращаем на место: оно, возможно, ещё
# работает по другим сайтам, а пустое закрепление гарантированно не работает
# ни по каким. Пусть лучше протухшее, чем никакого — до следующей ночи.
if [ -n "$PREV" ]; then
    printf '%s\n' "$PREV" > "$PIN"
    say "ни одно из $i имён не подошло; вернул прежнее $PREV"
else
    rm -f "$PIN" 2>/dev/null
    say "ни одно из $i имён не подошло"
fi
exit 2
