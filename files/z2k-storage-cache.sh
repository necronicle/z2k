#!/bin/sh
# /opt/zapret2/z2k-storage-cache.sh — заставить ядро реально сбрасывать кэш
# накопителя, на котором живёт /opt.
#
# ЧТО ПРОИСХОДИТ БЕЗ ЭТОГО (измерено на KN, ядро 4.9-ndm-5, 2026-08-10):
#
#   sd 0:0:0:0: [sda] No Caching mode page found
#   sd 0:0:0:0: [sda] Assuming drive cache: write through
#   /sys/block/sda/queue/write_cache = write through
#
# USB-флешки массово не отдают SCSI caching mode page (usb-storage к тому же
# принудительно ставит skip_ms_page_8 для дисков). Не получив страницу, sd
# делает вывод «volatile write cache отсутствует» и переводит очередь в
# write through. В этом режиме блочный слой ЗАВЕРШАЕТ REQ_PREFLUSH/REQ_FUA, НЕ
# ОТПРАВЛЯЯ их устройству — сбрасывать, по его мнению, нечего.
#
# Кэш при этом у флешки есть, как у любой. Результат — худшее сочетание:
# jbd2 каждые пять секунд честно просит сброс перед фиксацией транзакции,
# сброс никуда не уходит, устройство свободно переставляет и теряет записи, а
# `mount` продолжает показывать data=ordered. Гарантии журнала при потере
# питания держатся именно на том, что барьер доходит до носителя; здесь он не
# доходит, и журнал перестаёт защищать хоть что-нибудь.
#
# ЧЕМ ЭТО ОБЕРНУЛОСЬ. Разбор «умершей» флешки 2026-08-10: полное чтение всех
# 8 ГБ без единой ошибки, износ исключён (190 МБ записей за жизнь), но реальная
# порча метаданных — потерянные блоки читаются сплошным 0xFF прогонами ровно по
# 16 КБ (гранулярность трансляции внутри флешки, не файловой системы), тогда
# как никогда не писавшиеся области читаются нулями. То есть блоки были
# записаны и утрачены при обрыве питания. Так умерла не одна флешка, а
# несколько подряд, на разных ОС форматирования — потому что причина не в
# форматировании, а в неработающем барьере.
#
# ЧТО ДЕЛАЕМ. Говорим ядру правду: кэш есть. После этого FLUSH/FUA начинают
# уходить на устройство, и журнал снова делает то, ради чего существует.
# Настройка живёт до перезагрузки и слетает при переподключении накопителя,
# поэтому её переставляет NDM-хук на события USB и старт сервиса.
#
# Если накопитель кэша действительно не имеет, лишние FLUSH он завершит сразу —
# вреда нет. Записи становятся медленнее ровно настолько, насколько раньше были
# небезопасными.

Z2K_SC_CONFIG="${Z2K_SC_CONFIG:-/opt/zapret2/config}"

# Пользователь может отключить: Z2K_STORAGE_WRITEBACK=0 в конфиге.
_z2k_sc_enabled() {
    [ -f "$Z2K_SC_CONFIG" ] || return 0
    [ "$(awk -F= '/^Z2K_STORAGE_WRITEBACK=/{gsub(/[" ]/,"",$2);print $2;exit}' \
         "$Z2K_SC_CONFIG" 2>/dev/null)" = "0" ] && return 1
    return 0
}

# Имя диска из имени раздела: /dev/sda1 -> sda, /dev/mmcblk0p1 -> mmcblk0.
# Вынесено отдельно, чтобы это можно было проверить тестом, не подсовывая
# фальшивый /proc/mounts.
z2k_sc_disk_from_src() {
    local src="$1" base
    case "$src" in
        /dev/*) ;;
        *) return 1 ;;
    esac
    base=${src#/dev/}
    case "$base" in
        mmcblk*|nvme*) base=${base%p[0-9]*} ;;
        *)             base=$(printf '%s' "$base" | sed 's/[0-9]*$//') ;;
    esac
    [ -n "$base" ] || return 1
    printf '%s' "$base"
}

# Имя блочного устройства (без раздела), на котором смонтирован /opt.
z2k_sc_opt_disk() {
    local src base
    src=$(awk '$2 == "/opt" { print $1; exit }' /proc/mounts 2>/dev/null)
    base=$(z2k_sc_disk_from_src "$src") || return 1
    [ -d "/sys/block/$base" ] || return 1
    printf '%s' "$base"
}

# Идемпотентно. 0 — режим уже нужный или переключили, 1 — не смогли.
z2k_sc_apply() {
    _z2k_sc_enabled || return 0

    local disk knob cur
    disk=$(z2k_sc_opt_disk) || return 0
    knob="/sys/block/$disk/queue/write_cache"

    # Ручка появилась в ядре 4.8. Её отсутствие — не ошибка, просто нечего делать.
    [ -w "$knob" ] || return 0

    cur=$(cat "$knob" 2>/dev/null)
    [ "$cur" = "write back" ] && return 0

    echo "write back" > "$knob" 2>/dev/null || return 1
    [ "$(cat "$knob" 2>/dev/null)" = "write back" ] || return 1
    return 0
}
