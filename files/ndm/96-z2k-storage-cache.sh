#!/bin/sh
# /opt/etc/ndm/usb.d/96-z2k-storage-cache.sh
#
# Keenetic NDM хук на события USB. Настройка политики кэша записи живёт в
# очереди блочного устройства и обнуляется при каждом переподключении
# накопителя — а переподключение случается и при перезагрузке, и при
# передёргивании порта. Поэтому её надо переставлять на каждом событии, а не
# один раз при установке.
#
# Зачем вообще — целиком описано в /opt/zapret2/z2k-storage-cache.sh: без этого
# ядро считает, что у флешки нет кэша записи, и барьеры журнала ext4 не
# доходят до носителя.
#
# Логика намеренно живёт в общей библиотеке, а не здесь: хук, старт сервиса и
# ручной вызов обязаны делать одно и то же. Функция идемпотентна и молча
# ничего не делает, если /opt не на блочном устройстве, ручки нет (ядро
# старше 4.8) или пользователь выключил Z2K_STORAGE_WRITEBACK=0.

export PATH=/opt/sbin:/opt/bin:/sbin:/usr/sbin:/bin:/usr/bin

LIB=/opt/zapret2/z2k-storage-cache.sh
[ -r "$LIB" ] || exit 0

# shellcheck disable=SC1090
. "$LIB"

z2k_sc_apply || true
exit 0
