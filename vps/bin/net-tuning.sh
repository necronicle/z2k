#!/bin/sh
# Разнос приёма пакетов по ядрам (RPS).
#
# ЗАЧЕМ. У vNIC этого узла ровно ОДНА очередь, и гипервизор больше не отдаёт:
# `ethtool -l ens3` показывает Combined max = 1. Прерывание virtio0-input.0
# приходит всегда на одно ядро — замер 31.08.2026: 2 460 901 571 на cpu0
# против 0 на cpu1. Значит весь приём, включая обработку SYN, шёл в один
# поток независимо от того, сколько воркеров крутится сверху.
#
# ЗАМЕР до/после (окна по 120 с, живой трафик):
#   было:  cpu0 9719 пак/с, cpu1 4630 пак/с   (68% / 32%)
#   стало: cpu0 7262 пак/с, cpu1 7276 пак/с   (50% / 50%)
#   softirq 7.13% / 7.55%; соединения на :443 не пострадали, дропов не добавилось.
#
# ПОЧЕМУ НЕ ЛОМАЕТ ПОРЯДОК ПАКЕТОВ: RPS раскладывает по хешу ПОТОКА, поэтому
# пакеты одного соединения всегда попадают на одно ядро.
#
# Настройка живёт в sysfs, а не в sysctl, и сбрасывается при перезагрузке —
# отсюда отдельный юнит.
set -e

IFACE="${1:-$(ip route show default 2>/dev/null | awk '/default/{print $5; exit}')}"
[ -n "$IFACE" ] || { echo "не определил внешний интерфейс" >&2; exit 1; }

# маска = все ядра
NCPU=$(nproc)
MASK=$(printf '%x' $(( (1 << NCPU) - 1 )))

n=0
for q in /sys/class/net/"$IFACE"/queues/rx-*; do
    [ -e "$q/rps_cpus" ] || continue
    echo "$MASK" > "$q/rps_cpus"
    # RFS: держать поток на том ядре, где его читает процесс.
    # Общий размер таблицы задан через net.core.rps_sock_flow_entries.
    [ -e "$q/rps_flow_cnt" ] && echo 16384 > "$q/rps_flow_cnt"
    n=$((n + 1))
done

echo "RPS: $IFACE, очередей $n, маска $MASK, ядер $NCPU"
