package main

import "testing"

// Правило одно: адрес, записанный в имени, берём из имени; всё остальное —
// как раньше, через резолвер. Ошибка в любую сторону дорогая: в одну — туннель
// снова умирает вместе с DNS, в другую — дозвон уходит не туда.
func TestRelayDialAddr(t *testing.T) {
	cases := []struct{ in, want string }{
		// боевой адрес релея — ради него всё и делается
		{"213.176.74.63.nip.io:443", "213.176.74.63:443"},
		{"213.176.74.63.nip.io:8443", "213.176.74.63:8443"},
		{"1.2.3.4.nip.io:80", "1.2.3.4:80"},
		// регистр и завершающая точка — то же имя
		{"213.176.74.63.NIP.IO:443", "213.176.74.63:443"},
		{"1.2.3.4.nip.io.:443", "1.2.3.4:443"},

		// НЕ трогаем: обычное имя обязано идти в резолвер
		{"relay.example.com:443", "relay.example.com:443"},
		{"nip.io:443", "nip.io:443"},
		{"api.nip.io:443", "api.nip.io:443"},
		// не IPv4 в метках
		{"1.2.3.999.nip.io:443", "1.2.3.999.nip.io:443"},
		{"a.b.c.d.nip.io:443", "a.b.c.d.nip.io:443"},
		// меток не четыре
		{"1.2.3.nip.io:443", "1.2.3.nip.io:443"},
		{"1.2.3.4.5.nip.io:443", "1.2.3.4.5.nip.io:443"},
		// дефисную форму сознательно не поддерживаем
		{"1-2-3-4.nip.io:443", "1-2-3-4.nip.io:443"},
		// уже литерал — оставляем как есть
		{"213.176.74.63:443", "213.176.74.63:443"},
		// битый вход не должен паниковать и не должен меняться
		{"нет-порта", "нет-порта"},
		{"", ""},
	}
	for _, c := range cases {
		if got := relayDialAddr(c.in); got != c.want {
			t.Errorf("relayDialAddr(%q) = %q, ожидалось %q", c.in, got, c.want)
		}
	}
}

// Имя для TLS обязано остаться прежним: сертификат выписан на <ip>.nip.io,
// и подмена адреса сокета не должна на него влиять. Здесь проверяем лишь то,
// что хелпер не трогает ничего, кроме адреса дозвона.
func TestRelayDialAddrKeepsPort(t *testing.T) {
	if got := relayDialAddr("213.176.74.63.nip.io:12345"); got != "213.176.74.63:12345" {
		t.Fatalf("порт не сохранён: %q", got)
	}
}
