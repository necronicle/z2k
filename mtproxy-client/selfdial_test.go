package main

import (
	"net"
	"testing"
)

// САМОНАБОР: соединение, пришедшее НА порт слушателя напрямую, а не через
// REDIRECT, отдаёт в SO_ORIGINAL_DST адрес самого сокета. Клиент честно просил
// релей набрать этот адрес — и получалась петля.
//
// Замер на VPS 26.08.2026, отказы релея «rejected non-Telegram» за три часа:
//
//	9504  37.193.146.91:1443   (WAN-адрес роутера, порт открыт наружу)
//	3379  192.168.1.1:1443     (LAN-адрес самого роутера)
//	1408  127.0.0.1:1443       (локальная петля)
//
// Все до единого — порт 1443, то есть наш собственный слушатель. Одна такая
// сессия давала две попытки в секунду круглосуточно, около 16 000 отказов в
// сутки — больше, чем все прочие источники вместе.
func TestSelfDialRejected(t *testing.T) {
	cases := []struct {
		name string
		ip   string
		port int
		want bool
	}{
		{"локальная петля", "127.0.0.1", 1443, true},
		{"LAN-адрес роутера", "192.168.1.1", 1443, true},
		{"WAN-адрес роутера", "37.193.146.91", 1443, true},
		{"чужой хост на нашем порту", "1.2.3.4", 1443, true},
		{"дата-центр телеграма", "149.154.167.51", 443, false},
		{"телеграм на нестандартном порту", "149.154.167.51", 8443, false},
		{"приватный адрес, но не наш порт", "192.168.1.5", 443, true}, // телеграм там не живёт
	}
	for _, c := range cases {
		got := isSelfDial(net.ParseIP(c.ip), c.port, 1443)
		if got != c.want {
			t.Errorf("%s (%s:%d): получили %v, ждали %v", c.name, c.ip, c.port, got, c.want)
		}
	}
}

// Порт слушателя берётся из настройки, а не вписан числом: у человека он может
// быть другим, и гвард обязан следовать за ним.
func TestSelfDialFollowsListenPort(t *testing.T) {
	// Адрес публичный намеренно: приватный отсекается ДРУГИМ правилом, и
	// проверка порта на нём ничего бы не показала.
	if !isSelfDial(net.ParseIP("149.154.167.51"), 9999, 9999) {
		t.Error("свой порт из настройки не распознан")
	}
	if isSelfDial(net.ParseIP("149.154.167.51"), 1443, 9999) {
		t.Error("чужой порт 1443 при своём 9999 засчитан как самонабор")
	}
}
