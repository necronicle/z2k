package main

import (
	"flag"
	"log"
	"math/rand"
	"strconv"
	"sync/atomic"
)

// Потолок одновременных сессий.
//
// ЗАЧЕМ. Потолка не было вовсе, и это давало худший из возможных отказов: при
// исчерпании памяти релей убивал OOM, и ложились ВСЕ туннели разом. С потолком
// плохо становится только тем, кто не поместился, а уже подключённые продолжают
// работать. Отказ при этом ЯВНЫЙ: клиент получает 503 и знает, когда прийти
// снова, вместо того чтобы гадать над оборванным соединением.
//
// ОТКУДА ЧИСЛО. Замер 31.08.2026 на живом узле: 1762 туннеля при RSS релея
// 601 МБ — 349 КБ на соединение. Пик за наблюдение 1767. При бюджете релея в
// 2 ГБ (узел имеет 3.9 ГБ, из них caddy держит ~360 МБ, остальное системе и
// nginx) потолок выходит около 6000 сессий: втрое выше наблюдаемого пика и
// заметно ниже, чем нужно для OOM.
//
// Ноль означает «без потолка» — на случай, если узел вырастет и число станет
// вредным; но умолчание именно числовое, потому что выключенная страховка не
// страхует ни от чего.
var (
	maxSessions = flag.Int("max-sessions", 6000,
		"потолок одновременных сессий (0 = без потолка); сверх него — 503 с Retry-After")
	liveSessions atomic.Int64
	refusedTotal atomic.Int64
)

// retryAfterSeconds — сколько ждать до повтора, С РАЗБРОСОМ.
//
// Разброс здесь не украшение. Отвергнутые клиенты — это уже сгустившаяся
// группа: их отвергли в одну и ту же секунду. Отдать им всем одинаковое время
// повтора значит назначить следующий всплеск ровно на эту секунду и получить
// тот же отказ, только периодический. Диапазон 30–90 с размазывает возврат.
func retryAfterSeconds() int {
	return 30 + rand.Intn(61)
}

// acquireSession занимает место. Второе значение — сколько секунд ждать, если
// места нет.
//
// Резервируем СРАЗУ и откатываем при отказе, а не проверяем-и-занимаем: между
// проверкой и занятием на двух ядрах помещается сколько угодно соединений, и
// потолок протекал бы ровно под нагрузкой, ради которой написан.
func acquireSession() (bool, int) {
	if *maxSessions <= 0 {
		liveSessions.Add(1)
		return true, 0
	}
	if n := liveSessions.Add(1); n > int64(*maxSessions) {
		liveSessions.Add(-1)
		// Логируем первый отказ и дальше каждый сотый: под потолком отказы
		// идут потоком, и построчный лог сам станет нагрузкой.
		if r := refusedTotal.Add(1); r == 1 || r%100 == 0 {
			log.Printf("потолок сессий %d исчерпан, отказов всего %d", *maxSessions, r)
		}
		return false, retryAfterSeconds()
	}
	return true, 0
}

func releaseSession() {
	liveSessions.Add(-1)
}

// retryAfterHeader — значение заголовка Retry-After в секундах.
func retryAfterHeader(sec int) string { return strconv.Itoa(sec) }
